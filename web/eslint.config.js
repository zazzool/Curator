// Разборщик стиля у студии.
//
// # Зачем он, если есть разбор типов
//
// Разбор типов не видит доступности: `<div onClick=…>` для него безупречен,
// а для читающего с экрана это не кнопка вовсе — её нет ни в обходе по
// клавише, ни в списке действий. Половина находок аудита по доступности —
// ровно то, что `jsx-a11y` ловит без участия человека, и ловит на каждом
// прогоне, а не раз в квартал.
//
// # Почему правил немного и почему именно эти
//
// Набор выбран так, чтобы КАЖДОЕ правило отвечало на вопрос «что сломается
// у человека»: доступность и крючки React. Общестилевые правила сюда не
// берутся: где ставить запятую, решает не разборщик, а согласие в коде, и
// сотня замечаний про пробелы превращает красный разбор в фоновый шум,
// который перестают читать вместе с настоящими находками.
import js from '@eslint/js'
import tseslint from 'typescript-eslint'
import a11y from 'eslint-plugin-jsx-a11y'
import hooks from 'eslint-plugin-react-hooks'

export default tseslint.config(
  { ignores: ['dist/**', 'node_modules/**'] },
  js.configs.recommended,
  ...tseslint.configs.recommended,
  {
    files: ['src/**/*.{ts,tsx}'],
    plugins: { 'jsx-a11y': a11y, 'react-hooks': hooks },
    rules: {
      ...a11y.configs.recommended.rules,
      // Крючки: зависимости чтения и вечный круг запросов.
      //
      // Куплено замером, а не осторожностью: чтение, меняющееся на каждой
      // отрисовке, уводит экран в вечный круг обращений, и признак у
      // этого отказа никакой — страница просто «долго думает», а сервер
      // получает сотню запросов в секунду.
      'react-hooks/rules-of-hooks': 'error',
      'react-hooks/exhaustive-deps': 'error',
      // Заведённое и ни разу не позванное.
      //
      // Это не уборка: за аудит нашлось три таких места, и каждое —
      // защита, которой нет. Уборщик снимков, написанный и не позванный,
      // выглядел работающим ровно до дня, когда снимки понадобились.
      // Доводы, начинающиеся с подчёркивания, пропускаются: это способ
      // сказать «знаю, не нужен» вслух.
      '@typescript-eslint/no-unused-vars': [
        'error',
        { argsIgnorePattern: '^_', varsIgnorePattern: '^_' },
      ],
    },
  },
)
