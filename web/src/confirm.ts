/// Спросить человека, прежде чем сделать необратимое.
///
/// # Почему одно место, а не `window.confirm` по месту
///
/// Девять необратимых действий студии не спрашивали ничего: возврат денег,
/// закрытие входа врачу и сотруднику, закрытие ключа программы, по
/// которому ходят уже поставленные сборки, снятие задачи с раздачи, снятие
/// источника, выпуск набора. Кнопки у них выглядели ровно как «Открыть».
///
/// Собрано это в одно место не ради краткости — вопросов всё равно девять
/// разных, — а ради того, чтобы вопрос нельзя было задать плохо. Хороший
/// вопрос называет ПРЕДМЕТ и ПОСЛЕДСТВИЕ: «Вернуть платёж № 41 на 1990 ₽?
/// Право по нему будет отозвано». Плохой спрашивает «Вы уверены?» — на
/// него человек отвечает «да» не читая, и подтверждение перестаёт
/// подтверждать что-либо уже на второй неделе.
///
/// # Почему `window.confirm`, а не своё окно
///
/// Так у донора, и новой зависимости это не требует. Своё окно — это
/// состояние, перехват клавиш, возврат внимания на кнопку и ловушка
/// фокуса; всё это пишется ради того, что браузер уже умеет, и пишется
/// один раз на девять мест. Когда окна понадобятся по делу — например,
/// чтобы спросить причину возврата, — они появятся здесь же.
export function confirmed(subject: string, consequence: string): boolean {
  // Предмет и последствие разными доводами, а не одной строкой: строку
  // пишущий склеит как придётся, и половина вопросов останется без
  // последствия — то есть без того, ради чего вопрос и задаётся.
  return window.confirm(`${subject}\n\n${consequence}`)
}

/// Спросить строку, без которой действие не оформляется.
///
/// Возврат денег — единственное действие, которое потом разбирают, и
/// разбирают по одному полю: чем он объяснён. До 20.09.2026 в это поле
/// вписывалось «возврат оформлен в студии» — одинаково для всех возвратов,
/// какие когда-либо будут. У приёма прихода поле «Чем подтверждён» есть, и
/// у возврата оно нужнее.
///
/// Пустой ответ и отказ — одно и то же: возврат без причины и есть тот
/// возврат, который потом нечем объяснить.
export function askReason(subject: string, hint: string): string | null {
  const said = window.prompt(`${subject}\n\n${hint}`)
  if (said === null) return null
  const trimmed = said.trim()
  return trimmed === '' ? null : trimmed
}
