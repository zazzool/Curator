import { cleanup } from '@testing-library/react'
import { afterEach, beforeEach, vi } from 'vitest'

// Разобранное дерево убирается между проверками: иначе вторая проверка
// находит узел, нарисованный первой, и падает там, где всё исправно.
afterEach(cleanup)

// Подтверждения у необратимых действий: по умолчанию оператор соглашается.
//
// В jsdom `confirm` и `prompt` не написаны вовсе и бросают «not
// implemented» — то есть без подмены каждая проверка, доходящая до
// необратимого действия, падает не по делу. Умолчание выбрано «да»
// потому, что проверок про сам ход действия много, а про отказ от него —
// ровно столько, сколько нужно, и они подменяют это сами.
//
// Умолчание НЕ прячет пропавшее подтверждение: проверки на отказ зовут
// действие при `confirm`, отвечающем «нет», и ждут, что до сервера оно не
// дошло. Снимите подтверждение — и они покраснеют.
beforeEach(() => {
  vi.stubGlobal('confirm', vi.fn(() => true))
  vi.stubGlobal('prompt', vi.fn(() => 'причина из проверки'))
})
