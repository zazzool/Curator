/**
 * Единица источника во множественном числе.
 *
 * Слово выбирает составитель при заведении источника — «пункт», «статья»,
 * «рубрика», — и показать вместо него «единицу» значит заговорить с ним
 * на языке базы. Слова у источника может не быть вовсе: у ввезённого
 * своим порядком его никто не задавал, и тогда «единицы» честнее
 * выдуманного окончания.
 */
export function словарём(unitWord: string): string {
  return unitWord === '' ? 'единицы' : `${unitWord}ы`
}
