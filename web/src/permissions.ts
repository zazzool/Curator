// Права студии словами, понятными человеку.
//
// Это второе место для закрытого словаря сервера, и потому оно сверяется:
// проверка сервера читает этот файл и падает, если список разошёлся
// (`server/internal/studio/permissions_mirror_test.go`). Без сверки
// расхождение было бы молчаливым — право, забытое здесь, просто нельзя
// было бы выдать, и искали бы причину в маршруте.
//
// Порядок повторяет серверный: человек ищет право глазами по привычному
// месту, и переставлять их местами без нужды не надо.
export const ПРАВА: { code: string; title: string; about: string }[] = [
  { code: 'source:read', title: 'читать источники', about: 'видеть источники и их разбор' },
  { code: 'source:accept', title: 'принимать разбор', about: 'решать, что теперь истина источника' },
  { code: 'case:read', title: 'читать задачи', about: 'видеть задачи и их разметку' },
  { code: 'case:write', title: 'править задачи', about: 'менять условие, ответы и разбор' },
  { code: 'generate', title: 'запускать генерацию', about: 'ставить задания на конвейер' },
  { code: 'prompts', title: 'задания моделям', about: 'править то, чем модель пишет задачи' },
  { code: 'packs', title: 'наборы задач', about: 'собирать наборы и выпускать их' },
  { code: 'clients', title: 'клиенты', about: 'карточка врача, платежи и права' },
  { code: 'sales', title: 'продажи', about: 'цены и оформление прихода' },
  { code: 'analytics', title: 'отчёты', about: 'что решают и на чём спотыкаются' },
  { code: 'workshop', title: 'мастерская', about: 'пользователи студии и ключи программ' },
]

/** Название права словами. Незнакомый код показывается как есть: он
 *  остался от прежней редакции, и подменять его «неизвестно чем» значит
 *  скрыть от человека то, что у кого-то записано в базе. */
export function правоСловами(code: string): string {
  return ПРАВА.find((one) => one.code === code)?.title ?? code
}

/** Права строкой, какой её читают глазами в списке.
 *
 *  Полный набор сворачивается в «все права» намеренно: перечисленный
 *  целиком, он занимает две строки и у каждого такого человека одинаков —
 *  список превращается в стену, по которой не видно, чем люди
 *  отличаются, а это единственное, ради чего на него смотрят. */
export function праваСловами(codes: string[]): string {
  if (codes.length === 0) return 'прав нет: войти сможет, а разделов не увидит'
  if (ПРАВА.every((one) => codes.includes(one.code))) return 'все права'
  return codes.map(правоСловами).join(', ')
}
