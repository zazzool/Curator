/**
 * Иконки интерфейса.
 *
 * Все из одного набора — Lucide (лицензия ISC, свободная): контурные,
 * сетка 24×24, перо 2 px. Единство набора здесь не эстетство: смешанные
 * семейства — часть обводкой, часть заливкой — читаются как случайный
 * набор картинок, а не как система обозначений.
 *
 * **Зачем зависимость.** Без неё пришлось бы перерисовывать чужие
 * контуры руками: вторая, расходящаяся копия тех же рисунков — ровно то,
 * от чего правило о зависимостях и бережёт. Набор тот же, что у донора,
 * и это условие задачи: два студийных интерфейса, обозначающие одно и то
 * же разными рисунками, читаются как две разные системы.
 *
 * Имена свои, а не взятые из набора: «workshop» может сменить рисунок, не
 * трогая мест употребления. Сопоставление имени и рисунка — в одном
 * месте, в GLYPHS.
 */

import {
  BookOpen,
  ChartLine,
  Files,
  Hammer,
  LogOut,
  Users,
  Wallet,
  Wrench,
  type LucideIcon,
} from 'lucide-react'

export type IconName =
  | 'source'
  | 'drafts'
  | 'money'
  | 'people'
  | 'analytics'
  | 'workshop'
  | 'manage'
  | 'logout'

const GLYPHS: Record<IconName, LucideIcon> = {
  // Раскрытая книга: источник — первоисточник положений, то есть книга.
  source: BookOpen,
  // Стопка листов: набор — это перечень задач, а не одна задача.
  drafts: Files,
  // Кошелёк: раздел про деньги, а не про доли и не про диаграммы. Знак
  // должен читаться с одного взгляда — рядом с ним стоит сумма.
  money: Wallet,
  // Двое: группа — это про многих врачей сразу, а не про одного. Знак с
  // одной фигурой читался бы как «карточка врача», которая живёт в
  // «Продажах» и означает ровно обратное.
  people: Users,
  // Линия тренда: раздел про то, как показатели движутся во времени.
  analytics: ChartLine,
  // Молоток: мастерская — работа над самой установкой, а не над задачами.
  workshop: Hammer,
  // Гаечный ключ: сворачивание колонки — обслуживание самого окна.
  manage: Wrench,
  logout: LogOut,
}

export function Icon({
  name,
  size,
  className,
}: {
  name: IconName
  size?: number
  className?: string
}) {
  const Glyph = GLYPHS[name]
  return (
    <Glyph
      className={['icon', className].filter(Boolean).join(' ')}
      style={size ? { width: size, height: size } : undefined}
      strokeWidth={2}
      // Иконка сопровождает подпись и сама ничего не сообщает: для чтения
      // с экрана она шум.
      aria-hidden="true"
      focusable="false"
    />
  )
}
