import { Component, type ErrorInfo, type ReactNode } from 'react'

/**
 * Граница отказа вокруг рабочей области.
 *
 * React снимает ВСЁ дерево, когда отрисовка бросает, и белый экран
 * получается не в той панели, где беда, а во всей студии: пропадают и
 * колонка разделов, и имя вошедшего, и доступ к другим экранам. Между тем
 * бросить здесь есть чему: тела задач и черновиков пишет языковая модель,
 * и объявленные обязательными поля она может не написать.
 *
 * Граница не чинит кривую задачу и не должна: она удерживает отказ в
 * границах панели, чтобы составитель мог уйти на другой экран, а не
 * перезагружать вкладку, теряя набранное.
 *
 * Классом, а не обычной работой: другого способа поймать отказ отрисовки
 * в React нет — перехватчики живут только у классов.
 *
 * Сброс при переходе делается ключом снаружи, а не способом внутри:
 * сменившийся ключ строит границу заново, и упавшее состояние уходит
 * вместе со старой. Способ «вернись в рабочее» пришлось бы звать из
 * каждого места перехода, и первое же забытое оставило бы отказ висеть
 * на исправном экране.
 */
export class ErrorBoundary extends Component<
  { children: ReactNode },
  { failed: boolean }
> {
  constructor(props: { children: ReactNode }) {
    super(props)
    this.state = { failed: false }
  }

  static getDerivedStateFromError(): { failed: boolean } {
    return { failed: true }
  }

  componentDidCatch(error: Error, info: ErrorInfo): void {
    // В консоль, а не человеку: составителю нужен выход, а разбирающему
    // отказ нужен стек. Показанный стек не даёт ни того, ни другого.
    console.error('Экран упал:', error, info.componentStack)
  }

  render(): ReactNode {
    if (!this.state.failed) return this.props.children
    return (
      <div className="stack">
        <p className="banner error" role="alert">
          Этот экран не отрисовался. Похоже, задача или черновик записаны
          не полностью — такое бывает с написанным моделью.
        </p>
        <p className="hint">
          Остальная студия работает: перейдите в другой раздел и
          вернитесь. Если повторится, скажите об этом — по записи в
          журнале браузера видно, где именно.
        </p>
        <button onClick={() => this.setState({ failed: false })}>
          Показать ещё раз
        </button>
      </div>
    )
  }
}
