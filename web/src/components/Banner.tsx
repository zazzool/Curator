import type { ReactNode } from 'react'

/**
 * Полоса отказа, успеха или предупреждения.
 *
 * # Почему компонент, а не `<p className="banner error">` по месту
 *
 * Полос в студии было больше двадцати, и ни одна из них не объявлялась
 * читающему с экрана: `role="alert"` стоял ровно в одном месте — на форме
 * входа. Составитель, работающий с экранным диктором, жал «Раздавать»,
 * публикация отклонялась с четырьмя замечаниями, **не говорилось ничего**,
 * и фокус оставался на кнопке. С его стороны нажатие не сделало ничего, и
 * он жал снова.
 *
 * Собрано в одно место затем, чтобы объявление нельзя было забыть: пишущий
 * новую полосу выбирает её вид, а не её роль.
 *
 * # Почему у отказа `alert`, а у успеха `status`
 *
 * `alert` перебивает диктора на полуслове — это верно для того, что
 * остановило работу, и неверно для «Карточка сохранена»: перебитый на
 * каждое удачное действие человек выключает диктор. `status` дожидается
 * паузы и говорит то же самое, не мешая.
 */
export function Banner({
  kind,
  children,
  id,
}: {
  kind: 'error' | 'success' | 'warning' | 'info'
  children: ReactNode
  /** Нужен там, где на полосу ссылается `aria-describedby` поля. */
  id?: string
}) {
  return (
    <p
      className={`banner ${kind}`}
      id={id}
      role={kind === 'error' ? 'alert' : 'status'}
    >
      {children}
    </p>
  )
}
