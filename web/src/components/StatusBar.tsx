import type { ReactNode } from 'react'

/**
 * Строка состояния внизу окна.
 *
 * То же, что строка состояния в редакторе кода: сведения, которые нужны
 * постоянно и не нужны ни секунды внимания. Здесь ничего нельзя нажать —
 * это ответ, а не орган управления.
 *
 * Кто вошёл и что ему позволено, стояло здесь до 20.09.2026 — довод был
 * тот, что вторая строка ради одного имени отняла бы у страницы место.
 * Довод не выдержал сверки с донором: там личность живёт отдельной
 * строкой в самой рабочей области, и владелец потребовал донорского
 * устройства. Теперь это `IdentityBar`, а полоса ждёт своих сведений —
 * тех, что зависят от открытого экрана (у донора это состояние задачи и
 * счёт рабочего списка). Пока их нет, полоса пуста и потому не видна.
 *
 * Пустая полоса — это чистая рамка у нижнего края: ни слова, ни числа,
 * только линия. Прятать её проверкой аргументов нельзя — ячейки приходят
 * сюда узлом, а пусто ли у них внутри, решают они сами уже при
 * отрисовке. Поэтому прячет её правило в разметке
 * (`.status-bar:not(:has(…))`), которому видно уже отрисованное.
 */
export function StatusBar({ cells }: { cells?: ReactNode }) {
  return (
    <footer className="status-bar" aria-label="Состояние">
      <div className="status-cells">{cells}</div>
    </footer>
  )
}
