import type { ReactNode } from 'react'

/**
 * Строка состояния внизу окна.
 *
 * То же, что строка состояния в редакторе кода: сведения, которые нужны
 * постоянно и не нужны ни секунды внимания. Здесь ничего нельзя нажать —
 * это ответ, а не орган управления.
 *
 * Что в ней стоит у Куратора: кто вошёл и что ему позволено. У донора то
 * же самое вынесено отдельной строкой личности под верхней полосой,
 * потому что там она бывает ещё и плашкой режима «оператор от имени» —
 * работа от чужого имени без видимого признака это подпись под чужим
 * именем. Такого режима здесь нет вовсе, и вторая строка ради одного
 * имени отняла бы у страницы место, ничего не сказав сверх этой.
 *
 * Пустая полоса — это чистая рамка у нижнего края: ни слова, ни числа,
 * только линия. Прятать её проверкой аргументов нельзя — ячейки приходят
 * сюда узлом, а пусто ли у них внутри, решают они сами уже при
 * отрисовке. Поэтому прячет её правило в разметке
 * (`.status-bar:not(:has(…))`), которому видно уже отрисованное.
 */
export function StatusBar({ cells }: { cells?: ReactNode }) {
  return (
    <footer className="status-bar" aria-label="Состояние">
      <div className="status-cells">{cells}</div>
    </footer>
  )
}

/**
 * Кто вошёл и что ему позволено.
 *
 * Права названы словами и числом сразу: число отвечает «сколько их», а
 * всплывающая подсказка — «какие именно». Перечислить их в строке нельзя,
 * их бывает с десяток, а строка состояния не место для перечня.
 */
export function WhoCells({ who, permissions }: { who: string; permissions: string[] }) {
  return (
    <>
      <span className="status-cell">{who}</span>
      <span className="status-cell muted-cell" title={permissions.join(', ')}>
        {permissions.length === 0 ? 'без прав' : `прав: ${permissions.length}`}
      </span>
    </>
  )
}
