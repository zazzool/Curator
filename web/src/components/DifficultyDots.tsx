/**
 * Сложность задачи точками — как в приложении и у донора.
 *
 * Точек четыре: шкала видна целиком, и «три из четырёх» отличимо от
 * потолка. Спокойнее звёзд и не тянет на себя внимание в столбце, где
 * рядом стоят название и состояние.
 *
 * **Уровень сказан словами, а не только геометрией.** Четыре кружка по
 * шесть пикселей в дерево доступности не попадают вовсе: без подписи
 * читающему с экрана достаётся заголовок столбца и ничего больше, то есть
 * разницы между «простая» и «на пределе» у него нет. Ровно эту ошибку уже
 * разбирали в приложении (`app/lib/core/ui/difficulty_dots.dart`), и
 * повторять её здесь незачем.
 *
 * Ноль — это «сложность не назвали», а не «самая простая»: у задачи,
 * написанной без уровня, четыре пустых кружка врали бы о том, что кто-то
 * её оценил.
 */
export function DifficultyDots({ level, max = 4 }: { level: number; max?: number }) {
  if (level <= 0) return <span className="muted">—</span>

  return (
    <span className="dots" role="img" aria-label={`сложность ${level} из ${max}`}>
      {Array.from({ length: max }, (_, i) => (
        <span key={i} className={i < level ? 'dot dot-on' : 'dot'} aria-hidden="true" />
      ))}
    </span>
  )
}
