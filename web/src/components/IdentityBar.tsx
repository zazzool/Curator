/**
 * Строка личности: кто вошёл и что ему позволено.
 *
 * Стоит первой строкой рабочей области, как у донора, и по донорскому же
 * доводу: «кто я» нужно на любом экране, включая экран отказа, а заголовок
 * раздела уезжает вверх с первой прокруткой.
 *
 * У донора рядом с именем стоит вход в профиль, а сама строка бывает ещё и
 * плашкой режима «оператор от имени» — работа от чужого имени без видимого
 * признака это подпись под чужим именем. Ни профиля, ни такого режима в
 * Кураторе нет, и выдумывать их ради сходства нельзя; поэтому правый край
 * занимает то, что здесь действительно отвечает на вопрос «а что мне
 * позволено».
 *
 * Права названы числом, а не перечнем: их бывает с десяток, и строка для
 * перечня не место. Какие именно — говорит всплывающая подсказка.
 */
export function IdentityBar({ who, permissions }: { who: string; permissions: string[] }) {
  return (
    <div className="identity-bar">
      <span>{who}</span>
      <span title={permissions.join(', ')}>
        {permissions.length === 0 ? 'без прав' : `прав: ${permissions.length}`}
      </span>
    </div>
  )
}
