import { sectionTitle, type SectionId } from '../sections'
import { Icon } from './Icon'

/**
 * Верхняя полоса.
 *
 * Навигации здесь нет намеренно: разделы живут в колонке слева. Полосе
 * осталось общее — где мы сейчас и выход.
 *
 * «Где мы сейчас» не заменяет заголовок раздела: тот стоит внутри
 * страницы и уезжает с прокруткой, а эта строка остаётся на месте и
 * отвечает на вопрос «куда я попал» тогда, когда колонка свёрнута в
 * полосу значков.
 *
 * Имя раздела берётся из того же перечня, что и колонка: две редакции
 * имён разошлись бы молча.
 *
 * # Почему заголовок первого уровня именно здесь
 *
 * `<h1>` не встречался в студии ни разу, а читающий с экрана начинает
 * работу с него: «где я» он спрашивает у заголовков, а не у цвета полосы.
 * Ставить его внутри страницы нельзя — страниц в разделе бывает
 * несколько (список источников, экран источника, карточка набора), и у
 * каждой получился бы свой первый уровень при одном и том же разделе.
 * Полоса же одна на всю рабочую область и меняется ровно тогда, когда
 * меняется «где я».
 */
export function Toolbar({
  section,
  crumb,
  onSignOut,
}: {
  section: SectionId
  /** Что открыто внутри раздела: название источника, имя набора. */
  crumb?: string
  onSignOut: () => void
}) {
  return (
    <header className="app-bar">
      <h1 className="app-bar-here">
        <span>{sectionTitle(section)}</span>
        {crumb && <span className="app-bar-crumb">· {crumb}</span>}
      </h1>

      <button
        type="button"
        className="bar-button app-bar-exit"
        onClick={onSignOut}
        title="Выйти"
        aria-label="Выйти"
      >
        <Icon name="logout" size={15} />
      </button>
    </header>
  )
}
