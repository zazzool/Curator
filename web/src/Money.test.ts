import { describe, expect, it } from 'vitest'

import { рублями, вКопейки } from './Money'

describe('деньги', () => {
  it('копейки показываются рублями с копейками', () => {
    expect(рублями(199000)).toBe('1 990,00 ₽')
    expect(рублями(5)).toBe('0,05 ₽')
    expect(рублями(123456789)).toBe('1 234 567,89 ₽')
  })

  it('набранное рублями переводится в копейки', () => {
    expect(вКопейки('1990')).toBe(199000)
    expect(вКопейки('1990,50')).toBe(199050)
    expect(вКопейки('1990.5')).toBe(199050)
    expect(вКопейки(' 1 990 ')).toBe(199000)
  })

  it('негодная сумма отказывает, а не считается нулём', () => {
    // «1990» и «19,90» различаются в сто раз, и приход, оформленный на
    // сотую долю суммы, обнаружится не сегодня. Молчаливый ноль здесь
    // хуже отказа.
    expect(вКопейки('')).toBeNull()
    expect(вКопейки('тысяча')).toBeNull()
    expect(вКопейки('19,905')).toBeNull()
    expect(вКопейки('-100')).toBeNull()
  })
})
