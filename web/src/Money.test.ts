import { describe, expect, it } from 'vitest'

import { рублями, вКопейки, долларами } from './Money'

describe('деньги', () => {
  it('копейки показываются рублями с копейками', () => {
    expect(рублями(199000)).toBe('1 990,00 ₽')
    expect(рублями(5)).toBe('0,05 ₽')
    expect(рублями(123456789)).toBe('1 234 567,89 ₽')
  })

  it('набранное рублями переводится в копейки', () => {
    expect(вКопейки('1990')).toBe(199000)
    expect(вКопейки('1990,50')).toBe(199050)
    expect(вКопейки('1990.5')).toBe(199050)
    expect(вКопейки(' 1 990 ')).toBe(199000)
  })

  it('негодная сумма отказывает, а не считается нулём', () => {
    // «1990» и «19,90» различаются в сто раз, и приход, оформленный на
    // сотую долю суммы, обнаружится не сегодня. Молчаливый ноль здесь
    // хуже отказа.
    expect(вКопейки('')).toBeNull()
    expect(вКопейки('тысяча')).toBeNull()
    expect(вКопейки('19,905')).toBeNull()
    expect(вКопейки('-100')).toBeNull()
  })
})

describe('нанодоллары к показу', () => {
  it('тысячные доли цента не округляются до нуля', () => {
    // Одно обращение к модели стоит тысячные доли цента. Округлённое до
    // цента, оно показалось бы бесплатным — и решали бы по этому числу,
    // где менять модель.
    expect(долларами(3_200_000)).toBe('$0,0032')
    expect(долларами(1_000_000_000)).toBe('$1,0000')
  })

  it('слишком мелкое названо «менее», а не нулём', () => {
    // Ноль читается как «бесплатно»: узел, о цене которого просто нечего
    // сказать, выглядел бы даровым.
    expect(долларами(50_000)).toBe('менее $0,0001')
  })

  it('ровный ноль остаётся нулём', () => {
    // Ноль означает, что обращений не было вовсе, и «менее» о
    // несуществующем расходе сказать нельзя.
    expect(долларами(0)).toBe('$0')
  })
})
