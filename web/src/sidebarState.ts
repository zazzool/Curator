/**
 * Свёрнута ли боковая колонка — между заходами.
 *
 * В браузере, а не на сервере: это свойство рабочего места, а не учётной
 * записи. Один и тот же составитель за широким монитором и за ноутбуком
 * хочет разного, и сервер, помнящий одно на двоих, сворачивал бы колонку
 * там, где места хватает.
 *
 * Запись обёрнута в try: в приватном окне и при запрете хранилища
 * localStorage бросает на самой записи, и незакрытый отказ уронил бы
 * колонку — то есть навигацию целиком — ради настройки, без которой можно
 * жить.
 */

const KEY = 'curator.sidebar.collapsed'

export function readSidebarCollapsed(): boolean {
  try {
    return localStorage.getItem(KEY) === '1'
  } catch {
    return false
  }
}

export function writeSidebarCollapsed(collapsed: boolean): void {
  try {
    localStorage.setItem(KEY, collapsed ? '1' : '0')
  } catch {
    // Молчим намеренно: несохранённое положение колонки — не повод
    // объясняться с врачом.
  }
}
