import { go } from './router'

/**
 * Адрес, которого у студии нет.
 *
 * Страница завелась вместе с адресами, и не «на всякий случай». Сервер
 * теперь отдаёт студию на любой путь — без этого прямая ссылка на источник
 * не открылась бы вовсе, — и всякая опечатка в адресе доезжает сюда.
 * Подставить на неё список источников значит соврать: человек решит, что
 * попал куда хотел, и будет искать пропавшее в разделе, которого не
 * открывал.
 *
 * Адрес показывается как есть, потому что чаще всего он и есть ответ:
 * ошибку видно глазом — лишняя буква, съеденная косая черта, номер
 * источника, приехавший вместе со скобкой из письма.
 */
export function NotFound({ path }: { path: string }) {
  return (
    <div>
      <div className="page-head">
        <h2>Такой страницы в студии нет</h2>
      </div>
      <p className="hint">
        Адрес <span className="mono">{path}</span> ни одному разделу не
        принадлежит. Проверьте ссылку — в неё легко попадает лишний знак из
        письма.
      </p>
      {/* Выход со страницы даётся здесь же: попавший на неё пришёл
          работать, и отправлять его глазами в колонку разделов незачем. */}
      <div className="page-section">
        <div className="toolbar" style={{ justifyContent: 'center' }}>
          <button className="primary" onClick={() => go({ name: 'sources' })}>
            К источникам
          </button>
        </div>
      </div>
    </div>
  )
}
