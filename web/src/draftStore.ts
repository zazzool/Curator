/**
 * Черновик несохранённой правки — в браузере.
 *
 * Токен студии живёт только в памяти страницы, а значит F5 по привычке,
 * уснувший ноутбук, выгруженная браузером вкладка и истёкшая сессия — всё
 * это одно и то же событие: набранное исчезает. Методист переписывает
 * задание модели сорок минут, три тысячи знаков выверенных клинических
 * указаний; терять их из-за нажатия Ctrl-R нельзя.
 *
 * Слой здесь один — браузерный, и этого довольно для беды, ради которой
 * он заведён: она случается между двумя сохранениями, на этой же машине и
 * в этом же браузере. Серверного слоя намеренно нет: он потребовал бы
 * своей ручки, своей таблицы и решения, чей черновик старше при двух
 * открытых вкладках, — а закрывает он другую беду (переезд на другую
 * машину), которой у составителя за работой не бывает.
 *
 * Всякое обращение к хранилищу обёрнуто: в приватном окне и при запрете
 * данных сайта localStorage бросает на самом обращении, и незакрытый
 * отказ уронил бы редактор — то есть работу целиком — ради удобства, без
 * которого можно жить. Тот же довод и то же устройство, что у
 * `sidebarState.ts`.
 */

const PREFIX = 'curator.draft.'

export interface StoredDraft<T> {
  /** Само набранное. */
  value: T
  /**
   * На какой редакции оно набрано. Черновик, набранный на редакции, от
   * которой сервер уже ушёл, восстанавливать нельзя: человек дописал бы
   * поверх чужой правки, не увидев её.
   */
  revision: number
  /** Когда записан — показывается при восстановлении. */
  savedAt: string
}

export function readDraft<T>(key: string): StoredDraft<T> | null {
  try {
    const raw = localStorage.getItem(PREFIX + key)
    if (!raw) return null
    const parsed = JSON.parse(raw) as StoredDraft<T>
    // Непонятое не применяется: испорченная запись отбрасывается целиком,
    // а не подставляется по кускам. Подставленный наполовину черновик
    // человек примет за свой и сохранит поверх целого.
    if (parsed === null || typeof parsed !== 'object') return null
    if (typeof parsed.revision !== 'number' || parsed.value === undefined) return null
    return parsed
  } catch {
    return null
  }
}

export function writeDraft<T>(key: string, value: T, revision: number): void {
  try {
    const stored: StoredDraft<T> = {
      value,
      revision,
      savedAt: new Date().toISOString(),
    }
    localStorage.setItem(PREFIX + key, JSON.stringify(stored))
  } catch {
    // Молчим намеренно: незаписанный черновик — не повод прерывать
    // работу, ради которой он ведётся.
  }
}

export function dropDraft(key: string): void {
  try {
    localStorage.removeItem(PREFIX + key)
  } catch {
    // См. выше.
  }
}
