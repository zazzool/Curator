// Деньги в студии.
//
// Две валюты не смешиваются: расход на модели считается в долларах, а
// выручка и цены — в рублях. Здесь только рубли, и хранятся они копейками
// целым числом. Рубль с копейками, приехавший дробным числом, теряет
// копейку на первом же переводе в двоичную дробь, и сумма за месяц после
// этого не сходится ни с чьим счётом.

/** Копейки к показу: «1 990,00 ₽». */
export function рублями(kopecks: number): string {
  const знак = kopecks < 0 ? '−' : ''
  const целых = Math.trunc(Math.abs(kopecks) / 100)
  const копеек = Math.abs(kopecks) % 100
  const разряды = String(целых).replace(/\B(?=(\d{3})+(?!\d))/g, ' ')
  return `${знак}${разряды},${String(копеек).padStart(2, '0')} ₽`
}

/**
 * Набранные человеком рубли в копейки.
 *
 * Отказ, а не молчаливый ноль: «1990» и «19,90» различаются сотней раз, и
 * приход, оформленный на сотую долю суммы, обнаружится не сегодня.
 */
export function вКопейки(raw: string): number | null {
  const чистое = raw.trim().replace(/\s/g, '').replace(',', '.')
  if (!/^\d+(\.\d{1,2})?$/.test(чистое)) return null
  const [рубли, копейки = ''] = чистое.split('.')
  return Number(рубли) * 100 + Number(копейки.padEnd(2, '0'))
}
