// Деньги в студии.
//
// Две валюты не смешиваются: расход на модели считается в долларах, а
// выручка и цены — в рублях. Рубли хранятся копейками целым числом,
// доллары — нанодолларами: и то, и другое приехавшее дробным теряет
// разряд на первом же переводе в двоичную дробь, и сумма за месяц после
// этого не сходится ни с чьим счётом.
//
// Обе живут в одном файле, но НЕ смешиваются: своя функция показа у
// каждой, и перевода между ними здесь нет вовсе. Перевод делается при
// показе сводки, по курсу дня, и остаётся видимым как перевод —
// записанный в строку курс дня потерян безвозвратно.

/** Копейки к показу: «1 990,00 ₽». */
export function рублями(kopecks: number): string {
  const знак = kopecks < 0 ? '−' : ''
  const целых = Math.trunc(Math.abs(kopecks) / 100)
  const копеек = Math.abs(kopecks) % 100
  const разряды = String(целых).replace(/\B(?=(\d{3})+(?!\d))/g, ' ')
  return `${знак}${разряды},${String(копеек).padStart(2, '0')} ₽`
}

/**
 * Набранные человеком рубли в копейки.
 *
 * Отказ, а не молчаливый ноль: «1990» и «19,90» различаются сотней раз, и
 * приход, оформленный на сотую долю суммы, обнаружится не сегодня.
 */
export function вКопейки(raw: string): number | null {
  const чистое = raw.trim().replace(/\s/g, '').replace(',', '.')
  if (!/^\d+(\.\d{1,2})?$/.test(чистое)) return null
  const [рубли, копейки = ''] = чистое.split('.')
  return Number(рубли) * 100 + Number(копейки.padEnd(2, '0'))
}

/**
 * Нанодоллары к показу: «$0,0032».
 *
 * Четыре знака после запятой, а не два: одно обращение к модели стоит
 * тысячные доли цента, и округлённое до цента оно показалось бы
 * бесплатным. Меньше самого мелкого показываемого — «менее $0,0001», а
 * не ноль: ноль читается как «бесплатно», и узел, о цене которого просто
 * нечего сказать, выглядел бы даровым.
 *
 * Ровный ноль при этом остаётся нулём: он означает, что обращений не
 * было вовсе, и «менее» о несуществующем расходе сказать нельзя.
 */
export function долларами(nanoUsd: number): string {
  if (nanoUsd === 0) return '$0'
  const знак = nanoUsd < 0 ? '−' : ''
  const долларов = Math.abs(nanoUsd) / 1_000_000_000
  if (долларов < 0.0001) return `менее ${знак}$0,0001`
  return `${знак}$${долларов.toFixed(4).replace('.', ',')}`
}
