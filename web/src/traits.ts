/** Окна, за которые считается поведение. Словарь закрытый — четыре. */
export const ОКНА: { code: string; title: string }[] = [
  { code: 'all', title: 'за всё время' },
  { code: '7d', title: 'за 7 суток' },
  { code: '30d', title: 'за 30 суток' },
  { code: '90d', title: 'за 90 суток' },
]

/** Одно условие правила, как оно ездит на сервер и обратно. */
export interface Условие {
  trait: string
  n?: number
  over?: string
  not?: boolean
}

export function признак(code: string): Признак | undefined {
  return ПРИЗНАКИ.find((one) => one.code === code)
}

export function окноСловами(code: string | undefined): string {
  if (code === undefined || code === '') return 'за всё время'
  return ОКНА.find((one) => one.code === code)?.title ?? code
}

/**
 * Условие словами — одной строкой, какой её читают глазами в правиле.
 *
 * Незнакомый признак показывается как есть, а не «неизвестно чем»:
 * записан он в базе, и скрыть его от составителя значит оставить его
 * чинить правило вслепую.
 */
export function условиеСловами(one: Условие): string {
  const known = признак(one.trait)
  if (known === undefined) return `непонятный признак «${one.trait}»`
  const начало = one.not === true ? known.наоборот : known.title
  const части = [начало]
  if (known.порог !== undefined) части.push(`${one.n ?? 0} ${known.порог}`)
  if (known.заОкно === true) части.push(окноСловами(one.over))
  return части.join(' ')
}

/**
 * Правило словами. Пустое правило — НЕ «все», и написано это прямо:
 * прочитанное как «все», оно однажды раздаст набор всем подряд.
 */
export function правилоСловами(rule: Условие[]): string {
  if (rule.length === 0) return 'правила нет: только названные поимённо'
  return rule.map(условиеСловами).join(' и ')
}
