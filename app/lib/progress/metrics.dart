/// Каталог величин: чем меряется работа врача.
///
/// # Словарь закрыт, и закрытость здесь не украшение
///
/// Величина, заведённая строкой по месту, считалась бы приложением и не
/// считалась бы сервером — и разошлись бы они молча. Каталог зеркален с
/// общим эталоном (`shared/progress-fixtures.json`), а через него — с
/// сервером; сверка обязана отказывать на недоступном эталоне, а не
/// пропускать: сверка, зовущая «пропустить», не сверяет ничего.
///
/// # Каждая величина обязана быть неубывающей
///
/// Из величин выдаются знаки отличия, а выданный знак не отбирают. Значит
/// величина, способная уменьшиться, знак не выдерживает: сегодня он выдан,
/// завтра по той же величине выдавать его не за что, и сорвать его нельзя.
/// Отсюда «лучшая серия подряд без ошибок», а не «текущая».
library;

/// Величина каталога.
class Metric {
  const Metric(this.key, this.title);

  final String key;
  final String title;
}

/// Каталог целиком, в порядке эталона.
///
/// Считает величины сервер: они про то, каким врач пришёл среди всех.
/// Приложение их показывает и по ним же считает долю пути к знаку — её
/// видно и без сети.
abstract final class Metrics {
  static const catalog = <Metric>[
    Metric('casesSolved', 'Решено задач'),
    Metric('correctStreak', 'Подряд без ошибок'),
    Metric('daysActive', 'Дней занятий'),
    Metric('reviewsDone', 'Повторений сделано'),
    Metric('sourcesTouched', 'Источников затронуто'),
  ];

  /// Есть ли такая величина в каталоге.
  ///
  /// Отвечает по каталогу, а не по наличию ключа в присланных величинах:
  /// врач, ещё ничего не решавший, величины не имеет вовсе, и «нет ключа»
  /// не значит «нет такой величины».
  static bool known(String key) {
    for (final one in catalog) {
      if (one.key == key) return true;
    }
    return false;
  }

  /// Величины, приехавшие с сервера, дополненные нулями.
  ///
  /// Объект приезжает полным всегда, но полагаться на это нельзя: сборка
  /// переживёт не одну версию сервера. Отсутствующий ключ — ноль, а не
  /// пропуск: пропущенная величина оставила бы кольцо знака пустым у
  /// врача, который к нему шёл.
  static Map<String, int> fill(Map<String, dynamic> incoming) {
    final out = <String, int>{};
    for (final one in catalog) {
      final value = incoming[one.key];
      out[one.key] = value is int ? value : 0;
    }
    return out;
  }
}
