/// Переносы по правилам русского языка.
///
/// # Зачем они вообще
///
/// Справочник читают с телефона, узким столбцом, и длинные слова —
/// «дифференциальный», «психопатологический» — либо рвут строку в
/// середине пустотой, либо уезжают за край. Без переносов текст в узкой
/// колонке выглядит рваным, и читается он ровно настолько же хуже,
/// насколько выглядит.
///
/// # Мягкий перенос, а не разрезанное слово
///
/// В текст вставляется U+00AD — знак «здесь можно перенести». Само слово
/// не меняется: поиск, выделение и копирование получают его целым. Разрез
/// строки делает раскладка и только если строка не поместилась.
///
/// # Правила, а не словарь
///
/// Словарь переносов — это мегабайты, которые пришлось бы носить в
/// сборке и обновлять отдельно. Правила слогового деления покрывают
/// русский почти полностью, а их ошибки — это лишний непоставленный
/// перенос, то есть ровно то, что было без них.
///
/// Правила (школьные, и они же типографские):
///
///  * переносится по слогам, слог кончается гласной;
///  * на строке не остаётся и не переносится меньше двух букв — мерка
///    относится к краям слова, а не к каждому куску;
///  * «ь», «ъ» и «й» не отрываются от предшествующей буквы;
///  * из группы согласных между гласными первая остаётся на строке, а
///    одиночная согласная уходит к своей гласной целиком.
library;

/// Знак мягкого переноса.
const softHyphen = '­';

const _vowels = 'аеёиоуыэюяАЕЁИОУЫЭЮЯ';
const _sticky = 'ьъйЬЪЙ';

bool _isVowel(String ch) => _vowels.contains(ch);
bool _isSticky(String ch) => _sticky.contains(ch);

bool _isLetter(String ch) {
  final code = ch.codeUnitAt(0);
  // Русские буквы и латиница: метки рубрик бывают латинскими («F32.1»),
  // и ломать их переносом нельзя — на них правил слогового деления нет.
  final russian =
      (code >= 0x0410 && code <= 0x044F) || code == 0x0401 || code == 0x0451;
  final latin =
      (code >= 0x41 && code <= 0x5A) || (code >= 0x61 && code <= 0x7A);
  return russian || latin;
}

bool _isRussian(String ch) {
  final code = ch.codeUnitAt(0);
  return (code >= 0x0410 && code <= 0x044F) || code == 0x0401 || code == 0x0451;
}

/// Расставляет мягкие переносы в тексте.
///
/// Слова короче [minWord] не трогаются вовсе: перенос в коротком слове
/// экономит меньше, чем стоит внимания читателя.
String hyphenate(String text, {int minWord = 7}) {
  if (text.isEmpty) return text;
  final out = StringBuffer();
  final word = StringBuffer();

  void flush() {
    if (word.isEmpty) return;
    out.write(hyphenateWord(word.toString(), minWord: minWord));
    word.clear();
  }

  for (final ch in text.split('')) {
    if (_isLetter(ch)) {
      word.write(ch);
    } else {
      flush();
      out.write(ch);
    }
  }
  flush();
  return out.toString();
}

/// Расставляет мягкие переносы в одном слове.
///
/// Лишний непоставленный перенос ничего не портит; поставленный не по
/// правилу портит слово на глазах у читателя, поэтому сомнительные случаи
/// здесь не переносятся вовсе.
String hyphenateWord(String word, {int minWord = 7}) {
  if (word.length < minWord) return word;

  // Латиница и смешанные метки не трогаются: правила здесь русские, а
  // угаданный перенос в коде рубрики — это испорченный код.
  for (final ch in word.split('')) {
    if (!_isRussian(ch)) return word;
  }

  final l = word.split('');
  final breaks = <int>[];

  bool vowel(int at) => at >= 0 && at < l.length && _isVowel(l[at]);
  bool sticky(int at) => at >= 0 && at < l.length && _isSticky(l[at]);

  // Разбор идёт от гласных, а не по всем парам букв: слог без гласной
  // невозможен, и потому каждый перенос — это граница ПОСЛЕ гласной либо
  // внутри группы согласных, идущей за ней. Перебор пар был здесь до того
  // и давал правило на каждую длину группы; четвёртой длины в нём не
  // оказалось, и «боль-шин-ство» переносилось как «боль-шинство».
  for (var i = 0; i < l.length; i++) {
    if (!vowel(i)) continue;

    // «ь», «ъ» и «й» прилипают к предшествующей букве: «май-онез», а не
    // «ма-йонез». Поэтому граница слога отодвигается за них.
    var at = i;
    while (sticky(at + 1)) {
      at++;
    }
    // Прилипшая буква — это и есть та согласная, что остаётся на строке:
    // «расстрой-ство», а не «расстройс-тво». Без этой оговорки правило
    // «первая из группы остаётся» отсчитывало первую от «й» и уносило за
    // неё ещё одну букву.
    final glued = at > i;

    var next = at + 1;
    while (next < l.length && !vowel(next)) {
      next++;
    }
    // Дальше гласной нет — значит, нет и следующего слога.
    if (next >= l.length) continue;

    // Одна согласная уходит к своей гласной целиком («ра-бо-та»); из
    // группы в две и больше первая остаётся («сес-тра», «рас-строй-ство»,
    // и двойная согласная делится этим же правилом сама собой).
    final group = next - (at + 1);
    var cut = group <= 1 || glued ? at : at + 1;
    while (sticky(cut + 1)) {
      cut++;
    }

    // На строке не остаётся и не переносится меньше двух букв. Мерка
    // относится к краям слова, а не к каждому куску: перенос — это
    // разрешённое место, и одинокая гласная в середине («чи-та-е-мый»)
    // значит лишь, что рвать можно и до неё, и после.
    if (cut + 1 < 2 || l.length - (cut + 1) < 2) continue;
    breaks.add(cut);
  }

  if (breaks.isEmpty) return word;

  final out = StringBuffer();
  var last = 0;
  for (final at in breaks) {
    if (at < last) continue;
    out.write(word.substring(last, at + 1));
    out.write(softHyphen);
    last = at + 1;
  }
  out.write(word.substring(last));
  return out.toString();
}
