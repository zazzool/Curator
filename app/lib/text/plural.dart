/// Слова источника во множественном числе и числа с разрядами.
///
/// # Почему не «12 рубрик»
///
/// Русское числительное требует трёх форм («1 рубрика», «2 рубрики»,
/// «12 рубрик»), и вывести их из слова правилами нельзя — родительный
/// падеж множественного числа в русском не выводится из именительного
/// единственного вообще. Слово при этом приходит из источника: «рубрика»
/// у МКБ-10, «пункт» у приказа, и словаря на все источники не бывает.
///
/// Поэтому число ставится после слова, а не перед ним: «Рубрики: 940»
/// требует одной формы — именительного множественного, — и её правила
/// окончаний дают надёжно. Выдуманная форма на экране у врача выглядит
/// опечаткой приложения, а не особенностью источника.
library;

/// Именительный падеж множественного числа, с заглавной буквы.
///
/// Правила окончаний, а не словарь. Промах стоит одной неловкой буквы в
/// заголовке, поэтому сомнительное остаётся как есть.
String pluralWord(String word) {
  final one = word.trim();
  if (one.isEmpty) return '';
  final last = one[one.length - 1];
  // Гласная и мягкий знак на конце заменяются окончанием, согласная — нет.
  final stem = 'аяейь'.contains(last) ? one.substring(0, one.length - 1) : one;
  final tail = switch (last) {
    'й' || 'ь' || 'я' => 'и',
    'е' => 'я',
    // После шипящих и заднеязычных «ы» не пишется: «рубрики», а не
    // «рубрикы». Смотреть надо на конец ОСНОВЫ, а не слова: у «рубрика»
    // последняя буква «а», и по ней заднеязычная «к» не видна вовсе.
    _ when 'кгхжшчщ'.contains(stem[stem.length - 1]) => 'и',
    _ => 'ы',
  };
  final many = stem + tail;
  return many[0].toUpperCase() + many.substring(1);
}

/// Число с разрядами, разделёнными узким неразрывным пробелом.
///
/// «3 210» читается с одного взгляда, «3210» приходится считать глазами.
/// Пробел именно узкий неразрывный (U+202F): обычный пробел раскладка
/// разорвёт переносом строки, и число разъедется на две строки.
String grouped(int value) {
  final digits = value.abs().toString();
  final out = StringBuffer(value < 0 ? '−' : '');
  for (var i = 0; i < digits.length; i++) {
    if (i > 0 && (digits.length - i) % 3 == 0) out.write('\u202F');
    out.write(digits[i]);
  }
  return out.toString();
}

/// «Рубрики: 940» — слово источника и число при нём.
String counted(int value, String word) =>
    '${pluralWord(word)}: ${grouped(value)}';

/// Русское числительное: форма слова по количеству.
///
/// `plural(2, 'набор', 'набора', 'наборов')` → 'набора'. Исключение
/// 11–14 учтено: там всегда родительный множественного («11 наборов»).
///
/// Три формы называются поимённо, а не выводятся правилами, — и это не
/// противоречит [pluralWord] выше, а дополняет его. Там слово приходит из
/// источника и неизвестно заранее, поэтому число уходит за слово; здесь
/// слова наши собственные, их десяток на всё приложение, и выписать три
/// формы дешевле, чем сочинять их правилами.
String plural(int n, String one, String few, String many) {
  final mod100 = n.abs() % 100;
  if (mod100 >= 11 && mod100 <= 14) return many;
  return switch (n.abs() % 10) {
    1 => one,
    2 || 3 || 4 => few,
    _ => many,
  };
}

/// Число вместе с согласованным словом: «2 набора».
String withPlural(int n, String one, String few, String many) =>
    '$n ${plural(n, one, few, many)}';
