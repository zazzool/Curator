/// Чтение и правка своей записи.
///
/// Отдельным слоем, а не обращениями из экрана, по той же причине, что и
/// у наборов: в файле с проверками виджетов Flutter подменяет
/// `HttpClient` и отвечает 400 на всякий запрос — молча, без объяснения в
/// отказе. Экран, собирающий дверь сам, проверить нечем.
library;

import '../api/client.dart';
import 'model.dart';

class Account {
  Account(this._api);

  final Api _api;

  Future<Profile> read() async => Profile.parse(await _api.get('/v1/me'));

  /// Имя видно только врачу и нам: в таблицах соперничества оно не
  /// показывается. Обрезается здесь, а не на экране, — сервер обрежет
  /// тоже, но пробел, уехавший на сервер, вернётся оттуда именем с
  /// пробелом.
  Future<void> rename(String name) async {
    await _api.put('/v1/me', {'displayName': name.trim()});
  }

  /// Просит код на указанный адрес.
  ///
  /// Ответ сервера один и тот же, занят адрес или свободен, и экран не
  /// пытается это различить: различение здесь и было бы тем самым
  /// способом узнать, заведён ли у нас такой врач.
  Future<void> startBind(String email) async {
    await _api.post('/v1/me/email', {'email': email.trim()});
  }

  /// Сверяет код и привязывает почту, отдавая привязанный адрес.
  ///
  /// Адрес берётся из ответа, а не из поля ввода: сервер сводит его к
  /// одному виду (снимает регистр и пробелы), и показать врачу надо
  /// именно то, что записано, — иначе он будет вспоминать не тот адрес.
  Future<String> confirmBind(String code) async {
    final body = await _api.post('/v1/me/email/confirm', {'code': code.trim()});
    final email = body['email'];
    return email is String ? email : '';
  }

  /// Просит код возврата доступа. Токена для этого не нужно: врач приходит
  /// сюда ровно тогда, когда токена у него уже нет.
  Future<void> startRecovery(String email) => _api.startRecovery(email);

  /// Возвращает доступ и запоминает новый токен устройства.
  ///
  /// Незаконченное на этом устройстве не выбрасывается — ни очередь
  /// неотправленного, ни местный список повторения. Это работа того же
  /// человека, сделанная до того, как он вернул себе запись, и выбросить
  /// её значило бы наказать его за смену телефона. Уедет она уже под
  /// вернувшейся записью, что и верно.
  Future<void> confirmRecovery(String email, String code) =>
      _api.confirmRecovery(email, code);
}
