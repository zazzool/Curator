/// Проверки канонического вида на том, в чём сборщики Dart и Go расходятся.
///
/// Эталон `shared/pack-manifest.json` держит один разобранный пример, и он
/// главный. Но расходятся стандартные сборщики не на нём, а на мелочах,
/// которых в примере нет: целое, приехавшее дробью, управляющие символы,
/// U+2028. Каждое такое расхождение неотличимо от подмены — подпись просто
/// не сходится, и искать причину будут неделю. Поэтому они пришпилены
/// здесь, а с той стороны — в `server/internal/packs/manifest_test.go`.
library;

import 'dart:convert';

import 'package:curator/packs/canonical.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  test('ключи идут по алфавиту на всех уровнях', () {
    expect(
      canonicalJson({
        'b': 1,
        'a': {'z': 1, 'y': 2},
      }),
      '{"a":{"y":2,"z":1},"b":1}',
    );
  });

  test('амперсанд и угловые скобки не экранируются', () {
    // Go по умолчанию превращает их в & и прочее — наследство
    // встраивания JSON в HTML. Выпуск с «и» в названии подписался бы
    // одними байтами, а свернулся бы на устройстве в другие.
    expect(canonicalJson('а & б <в>'), '"а & б <в>"');
  });

  test('целое, приехавшее дробью, пишется целым', () {
    // jsonDecode("1.0") даёт double, и библиотека Dart написала бы «1.0»;
    // Go на том же месте пишет «1». Числа в содержании задач обычны, и
    // отпечаток не сошёлся бы на ровном месте.
    expect(canonicalJson(jsonDecode('{"n":1.0}')), '{"n":1}');
    expect(canonicalJson(1.5), '1.5');
  });

  test('управляющие символы записаны как у Go', () {
    // Замерено на go1.25, а не принято на веру: короткая запись у забоя,
    // перевода страницы, перевода строки, возврата каретки и табуляции,
    // длинная у прочих. Встречная проверка — в
    // server/internal/packs/manifest_test.go.
    expect(canonicalJson('\b\f\n\r\t'), r'"\b\f\n\r\t"');
    expect(canonicalJson('\u0001\u000b\u001f'), r'"\u0001\u000b\u001f"');
  });

  test('U+2028 и U+2029 экранируются', () {
    // Go экранирует их всегда, даже с выключенным экранированием HTML:
    // в JavaScript они рвут строку, и отменить это в Go нечем.
    expect(
      canonicalJson(
        '\u2028'
        '\u2029',
      ),
      r'"\u2028\u2029"',
    );
  });

  test('кавычка и обратная косая экранируются', () {
    expect(canonicalJson(r'"\'), r'"\"\\"');
  });

  test('кириллица остаётся собой', () {
    expect(canonicalJson('Пример'), '"Пример"');
  });

  test('пробелов и переводов строк нет', () {
    final got = canonicalJson({
      'a': [1, 2],
      'b': {'c': 'd'},
    });
    expect(got, '{"a":[1,2],"b":{"c":"d"}}');
    expect(got.endsWith('}'), isTrue);
  });

  test('непонятое не сворачивается, а отказывает', () {
    // Подписать то, чего мы не поняли, значит поручиться за это.
    expect(() => canonicalJson(DateTime.now()), throwsFormatException);
    expect(() => canonicalJson(double.nan), throwsFormatException);
    expect(() => canonicalJson({1: 'a'}), throwsFormatException);
  });
}
