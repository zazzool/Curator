#!/usr/bin/env bash
# Обязательные проверки. Красный набор означает, что работа не сделана.
#
# Порядок не случаен: схема накатывается ДО проверок сервера, потому что
# часть из них идёт на живой базе и без таблиц не пройдёт.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Без строки подключения набор не идёт вовсе — это отказ, а не пропуск.
# Набор, который молча пропускает проверки на базе и возвращает успех,
# выдаёт зелёное за непроверенное.
if [ -z "${CURATOR_TEST_DSN:-}" ]; then
    echo "CURATOR_TEST_DSN не задан: проверки на живой базе не идут." >&2
    echo "Это отказ, а не пропуск — см. server/.env.example." >&2
    exit 1
fi

cd "$ROOT/server"

echo "== Схема: первый накат =="
DATABASE_URL="$CURATOR_TEST_DSN" go run ./cmd/migrate -schema schema.sql -apply

# Второй накат — не придирка: накат идёт при каждой выкатке, и схема,
# падающая на повторе, останавливает выкатку в тот день, когда её меньше
# всего ждут.
echo "== Схема: повторный накат (обязан пройти) =="
DATABASE_URL="$CURATOR_TEST_DSN" go run ./cmd/migrate -schema schema.sql -apply

echo "== Сервер: формат =="
# gofmt сам по себе молчит и возвращает успех, перечисляя негодные файлы в
# вывод, — поэтому смотрим на вывод, а не на код возврата.
bad="$(gofmt -l .)"
if [ -n "$bad" ]; then
    echo "не по формату:" >&2
    echo "$bad" >&2
    exit 1
fi

echo "== Сервер: vet =="
go vet ./...

echo "== Сервер: проверки =="
# -count=1 обязателен, и это замер, а не осторожность. Общие эталоны лежат
# в shared/, то есть ВНЕ каталога пакета, и кэш `go test` правку такого
# файла не замечает: 2026-09-19 сверка словаря видов отвечала «ok (cached)»
# на эталоне, в котором вид был переименован, — то есть ровно та проверка,
# ради которой эталон и заведён, выдавала зелёное за непроверенное.
go test -count=1 ./...

# Проверки на живой базе зовутся TestPg* и обязаны идти, а не пропускаться.
# Считаем их поимённо: набор, в котором они тихо исчезли, выглядит зелёным
# ровно так же, как набор, в котором они прошли.
echo "== Сервер: проверки на живой базе =="
passed="$(go test -count=1 ./... -v -run TestPg 2>&1 | grep -cE '^--- PASS' || true)"
echo "прошло проверок на базе: $passed"
if [ "$passed" -lt 1 ]; then
    echo "ни одна проверка на живой базе не прошла — их либо нет, либо они пропущены." >&2
    exit 1
fi

echo "== Приложение: формат =="
cd "$ROOT/app"
# Набор инструментов Flutter обязан быть на месте. Молча пропустить
# приложение значит выдать зелёное за непроверенное — ровно то, ради чего
# этот набор и написан.
if ! command -v flutter >/dev/null 2>&1; then
    echo "flutter не найден: проверки приложения не идут." >&2
    echo "Это отказ, а не пропуск — см. app/CLAUDE.md." >&2
    exit 1
fi
# Зависимости ставятся набором, а не человеком: в новом рабочем дереве их
# нет, и набор без них падает не на работе, а на обстановке.
if [ ! -f .dart_tool/package_config.json ]; then
    flutter pub get
fi
dart format --output=none --set-exit-if-changed lib test

echo "== Приложение: разбор =="
flutter analyze

echo "== Приложение: проверки =="
flutter test

echo "== Студия: разбор типов =="
cd "$ROOT/web"
# Зависимости ставятся набором, а не человеком: в новом рабочем дереве их
# нет, и набор без них падает на пустом месте — не на работе, а на
# обстановке.
if [ ! -d node_modules ]; then
    npm ci
fi
npm run --silent typecheck

echo "== Студия: проверки =="
npm run --silent test

# Выкатка — тоже код, и негодный её синтаксис выясняется иначе только на
# горящем контуре: `deploy.sh` запускают, когда что-то надо выкатить, а не
# когда есть время читать отказ шелла.
echo "== Выкатка: синтаксис =="
cd "$ROOT"
bash -n deploy.sh

echo
echo "Всё зелено."
