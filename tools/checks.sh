#!/usr/bin/env bash
# Обязательные проверки. Красный набор означает, что работа не сделана.
#
# Пока в проекте есть только схема базы, набор состоит из одной проверки —
# но именно той, ради которой он заводится: схема обязана накатываться на
# чистую базу и накатываться ПОВТОРНО, ничего не ломая. Второй накат — не
# придирка: накат применяется при каждой выкатке, и схема, падающая на
# второй раз, останавливает выкатку в тот день, когда её меньше всего ждут.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Без строки подключения — отказ, а не пропуск. Набор, который молча
# пропускает проверку базы и возвращает успех, выдаёт зелёное за
# непроверенное; это хуже, чем отсутствие набора.
if [ -z "${CURATOR_TEST_DSN:-}" ]; then
    echo "CURATOR_TEST_DSN не задан: проверять схему не на чем." >&2
    echo "Это отказ, а не пропуск — см. server/.env.example." >&2
    exit 1
fi

echo "== Схема: первый накат =="
psql -v ON_ERROR_STOP=1 -q -d "$CURATOR_TEST_DSN" -f "$ROOT/server/schema.sql"

echo "== Схема: повторный накат (обязан пройти) =="
psql -v ON_ERROR_STOP=1 -q -d "$CURATOR_TEST_DSN" -f "$ROOT/server/schema.sql"

echo "== Схема: таблицы на месте =="
tables="$(psql -tAq -d "$CURATOR_TEST_DSN" \
    -c "SELECT count(*) FROM pg_tables WHERE schemaname = 'public'")"
if [ "$tables" -lt 50 ]; then
    echo "В базе всего $tables таблиц — накат прошёл не целиком." >&2
    exit 1
fi
echo "таблиц: $tables"

echo
echo "Всё зелено."
