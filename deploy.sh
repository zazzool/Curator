#!/usr/bin/env bash
# Выкатка Куратора на контур.
#
# Исходники копируются на хост и собираются там: реестра образов у проекта
# нет, а собирать на машине разработчика нечем — Docker стоит не везде.
#
# Файл .env на контуре не трогается: в нём боевые секреты, и живёт он
# отдельно от репозитория. Образец — server/.env.example.
#
# Порядок шагов выбран так, чтобы каждое «нет» звучало как можно раньше и
# как можно дешевле: сперва статические проверки на этой машине, потом
# опрос базы, потом накат схемы — и только затем подмена контейнера.
#
# # Почему накат схемы ДО подмены кода
#
# Код, вышедший раньше своей схемы, падает не при старте, а на первом
# обращении к недостающей колонке — то есть у врача, а не в журнале
# выкатки. Схема растёт только добавлением, поэтому старый код на новой
# схеме работает по-прежнему, а обратное неверно.
set -euo pipefail

HOST="${CURATOR_HOST:-root@curator.psync.ru}"
DIR="${CURATOR_DIR:-/root/curator}"

# Адрес, по которому выкатка убеждается, что служба видна снаружи. Не
# путать с CURATOR_PUBLIC_URL: та уезжает в образ и попадает в письма, а
# эта нужна только здесь и только для опроса.
ORIGIN="${CURATOR_DEPLOY_ORIGIN:-https://curator.psync.ru}"

ROLLBACK=0

die() {
    printf '%s\n' "$@" >&2
    exit 1
}

# Ждёт, пока контур ответит снаружи. Последний ответ кладёт в READY_STATUS.
#
# Подпрограммой, потому что этим опросом кончаются оба пути — и выкатка
# вперёд, и возврат назад; два места для одного окна ожидания разошлись бы
# молча.
READY_STATUS=
wait_ready() {
    local attempt
    for attempt in $(seq 1 20); do
        READY_STATUS=$(curl -s -o /dev/null -w '%{http_code}' \
            --connect-timeout 5 --max-time 15 "$ORIGIN/healthz" || true)
        if [ "$READY_STATUS" = "200" ]; then
            return 0
        fi
        sleep 2
    done
    return 1
}

while [ $# -gt 0 ]; do
    case "$1" in
    --rollback) ROLLBACK=1 ;;
    -h | --help)
        cat <<'USAGE'
Выкатка Куратора.

  ./deploy.sh              собрать и выкатить
  ./deploy.sh --rollback   вернуть предыдущий образ

Куда выкатывать, задаётся окружением:
  CURATOR_HOST            root@curator.psync.ru
  CURATOR_DIR             /root/curator
  CURATOR_DEPLOY_ORIGIN   https://curator.psync.ru
USAGE
        exit 0
        ;;
    *) die "непонятный довод: $1. Что бывает — ./deploy.sh --help" ;;
    esac
    shift
done

# --- Возврат назад ---
#
# Первым делом, до всех проверок: возврат нужен тогда, когда выкаченное
# уже не работает, и гонять на нём проверки студии значит терять минуты на
# горящем контуре. Образ предыдущей выкатки лежит под меткой previous —
# её ставит шаг сборки ниже.
if [ "$ROLLBACK" = 1 ]; then
    echo "Возвращаю предыдущий образ на $HOST…"
    ssh "$HOST" "cd $DIR && docker image inspect curator:previous >/dev/null" ||
        die "На контуре нет образа curator:previous — возвращать нечего." \
            "Так бывает до первой повторной выкатки: предыдущий образ" \
            "появляется, когда поверх него выкатывают следующий."
    ssh "$HOST" "cd $DIR && docker tag curator:previous curator:latest && \
        docker compose up -d --no-build curator"
    if wait_ready; then
        echo "Контур вернулся: $ORIGIN/healthz отвечает $READY_STATUS"
        exit 0
    fi
    die "Контур не ответил после возврата (последний ответ: ${READY_STATUS:-нет}). " \
        "Смотреть: ssh $HOST 'cd $DIR && docker compose logs --tail=100 curator'"
fi

# --- Проверки этой машины ---
#
# Только статические: они идут секунды и ловят неотправляемое. Наборы
# проверок гоняет сторож, и он единственное мерило зелёного — но выкатка
# идёт с того же дерева, и отправлять на контур то, что не собирается,
# незачем.
echo "== Сервер: формат и vet =="
cd server
bad="$(gofmt -l .)"
if [ -n "$bad" ]; then
    echo "не по формату:" >&2
    echo "$bad" >&2
    exit 1
fi
go vet ./...
cd ..

echo "== Студия: типы =="
(cd web && npm run typecheck)

# --- Опрос базы ---
#
# База спрашивается ДО наката и до сборки: по ответу видно, та ли это
# база. Ноль пользователей студии — не отказ, а предупреждение: на такой
# контур можно выкатиться, но войти в студию будет нельзя.
echo "== Контур: опрос базы =="
ssh "$HOST" "cd $DIR && docker compose --profile preflight run --rm -T preflight" ||
    die "Опрос базы не прошёл. Выкатка остановлена: накатывать схему на базу," \
        "о которой ничего не известно, — это и есть тот случай, когда" \
        "ломаются данные."

# --- Хост ---

echo "== Копирую исходники на $HOST:$DIR =="
# Каталоги кода чистим перед распаковкой: tar не удаляет то, чего в архиве
# уже нет, и однажды удалённый файл продолжал собираться на сервере, ломая
# сборку. Файл .env лежит вне этих каталогов и не трогается.
ssh "$HOST" "mkdir -p $DIR && rm -rf $DIR/server $DIR/web $DIR/deploy"

# Каталог снимков — до первого запуска и с правами на запись. Docker
# создал бы его сам, но от root, а служба работает от непривилегированного
# пользователя (uid 10001 в образе) и писать в чужой каталог не может.
# Ошибка эта тихая: служба поднимется, студия заработает, и только снимки
# не появятся — то есть выяснится всё в тот единственный день, когда они
# нужны.
ssh "$HOST" "mkdir -p $DIR/backups && chown 10001:10001 $DIR/backups"

tar czf - \
    --exclude='web/node_modules' --exclude='web/dist' \
    Dockerfile .dockerignore docker-compose.yml deploy server web |
    ssh "$HOST" "tar xzf - -C $DIR"

# --- Сборка ---
#
# Метка previous ставится ДО сборки нового образа, на то, что сейчас
# работает. После сборки было бы поздно: --rollback тогда возвращал бы то
# же самое, что и сломало контур.
echo "== Сборка образа на контуре =="
ssh "$HOST" "cd $DIR && (docker image inspect curator:latest >/dev/null 2>&1 && \
    docker tag curator:latest curator:previous || \
    echo 'предыдущего образа нет — это первая выкатка')"
ssh "$HOST" "cd $DIR && docker compose build curator"

# --- Накат схемы ---
#
# До подмены кода и из свежесобранного образа: утилита наката едет вместе
# с сервером, и версия схемы у них тем самым одна. Без --no-deps compose
# поднял бы заодно и службу — то есть новый код до наката, ровно наоборот.
echo "== Накат схемы =="
ssh "$HOST" "cd $DIR && docker compose run --rm --no-deps --entrypoint /app/migrate curator -apply" ||
    die "Накат схемы не прошёл — код на контур не выкатан, служба работает прежняя." \
        "Это и есть смысл порядка: схема накатывается до подмены кода."

# --- Подмена ---

echo "== Подмена контейнера =="
ssh "$HOST" "cd $DIR && docker compose up -d --no-build curator"

echo "== Жду ответа контура =="
if wait_ready; then
    echo "Готово: $ORIGIN/healthz отвечает $READY_STATUS"
else
    echo "Контур не ответил (последний ответ: ${READY_STATUS:-нет})." >&2
    echo "Журнал: ssh $HOST 'cd $DIR && docker compose logs --tail=100 curator'" >&2
    die "Вернуть предыдущий образ: ./deploy.sh --rollback"
fi

# Образы прежних выкаток не копятся: у хоста есть диск, и его занимают
# соседи. previous при этом остаётся — на нём стоит возврат.
ssh "$HOST" "docker image prune -f --filter 'until=168h' >/dev/null" || true
