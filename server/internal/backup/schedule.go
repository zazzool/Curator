package backup

import (
	"context"
	"log"
	"time"
)

// Ежедневный съём.
//
// # Почему в самой службе, а не в cron на хосте
//
// Служба знает, настроены ли снимки, и говорит об этом вслух при старте.
// Запись в cron на хосте живёт отдельно от выкатки: она переживает
// переезд контура ровно до первого переезда, и заметить её отсутствие
// нечем — снимков просто не будет.
//
// # Почему отказ не роняет службу
//
// Врач, не получивший задачу из-за того, что не снялся снимок, потерял
// больше, чем мы выиграли. Отказ кричит в журнал и ждёт следующего раза.

// Every заводит ежедневный съём и возвращается сразу.
//
// Останавливается отменой ctx: служба, которую нельзя остановить,
// останавливается убийством, а убитая посреди съёмки оставляет
// недописанный файл, выглядящий как снимок.
func (k *Keeper) Every(ctx context.Context, at time.Duration) {
	if !k.Ready() {
		// Вслух и при старте, а не молчанием: каталог снимков заводит
		// выкатка, и пустой каталог выглядит одинаково при «ещё не
		// сняли» и при «не снимаем никогда».
		log.Print("снимки базы не настроены: задачи и разметка существуют в одном экземпляре")
		return
	}
	if at <= 0 {
		at = 24 * time.Hour
	}
	log.Printf("снимки базы: раз в %s в %s", at, k.Dir)

	go func() {
		// Первый снимок — сразу, а не через сутки. Контур, поднятый и
		// упавший в тот же день, иначе не оставил бы ни одного, а первый
		// день новой установки — как раз тот, когда ломают.
		k.once(ctx)

		ticker := time.NewTicker(at)
		defer ticker.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case <-ticker.C:
				k.once(ctx)
			}
		}
	}()
}

// once снимает, сверяет и чистит — и докладывает обо всём словами.
func (k *Keeper) once(ctx context.Context) {
	snap, err := k.Take(ctx)
	if err != nil {
		log.Printf("снимок базы НЕ снят: %v", err)
		return
	}
	log.Printf("снимок базы снят: %s, %d байт", snap.Path, snap.Bytes)

	if k.VerifyDSN != "" {
		// Сверка идёт после съёмки, а не вместо: снимок уже лежит, и
		// отказ сверки не отменяет его — он означает «этому файлу верить
		// нельзя», и сказать это надо громко.
		if err := k.Verify(ctx, snap.Path); err != nil {
			log.Printf("снимку %s ВЕРИТЬ НЕЛЬЗЯ: %v", snap.Path, err)
		} else {
			log.Printf("снимок %s развёрнут и сошёлся по строкам", snap.Path)
		}
	} else {
		// Тоже вслух: снимок, который никто не восстанавливал, — не
		// снимок, и молчание здесь читалось бы как «всё хорошо».
		log.Print("снимок не сверялся: не задана отдельная база под разворачивание")
	}

	if removed, err := k.Prune(); err != nil {
		log.Printf("старые снимки не убраны: %v", err)
	} else if removed > 0 {
		log.Printf("старых снимков убрано: %d", removed)
	}
}
