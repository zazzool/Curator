// Воспроизведение дефектов, найденных аудитом 2026-09-20.
//
// Пакет пустой намеренно: в нём нет кода службы, только проверки, и те —
// под признаком сборки `audit`. Смысл такой:
//
//   - обычный прогон (`go test ./...`, сторож, `tools/checks.sh`) этого
//     пакета не видит вовсе, и зелёное остаётся зелёным. Красная проверка,
//     положенная в общий набор, учит не верить сторожу;
//   - проверки не зовутся TestPg*, и это не придирка: `tools/checks.sh`
//     считает объявленные TestPg по исходникам и требует, чтобы прошло
//     ровно столько же. Проверка под признаком сборки объявлена, но не
//     идёт — счёт разошёлся бы, и набор упал бы на ровном месте;
//   - файл без признака сборки здесь обязателен: каталог, где ВСЕ файлы
//     отсечены признаком, роняет `go vet ./...` словами
//     «build constraints exclude all Go files».
//
// Как позвать:
//
//	CURATOR_TEST_DSN=… go test -tags audit -count=1 -v ./internal/audit/
//
// Оставшиеся здесь проверки падают, и это их работа: каждая показывает
// дефект, названный в docs/audit-2026-09-20.md. Когда дефект починят —
// проверка позеленеет, и вот тогда её надо перенести в пакет, к которому
// она относится, переименовать в TestPg… и снять признак сборки. До тех
// пор она здесь: доказательство, а не сторож.
//
// Так уже прошли двое: СЕР-1 (продление подписки двумя одновременными
// оплатами) и СЕР-2 (ключ повторности, не привязанный к врачу) починены и
// переехали в internal/sales/sales_test.go под именами
// TestPgДвеОплатыПодрядДаютДваМесяца, TestPgКлючПовторностиСверяетсяСПриходом
// и TestPgПовторТемЖеПриходомОтдаётПрежнийПлатёж. Переезд не формальность:
// первая же починка СЕР-1 оказалась неверной — замок на записи врача стоял
// после вставки платежа и давал взаимную блокировку, — и увидела это
// именно переехавшая проверка, а не рассуждение.
