// Разбор файла схемы на отдельные команды.
//
// Накат шлёт команды по одной, а не файлом целиком: расширенный протокол
// postgres запрещает несколько команд в одном сообщении, и файл, посланный
// целиком, отказал бы на первой же точке с запятой.
//
// # Правило разбора и его цена
//
// Команда кончается точкой с запятой в конце строки. Правило простое, и
// потому у него есть известная граница: тело DO-блока разрезало бы пополам,
// потому что внутри него точки с запятой стоят там же. Поэтому DO-блоков в
// schema.sql нет — и это не случайность, а условие, при котором разбор
// работает. Появится нужда в DO-блоке — меняется разбор, а не схема
// втихомолку.
//
// Строчные комментарии выбрасываются до разбора: точка с запятой внутри
// пояснения — обычное дело («…; и это не опечатка»), и, оставленная в
// тексте, она разрезала бы команду по живому.
//
// Выбрасывается при этом и пояснение В КОНЦЕ строки, а не только строка
// целиком из пояснения. Прежде выбрасывалась только целая: строка вида
// `id INT, -- пока так;` внутри CREATE TABLE разрезала бы объявление
// пополам, и накат ушёл бы в postgres половиной команды. Отказ при этом
// был бы громкий, но случился бы он на выкатке — там, где чинить дороже
// всего.
package schema

import "strings"

// Split режет текст схемы на команды.
//
// Пустые куски не возвращаются: файл кончается переводом строки, и без
// этого последней командой всегда шла бы пустота.
func Split(text string) []string {
	var out []string
	var cur strings.Builder

	for _, line := range strings.Split(text, "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "--") {
			continue
		}
		line = cutComment(line)
		trimmed := strings.TrimSpace(line)
		cur.WriteString(line)
		cur.WriteString("\n")
		if strings.HasSuffix(trimmed, ";") {
			if stmt := strings.TrimSpace(cur.String()); stmt != "" {
				out = append(out, stmt)
			}
			cur.Reset()
		}
	}
	if stmt := strings.TrimSpace(cur.String()); stmt != "" {
		out = append(out, stmt)
	}
	// Пустой список — это пустой список, а не nil: вызывающий перебирает
	// его и считает длину, и nil тут ничего не упрощает, зато однажды
	// уедет в ответ ручки и станет там null вместо [].
	if out == nil {
		out = []string{}
	}
	return out
}

// cutComment отрезает строчное пояснение, не тронув его подобия в тексте.
//
// Два знака минуса внутри строковой постоянной пояснением не являются:
// `DEFAULT 'шкала a--b'` — законное значение, и обрезанное по ним
// объявление колонки станет негодным SQL. Поэтому состояние кавычек
// отслеживается, а не ищется первое вхождение «--».
//
// Одиночная кавычка удваивается внутри постоянной ('O”Брайен'), и
// отдельного разбора это не требует: вторая кавычка просто открывает
// постоянную снова, и до конца строки состояние сходится.
func cutComment(line string) string {
	inString := false
	inQuoted := false
	runes := []rune(line)
	for i := 0; i < len(runes); i++ {
		switch runes[i] {
		case '\'':
			if !inQuoted {
				inString = !inString
			}
		case '"':
			if !inString {
				inQuoted = !inQuoted
			}
		case '-':
			if !inString && !inQuoted && i+1 < len(runes) && runes[i+1] == '-' {
				return strings.TrimRight(string(runes[:i]), " \t")
			}
		}
	}
	return line
}
