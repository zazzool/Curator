package schema

import (
	"os"
	"testing"
)

// TestИмяТаблицыВСхемеОдноНаОдну — два объявления одного имени.
//
// Проверка куплена живым промахом (наряд 5б): свод правил был объявлен
// таблицей `rules`, а такая таблица в схеме уже стояла — заведённая под
// другое и не используемая ни одной строкой кода. `CREATE TABLE IF NOT
// EXISTS` пропускает второе объявление МОЛЧА: на свежей базе выигрывает
// первое, на живой — то, что там уже лежит. Дальше догоняющий накат
// принимается дописывать колонки одной таблицы в другую, и сходится это
// только там, где базы ещё нет, — то есть в проверках и нигде больше.
//
// Отказ отсюда читается сразу: имя названо, и остаётся выбрать другое.
func TestИмяТаблицыВСхемеОдноНаОдну(t *testing.T) {
	raw, err := os.ReadFile("../../schema.sql")
	if err != nil {
		t.Fatal(err)
	}
	seen := map[string]int{}
	for _, tbl := range Tables(Split(string(raw))) {
		seen[tbl.Name]++
	}
	for name, n := range seen {
		if n > 1 {
			t.Errorf("таблица %q объявлена %d раза: второе объявление пропустится молча", name, n)
		}
	}
}
