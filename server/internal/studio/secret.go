// Хранение секрета аутентификатора.
//
// # Почему секрет запечатывается, а не хешируется
//
// Жетон сессии в базе лежит отпечатком, и довод записан там же: утёкшая
// база не должна давать входа. Секрет аутентификатора — из той же таблицы,
// и даёт он больше жетона: жетон истекает, а секрет открывает вход
// НАВСЕГДА, пока человек не перепривяжет аутентификатор. Правило было
// верное, применённое наполовину.
//
// Отпечатком его положить нельзя: код сверяется пересчётом от секрета, и
// для этого секрет нужен целиком. Значит — запечатывание ключом, который
// в базе не лежит: тот, кто унёс снимок, уносит нечитаемое.
//
// # Почему ключа может не быть
//
// Без ключа служба поднимается и работает, а секреты лежат как лежали —
// иначе выкатка на контур, где ключ ещё не положили, закрыла бы вход в
// студию всем сразу. Отсутствие ключа объявляется в журнале при старте.
//
// Обратное, однако, не прощается: запечатанный секрет при отсутствующем
// или неподходящем ключе — ОТКАЗ, а не «прочитаем как есть». Прочитанный
// как есть, он превратился бы в негодный секрет, сверка вернула бы «код
// не подошёл», и человек перепривязал бы аутентификатор, стерев
// запечатанное. Непонятое не применяется.
package studio

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/base64"
	"errors"
	"fmt"
	"os"
	"strings"
)

// sealedPrefix — метка запечатанного значения.
//
// Метка, а не догадка по длине: секрет аутентификатора — это base32, и
// отличить его от base64 на глаз нельзя, а «попробуем распечатать, не
// вышло — значит открытый» превращает подпорченный шифртекст в тихо
// принятую пустоту. Номер в метке — затем, что смена способа
// запечатывания должна быть видна в самой строке.
const sealedPrefix = "enc1:"

// SealKeySize — длина ключа запечатывания.
//
// Ровно 32 байта: AES-256. Короткий ключ не растягивается и не дополняется
// — «дополним нулями» превращает опечатку в переменной окружения в
// шифрование ключом из одних нулей, и происходит это молча.
const SealKeySize = 32

// sealSecret запечатывает секрет для хранения.
//
// Без ключа возвращает секрет как есть: см. довод о выкатке выше.
func sealSecret(key []byte, plain string) (string, error) {
	if len(key) == 0 {
		return plain, nil
	}
	gcm, err := sealer(key)
	if err != nil {
		return "", err
	}
	nonce := make([]byte, gcm.NonceSize())
	if _, err := rand.Read(nonce); err != nil {
		return "", fmt.Errorf("одноразовое число не порождено: %w", err)
	}
	// Одноразовое число едет вместе с шифртекстом: без него не
	// распечатать, а тайны в нём нет.
	sealed := gcm.Seal(nonce, nonce, []byte(plain), nil)
	return sealedPrefix + base64.StdEncoding.EncodeToString(sealed), nil
}

// openSecret распечатывает прочитанное из базы.
//
// Второе возвращаемое значение — был ли секрет запечатан. По нему решается,
// нужно ли догнать старую строку: догонять открытую есть смысл, а
// перепечатывать уже запечатанную — нет.
func openSecret(key []byte, stored string) (string, bool, error) {
	if !strings.HasPrefix(stored, sealedPrefix) {
		return stored, false, nil
	}
	if len(key) == 0 {
		return "", true, errors.New("секрет аутентификатора запечатан, а ключа запечатывания нет: " +
			"проверьте CURATOR_SECRET_KEY")
	}
	raw, err := base64.StdEncoding.DecodeString(strings.TrimPrefix(stored, sealedPrefix))
	if err != nil {
		return "", true, fmt.Errorf("запечатанный секрет не читается как base64: %w", err)
	}
	gcm, err := sealer(key)
	if err != nil {
		return "", true, err
	}
	if len(raw) < gcm.NonceSize() {
		return "", true, errors.New("запечатанный секрет короче одноразового числа")
	}
	plain, err := gcm.Open(nil, raw[:gcm.NonceSize()], raw[gcm.NonceSize():], nil)
	if err != nil {
		// Печать не сошлась: либо ключ не тот, либо строку правили. Оба
		// случая — отказ, и оба чинятся человеком, а не службой.
		return "", true, errors.New("секрет аутентификатора не распечатан: ключ не тот или строка испорчена")
	}
	return string(plain), true, nil
}

func sealer(key []byte) (cipher.AEAD, error) {
	if len(key) != SealKeySize {
		return nil, fmt.Errorf("ключ запечатывания в %d байт вместо %d", len(key), SealKeySize)
	}
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, fmt.Errorf("шифр не собран: %w", err)
	}
	return cipher.NewGCM(block)
}

// SealKeyFromEnv читает ключ запечатывания из окружения.
//
// Одно место на всех, кто его читает: и служба, и утилита заведения
// пользователей ходят в ту же таблицу, и разные способы прочитать ключ
// означали бы секреты, запечатанные по-разному.
//
// Пусто — не отказ: служба поднимется и будет хранить секреты открыто, как
// хранила. Негодный ключ — отказ: ключ длиной не в 32 байта чаще всего
// опечатка, и молча обрезанный он запечатает секреты так, что распечатать
// их будет нечем.
func SealKeyFromEnv() ([]byte, error) {
	raw := strings.TrimSpace(os.Getenv("CURATOR_SECRET_KEY"))
	if raw == "" {
		return nil, nil
	}
	key, err := base64.StdEncoding.DecodeString(raw)
	if err != nil {
		return nil, fmt.Errorf("CURATOR_SECRET_KEY не читается как base64: %w", err)
	}
	if len(key) != SealKeySize {
		return nil, fmt.Errorf("CURATOR_SECRET_KEY даёт %d байт вместо %d", len(key), SealKeySize)
	}
	return key, nil
}
