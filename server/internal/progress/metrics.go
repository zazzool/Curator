package progress

// Каталог величин.
//
// # Словарь закрыт, и закрытость здесь не украшение
//
// Величина, заведённая строкой по месту, считалась бы одним приложением и
// не считалась бы другим — и разошлись бы они молча. Каталог зеркален с
// общим эталоном (shared/progress-fixtures.json), а через него — с
// приложением; сверка обязана отказывать на недоступном эталоне, а не
// пропускать: сверка, зовущая «пропустить», не сверяет ничего.
//
// # Каждая величина обязана быть неубывающей
//
// Из величин выдаются знаки отличия, а выданный знак не отбирают. Значит
// величина, способная уменьшиться, знак не выдерживает: сегодня он выдан,
// завтра по той же величине его выдавать не за что, и сорвать его нельзя.
// Отсюда «лучшая серия подряд без ошибок», а не «текущая»: текущая
// обнуляется первой же ошибкой.
//
// Проверка на неубывание стоит рядом с каталогом и идёт на живой базе:
// величина ломается не в день, когда её завели, а в день, когда по ней
// выдали первый знак.

// MetricKey — ключ величины. Тип свой, а не string, чтобы ключ,
// написанный по месту с опечаткой, не прошёл компилятор.
type MetricKey string

const (
	// CasesSolved — сколько РАЗНЫХ задач решено верно хотя бы раз.
	// Разных, а не попыток: иначе величина набивается одной задачей.
	CasesSolved MetricKey = "casesSolved"

	// CorrectStreak — лучшая серия подряд без ошибок. Лучшая, а не
	// текущая: см. про неубывание выше.
	CorrectStreak MetricKey = "correctStreak"

	// DaysActive — сколько разных дней врач занимался.
	DaysActive MetricKey = "daysActive"

	// ReviewsDone — сколько разборов сделано по расписанию повторения.
	ReviewsDone MetricKey = "reviewsDone"

	// SourcesTouched — скольких разных источников коснулся.
	SourcesTouched MetricKey = "sourcesTouched"
)

// Metric — величина каталога.
type Metric struct {
	Key   MetricKey
	Title string
}

// Metrics — каталог целиком, в порядке эталона.
func Metrics() []Metric {
	return []Metric{
		{CasesSolved, "Решено задач"},
		{CorrectStreak, "Подряд без ошибок"},
		{DaysActive, "Дней занятий"},
		{ReviewsDone, "Повторений сделано"},
		{SourcesTouched, "Источников затронуто"},
	}
}

// KnownMetric отвечает, есть ли такая величина в каталоге.
//
// Отвечает по каталогу, а не по наличию ключа в сохранённых величинах:
// врач, ещё ничего не решавший, величины не имеет вовсе, и «нет ключа» не
// значит «нет такой величины».
func KnownMetric(key MetricKey) bool {
	for _, m := range Metrics() {
		if m.Key == key {
			return true
		}
	}
	return false
}
