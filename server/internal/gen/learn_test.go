package gen

import (
	"strings"
	"testing"
	"time"

	"curator/server/internal/rules"
)

// сейчасПроверки — часы проверок. Своя отметка, а не time.Now(): правило
// считает кворум и затухание по времени, и проверка на плывущих часах
// проверяла бы разное в разные дни.
var сейчасПроверки = time.Date(2026, 9, 20, 12, 0, 0, 0, time.UTC)

func планОбучения() Plan {
	return Plan{
		SourceID:      7,
		Title:         "Приказ № 1130н",
		UnitWord:      "пункт",
		StatementWord: "указание",
		TaskKind:      KindRecognise,
		Unit:          UnitRef{Label: "3.1", Title: "Ритуальное сопровождение", Path: "3/3.1"},
	}
}

func TestСловоформыСводятсяВОдноПравило(t *testing.T) {
	// «ритуально» и «ритуальный» — одна протечка в двух формах. Считай
	// их разными, и ни одна не набрала бы кворума, а в списке правил
	// стояли бы три пункта об одном и том же.
	список := словесныеПравила(планОбучения(), []Cue{
		{Kind: CueNamedSign, Terms: []string{"ритуально", "ритуальный", "ритуальная"}},
	})
	if len(список) != 1 {
		ids := []string{}
		for _, r := range список {
			ids = append(ids, r.ID)
		}
		t.Fatalf("словоформы дали %d правил: %v", len(список), ids)
	}
}

func TestПравилоОСловеПривязаноКСвоемуИсточнику(t *testing.T) {
	// Слово протекло в задаче по ЭТОМУ документу. Пусти правило без
	// области — и «не пиши слово „явка“» уедет в задачи по клиническим
	// рекомендациям, где это слово ни при чём.
	список := словесныеПравила(планОбучения(), []Cue{
		{Kind: CueNamedSign, Terms: []string{"ритуально"}},
	})
	if len(список) != 1 {
		t.Fatalf("правил %d вместо одного", len(список))
	}
	r := список[0]
	if len(r.Scope.Sources) != 1 || r.Scope.Sources[0] != 7 {
		t.Fatalf("область не привязана к источнику: %+v", r.Scope)
	}
	if r.Source != rules.FromLint {
		t.Fatalf("источник правила «%s» вместо выведенного", r.Source)
	}
	if !strings.Contains(r.Text, "ритуально") {
		t.Fatalf("слово не названо в тексте правила: %q", r.Text)
	}
	if !strings.Contains(r.ID, "7") {
		t.Fatalf("опознаватель не несёт источника: %q", r.ID)
	}
}

func TestВыведенноеПравилоЗаводитсяКандидатом(t *testing.T) {
	// Заведи его действующим — и первое же случайное замечание стало бы
	// требованием к модели на все следующие задачи. Кворум за тем и
	// заведён.
	список := словесныеПравила(планОбучения(), []Cue{
		{Kind: CueNamedSign, Terms: []string{"ритуально"}},
	})
	r := список[0]
	if err := r.Normalize(сейчасПроверки); err != nil {
		t.Fatal(err)
	}
	if r.Status == rules.Active {
		t.Fatal("выведенное правило заведено сразу действующим")
	}
}

func TestНезнакомыйРодЗамечанияОбучениеНеТрогает(t *testing.T) {
	// Словарь родов закрыт, и род, которого в нём нет, проходит мимо
	// обучения. Это решение, а не потеря: учиться стоит тому, что
	// проверяется механически и повторяется.
	список := словесныеПравила(планОбучения(), []Cue{
		{Kind: "какой-то новый род", Terms: []string{"слово"}},
	})
	if len(список) != 0 {
		t.Fatalf("незнакомый род завёл правило: %+v", список)
	}
}

func TestБезИсточникаПравилОСловахНеБывает(t *testing.T) {
	// Правило о слове без источника — это «не пиши слово „срок“» во всех
	// задачах системы.
	план := планОбучения()
	план.SourceID = 0
	if список := словесныеПравила(план, []Cue{
		{Kind: CueNamedSign, Terms: []string{"ритуально"}},
	}); len(список) != 0 {
		t.Fatalf("правило о слове завелось без источника: %+v", список)
	}
}

func TestИмяПравилаОСловеВлезаетВСписок(t *testing.T) {
	// Имя стоит в списке одной строкой, и потолок у него в байтах.
	// Кириллица стоит двух, и длинное слово выносило бы имя за потолок —
	// а запись правила падала бы уже на записи, то есть обучение молча
	// переставало бы работать на длинных словах.
	длинное := strings.Repeat("непроизносимо", 4)
	список := словесныеПравила(планОбучения(), []Cue{
		{Kind: CueNamedSign, Terms: []string{длинное}},
	})
	if len(список) != 1 {
		t.Fatalf("правил %d вместо одного", len(список))
	}
	r := список[0]
	if err := r.Normalize(сейчасПроверки); err != nil {
		t.Fatalf("правило о длинном слове негодно: %v", err)
	}
}
