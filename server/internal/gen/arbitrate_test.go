func TestPgНесостоявшийсяРазборНеМолчитИНеРонитЗадачу(t *testing.T) {
	// Разбор уточняет уже оплаченную проверку, и ронять из-за него
	// написанную задачу нельзя. Но и молчать нельзя: составитель увидел
	// бы расхождение без разбора и решил, что разобрали и подтвердили, —
	// то есть пошёл бы переделывать задачу, которой, возможно, ничего не
	// нужно.
	gate := testGate(t)
	sourceID := источник(t, gate)
	order := Order{SourceID: sourceID, UnitLabel: "3.1"}
	model := &подставнаяМодель{ответы: []string{
		годныйОтвет,
		ответВычитки,
		`{"answer":"3.2","why":"похоже на оформление отказа","sure":true}`,
		`{"verdict":"конечно заказанная","why":"я уверена"}`,
		ответСоседа,
		ответСоседа,
	}}
	runner, jobs, _ := конвейер(t, model, order)

	result, err := прогнать(t, runner, jobs, sourceID)
	if err != nil {
		t.Fatalf("задание упало из-за несостоявшегося разбора: %v", err)
	}
	if result.DraftID == 0 {
		t.Fatal("черновик выброшен из-за несостоявшегося разбора")
	}
	if result.Check.Arbitration != nil {
		t.Fatalf("неузнанный исход засчитан разбором: %+v", result.Check.Arbitration)
	}
	if result.Check.ArbitrationNote == "" {
		t.Fatal("о несостоявшемся разборе не сказано: молчание читается как «разобрали и подтвердили»")
	}
	if result.Check.Agrees() || !result.Check.Disputed() {
		t.Fatal("несостоявшийся разбор снял расхождение")
	}
	// Различающая сверка при этом состоялась: отказ разбора её очереди не
	// съел, и узлы ниже мерили то, что им приготовили.
	if len(result.Siblings) != 2 {
		t.Fatalf("различающих сверок %d: отказ разбора сдвинул очередь", len(result.Siblings))
	}
	// Причина живёт в черновике, а не только в журнале выкатки: журнал
	// составитель не читает и читать не обязан.
	drafts, err := jobs.Drafts(context.Background(), result.JobID)
	if err != nil {
		t.Fatal(err)
	}
	if drafts[0].Check == nil || drafts[0].Check.ArbitrationNote == "" {
		t.Fatalf("причина несостоявшегося разбора не легла в черновик: %+v", drafts[0].Check)
	}
}

func TestPgРазборБезПоложенийСоседейОтказываетсяНазвавПричину(t *testing.T) {
	// Спор двух сторон требует двух сторон. Дай мы разбору одну
	// заказанную единицу, вопрос выродился бы в «подходит ли условие
	// сюда», на который ответ «да» почти всегда: условие по ней и
	// писалось. Такой разбор снимал бы всякое расхождение подряд — то
	// есть выглядел бы работой, отпуская к врачу ровно те задачи, ради
	// которых сверку и завели.
	ctx := context.Background()
	gate := testGate(t)
	sourceID := источник(t, gate)

	// Соседей лишаем положений ДО заказа: план собирается в момент
	// заказа и уезжает в задание целиком, и правка базы после этого до
	// него уже не достанет. Круг вариантов при этом цел — он собран по
	// названиям, — а мерить разбору нечем.
	if _, err := gate.Exec(ctx,
		`DELETE FROM source_unit_statements WHERE source_id = $1 AND unit_label <> '3.1'`,
		sourceID); err != nil {
		t.Fatal(err)
	}

	order := Order{SourceID: sourceID, UnitLabel: "3.1"}
	model := &подставнаяМодель{ответы: []string{
		годныйОтвет,
		ответВычитки,
		`{"answer":"3.2","why":"похоже на оформление отказа","sure":true}`,
		ответРазбора,
		ответСоседа,
		ответСоседа,
	}}
	runner, jobs, _ := конвейер(t, model, order)

	result, err := прогнать(t, runner, jobs, sourceID)
	if err != nil {
		t.Fatal(err)
	}
	if result.Check.Arbitration != nil {
		t.Fatalf("разбор состоялся без положений соседей: %+v", result.Check.Arbitration)
	}
	if !strings.Contains(result.Check.ArbitrationNote, "положений") {
		t.Fatalf("причина отказа разбора не названа: %q", result.Check.ArbitrationNote)
	}
	// И денег за него не заплачено: узел отказал ДО обращения к модели.
	//
	// Счёт берётся местом узла соседей не из хитрости: это ровно число
	// обращений, случающихся ДО него, — написание, вычитка и слепая
	// сверка. Сам узел соседей на этом источнике молчит по той же
	// причине, что и разбор: положений у соседей нет, и спрашивать
	// нечего.
	if len(model.спрошено) != узелСоседей {
		t.Fatalf("обращений к модели %d вместо %d: за несостоявшийся разбор заплачено",
			len(model.спрошено), узелСоседей)
	}
}
