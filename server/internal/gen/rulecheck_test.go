func TestСупругЧужойНарушениемНеСчитается(t *testing.T) {
	// Живая проверка у донора научила: супруг в условии не всегда супруг
	// того, о ком речь. Замечание на обычный социальный анамнез убило бы
	// доверие ко всей проверке быстрее, чем она поймала бы хоть одну
	// настоящую ошибку.
	check := &rules.Check{Type: rules.CheckSpouseGender}
	check.Normalize()

	for _, чужой := range []string{
		"Пациентка Л., 31 год, женщина, жена военнослужащего.",
		"Пациентка Л., 31 год, женщина, конфликтует с женой брата.",
	} {
		if got := RunCheck(условие(чужой), check); len(got) != 0 {
			t.Fatalf("чужая роль сочтена нарушением: %q → %s", чужой, сообщения(got))
		}
	}
}

func TestСупругТогоЖеПолаЭтоНарушение(t *testing.T) {
	// Ровно тот случай, ради которого свод и заводился: «пациент,
	// мужчина 43 лет… его муж рассказывает».
	check := &rules.Check{Type: rules.CheckSpouseGender}
	check.Normalize()

	got := RunCheck(условие("Пациент, мужчина 43 лет, жалуется на бессонницу.",
		"Его муж отмечает, что приступы участились."), check)
	if len(got) != 1 {
		t.Fatalf("супруг того же пола пропущен: %s", сообщения(got))
	}
	if !strings.Contains(got[0].Message, "жена") {
		t.Fatalf("в замечании не сказано, как должно быть: %s", got[0].Message)
	}

	// Супруг противоположного пола — как и задумано.
	if got := RunCheck(условие("Пациент, мужчина 43 лет.",
		"Его жена отмечает, что приступы участились."), check); len(got) != 0 {
		t.Fatalf("исправный супруг объявлен нарушением: %s", сообщения(got))
	}
}

