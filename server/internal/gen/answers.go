package gen

import (
	"errors"
	"fmt"
	"strings"
)

// Круг вариантов собирает СЕРВЕР, а не модель.
//
// # Почему не модель
//
// Прежде круг писала модель: заданию уходил список соседей, модель
// выбирала из него, а разбор сверял выбранное с планом и отбивал
// черновик, если вариант оказывался со стороны. Порядок этот платил
// дважды. Во-первых, деньгами: единицу со стороны модель выдумывала
// исправно, и заказ уходил в повтор из-за списка, который у нас и так
// был. Во-вторых, молчанием: у задачи-действия проверять было нечего
// вовсе — варианты там тексты, а не единицы, и `checkActionAnswer`
// смотрел лишь на то, что у них нет метки. Модель сочиняла неверные
// действия сама, и выдуманное действие узнаётся обучающимся с первого
// взгляда: такая задача мерит чутьё на неестественную формулировку, а не
// знание документа.
//
// Теперь круг известен ДО обращения к модели, и модель пишет только
// прозу: условие, разметку и разбор. Вариант со стороны стал невозможен,
// а не отлавливаемым.
//
// # Одно место на оба вида задачи
//
// Виды расходятся ровно в двух вещах: чем является эталон и откуда
// берутся неверные варианты. Всё остальное — потолок круга, отсев
// повторов, порядок, отказ по малому источнику — у них общее. Третьей
// сборки круга не заводится: разойдись две, задача спрашивала бы одно, а
// различающая сверка мерила бы другое.

const (
	// rivalsMax — сколько неверных вариантов берётся в круг.
	//
	// Число донорское, и довод при нём донорский же: круг шире семи
	// вариантов перестаёт читаться, а варианты за пределами первой
	// пятёрки выбирают единицы (Haladyna & Downing, 1988 — там же о том,
	// что лишний нефункциональный вариант не добавляет задаче ничего).
	//
	// У донора число это плавало по сложности заказа. Здесь оно
	// постоянное, и это не упрощение: сложность у нас называет МОДЕЛЬ,
	// написав задачу, — то есть узнаётся она после того, как круг уже
	// должен быть собран. Считать круг по числу, которого ещё нет,
	// пришлось бы гаданием.
	rivalsMax = 6

	// optionsMin — меньше трёх вариантов не задача, а подсказка: угадать
	// верный можно, не читая условия.
	optionsMin = 3
)

// Rival — неверный вариант круга.
type Rival struct {
	// Option — что увидит обучающийся.
	Option Option

	// Ref — чем различающая сверка мерит этот вариант: положения той
	// единицы, из которой он взят. У задачи-действия это само положение,
	// а не вся единица: вариантом там стало одно действие, и спрашивать
	// про остальные значило бы мерить не то, что показано.
	Ref UnitRef

	// Whence — откуда вариант взялся, словами источника. Уезжает в
	// задание модели: она пишет разбор, и разбор обязан сказать, почему
	// каждый неверный вариант неверен. Не зная, откуда вариант, она
	// сочинит довод.
	Whence string
}

// AnswerSet — круг вариантов заказа.
//
// Собирается один раз и читается всеми — заданием модели, телом готовой
// задачи и различающей сверкой. Разойдись они, задача спрашивала бы одно,
// а мерилась другим.
type AnswerSet struct {
	// Answer — верный ответ: метка единицы у узнавания, текст действия у
	// действия. Ровно то, что сверяет casestore.Body.CorrectOption.
	Answer string

	// Correct — эталон в том виде, в каком его увидит обучающийся.
	Correct Option

	Rivals []Rival
}

// AnswerSet собирает круг по плану заказа.
//
// Отказывает, а не добирает выдумкой: источник, из которого круга не
// набирается, задачу дать не может, и написанная по нему задача мерила бы
// умение выбрать из двух. Отказ приходит ДО обращения к модели — то есть
// бесплатно.
func (p Plan) AnswerSet() (AnswerSet, error) {
	var set AnswerSet
	if p.TaskKind == KindAction {
		set = p.actionAnswers()
	} else {
		set = p.recogniseAnswers()
	}
	if err := set.validate(p); err != nil {
		return AnswerSet{}, err
	}
	return set, nil
}

// recogniseAnswers — у узнавания эталон и варианты суть единицы источника.
func (p Plan) recogniseAnswers() AnswerSet {
	set := AnswerSet{
		Answer:  p.Unit.Label,
		Correct: Option{Label: p.Unit.Label, Text: p.Unit.Title},
	}

	// Путаемые идут первыми, и это не порядок ради порядка. Пара «путают
	// с» — единственное место, где сходство двух единиц назвал САМ
	// источник; обрежь мы круг по порядку документа, и первой вылетела бы
	// именно та единица, про которую источник сказал прямо, что её
	// путают. Круг стал бы хуже, чем мог бы быть, и молча.
	for _, pass := range []bool{true, false} {
		for _, s := range p.Siblings {
			if s.Confusable != pass || len(set.Rivals) >= rivalsMax {
				continue
			}
			// Словарь источника («пункт», «статья», «код») сюда не
			// подставляется, и это не забывчивость: согласовать с ним
			// прилагательное нечем — род у чужого слова любой, — а
			// «другая пункт источника» читает и модель, и составитель,
			// правящий задание. Метку варианта Origins и так печатает
			// строкой выше.
			whence := "сосед по документу"
			if s.Confusable {
				whence = "источник прямо называет его путаемым с заказанным"
			}
			set.Rivals = append(set.Rivals, Rival{
				Option: Option{Label: s.Label, Text: s.Title},
				Ref:    s,
				Whence: whence,
			})
		}
	}
	return set
}

// actionAnswers — у действия эталон это текст положения.
//
// Неверные действия берутся из документа, а не сочиняются: сперва
// соседние положения той же единицы — они правдоподобнее всего, потому
// что написаны про тот же предмет, — затем головные положения соседних
// единиц. Выдуманное действие узнаётся с первого взгляда.
func (p Plan) actionAnswers() AnswerSet {
	if p.Target == nil {
		// Сюда заказ не доходит: Resolve отказал бы до задания. Но сборка
		// обязана пережить и это — задание, пролежавшее в очереди с
		// прежней выкатки, разбирается по своему плану, а не по нынешним
		// заслонам.
		return AnswerSet{}
	}
	target := strings.TrimSpace(p.Target.Body)
	set := AnswerSet{Answer: target, Correct: Option{Text: target}}

	names := p.Designations()
	seen := map[string]bool{strings.ToLower(target): true}
	take := func(name, text, whence string) {
		text = strings.TrimSpace(text)
		if text == "" || seen[strings.ToLower(text)] || len(set.Rivals) >= rivalsMax {
			return
		}
		seen[strings.ToLower(text)] = true
		set.Rivals = append(set.Rivals, Rival{
			Option: Option{Text: text},
			// Мерило различающей сверки — само положение, и оно же имя
			// варианта для составителя. Единицу сюда класть нельзя:
			// сверка спросила бы про все её положения разом и объявила
			// подтверждением совпадение с любым.
			Ref:    UnitRef{Label: name, Title: text, StatementsMd: text},
			Whence: whence,
		})
	}

	for i, st := range p.Statements {
		if strings.EqualFold(strings.TrimSpace(st.Body), target) {
			continue
		}
		take(names[i], st.Body, "сказано там же, рядом с эталоном")
	}
	for _, sib := range p.Siblings {
		head := headStatement(sib.StatementsMd)
		take(sib.Label, head, "сказано у соседа, а не про заказанное")
	}
	return set
}

// headStatement — первое положение соседа из собранного при заказе текста.
//
// Соседи приезжают положениями одной строкой (см. Resolver.siblings), и
// головное из них — первая непустая строка. Разбирать её обратно в
// обозначения не нужно и нельзя: это была бы вторая реализация сборки
// положений, и расходилась бы она с первой молча.
func headStatement(md string) string {
	for _, line := range strings.Split(md, "\n") {
		if line = strings.TrimSpace(line); line != "" {
			return line
		}
	}
	return ""
}

// validate — годен ли собранный круг.
//
// Мерится тем же, чем прежде мерился черновик модели: эталон на месте,
// вариантов не меньше трёх, повторов нет. Разница в том, КОГДА это
// спрашивается. Прежде — после того, как за задачу заплачено; теперь — до
// обращения к модели, и отказ называет настоящую причину: круга не даёт
// сам источник, а не «модель написала плохо».
func (s AnswerSet) validate(p Plan) error {
	if strings.TrimSpace(s.Answer) == "" {
		return errors.New("у заказа нет эталона: писать не про что")
	}
	if strings.TrimSpace(s.Correct.Text) == "" {
		// У узнавания текстом эталона идёт название единицы. Безымянная
		// единица дала бы обучающемуся пустую строку в списке ответов.
		return fmt.Errorf("у %s %q нет названия: в круге вариантов он был бы пустой строкой",
			p.UnitWord, s.Answer)
	}
	if got := len(s.Rivals) + 1; got < optionsMin {
		// Словарь источника ставится в именительном падеже, как и во
		// всех прочих отказах этого пакета: склонять чужое слово
		// («пункт», «абзац», «критерий») нечем, а «у этой пункт» читается
		// хуже, чем отсутствие слова вовсе.
		if p.TaskKind == KindAction {
			return fmt.Errorf(
				"круга вариантов не набирается: неверных действий нашлось %d, а нужно хотя бы %d — "+
					"у %q нет второго положения, и у соседей брать нечего",
				len(s.Rivals), optionsMin-1, p.Unit.Label)
		}
		return fmt.Errorf(
			"круга вариантов не набирается: соседей нашлось %d, а нужно хотя бы %d — "+
				"%s %q единственный на своём уровне, и различать его не с чем",
			len(s.Rivals), optionsMin-1, p.UnitWord, p.Unit.Label)
	}
	return nil
}

// Options — круг, каким он ложится в задачу: эталон первым.
//
// Порядок этот читают обе сверки и тело готовой задачи, а тасует варианты
// устройство при выдаче. Записать их тасованными нельзя: разбор задачи
// ссылается на варианты, и перетасуй мы их здесь — ссылки разъехались бы.
func (s AnswerSet) Options() []Option {
	out := make([]Option, 0, len(s.Rivals)+1)
	out = append(out, s.Correct)
	for _, r := range s.Rivals {
		out = append(out, r.Option)
	}
	return out
}

// Refs — чем различающая сверка мерит каждый неверный вариант.
//
// Пустой список — [], а не nil: он уезжает в ответ ручки, и null вместо
// списка роняет студию на исправном случае.
func (s AnswerSet) Refs() []UnitRef {
	out := make([]UnitRef, 0, len(s.Rivals))
	for _, r := range s.Rivals {
		out = append(out, r.Ref)
	}
	return out
}

// Listing — неверные варианты в задание модели ({круг}).
func (s AnswerSet) Listing() string {
	if len(s.Rivals) == 0 {
		return "(неверных вариантов не нашлось)"
	}
	var b strings.Builder
	for i, r := range s.Rivals {
		if i > 0 {
			b.WriteString("\n")
		}
		b.WriteString("- ")
		if r.Option.Label != "" {
			b.WriteString(r.Option.Label)
			if r.Option.Text != "" {
				b.WriteString(" — ")
			}
		}
		b.WriteString(r.Option.Text)
	}
	return b.String()
}

// Origins — откуда взят каждый неверный вариант ({откуда}).
//
// Отдельной переменной, а не приписками в {круг}: круг модель перечисляет
// обучающемуся дословно, и «(соседнее положение той же единицы)» уехало бы
// в задачу вариантом ответа.
func (s AnswerSet) Origins() string {
	if len(s.Rivals) == 0 {
		return "(неверных вариантов не нашлось)"
	}
	var b strings.Builder
	for i, r := range s.Rivals {
		if i > 0 {
			b.WriteString("\n")
		}
		name := r.Option.Label
		if name == "" {
			name = r.Option.Text
		}
		fmt.Fprintf(&b, "- %s: %s", name, r.Whence)
	}
	return b.String()
}
