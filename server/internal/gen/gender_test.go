package gen

import "testing"

func TestРассогласованиеПоРодуВидно(t *testing.T) {
	// То, ради чего словарь и заведён: «женщина… потерял работу» читается
	// как небрежность и подрывает доверие ко всему тексту.
	text := "Пациентка 61 года обратилась к врачу. Полгода назад потерял работу."
	if got := DetectGender(text); got != GenderMixed {
		t.Fatalf("спор форм не замечен: %q", got)
	}
	male, female := GenderMarkers(text)
	if len(male) == 0 || len(female) == 0 {
		t.Fatalf("спорящие слова не названы: %v против %v", male, female)
	}
}

func TestСогласованныйТекстСпорнымНеОбъявляется(t *testing.T) {
	// Тревога у исправного текста приучает не верить тревоге.
	for текст, род := range map[string]Gender{
		"Пациентка обратилась к врачу. Была госпитализирована.": GenderFemale,
		"Пациент обратился к врачу. Был госпитализирован.":      GenderMale,
		"Срок рассмотрения — десять рабочих дней.":              GenderUnknown,
	} {
		if got := DetectGender(текст); got != род {
			t.Errorf("%q определён как %q, ожидали %q", текст, got, род)
		}
	}
}

func TestПравкаМеняетТолькоСловарныеФормы(t *testing.T) {
	// Правка снимает типовые огрехи, а не переписывает врачебный текст по
	// своему разумению: слово вне словаря обязано уцелеть как есть.
	было := "Пациент был направлен неврологом и уволился с должности инженера."
	стало := AgreeGender(было, GenderFemale)
	if стало != "Пациентка была направлена неврологом и уволилась с должности инженера." {
		t.Fatalf("получили %q", стало)
	}
}

func TestСловоВнутриСловаНеТрогается(t *testing.T) {
	// Границы слова в Go (\b) рассчитаны на латиницу: «был» нашёлся бы
	// внутри «забыл», и правка по образцу испортила бы чужое слово.
	было := "Забыл о приёме. Прибыл вовремя."
	if стало := AgreeGender(было, GenderFemale); стало != было {
		t.Fatalf("правка залезла внутрь слов: %q", стало)
	}
}

func TestЗнакиИЗаглавнаяПереживаютПравку(t *testing.T) {
	было := "Пациент, 61 года, доставлен: жаловался на боль."
	стало := AgreeGender(было, GenderFemale)
	if стало != "Пациентка, 61 года, доставлена: жаловалась на боль." {
		t.Fatalf("получили %q", стало)
	}
}

func TestПравкаНеМеняетУжеСогласованное(t *testing.T) {
	// Второй проход обязан не делать ничего: правка идёт и при повторе
	// задания, и при вычитке, и текст, меняющийся от числа проходов, —
	// это текст, о котором нельзя сказать, какой он.
	раз := AgreeGender("Пациент был доставлен.", GenderFemale)
	if два := AgreeGender(раз, GenderFemale); два != раз {
		t.Fatalf("второй проход изменил текст: %q против %q", два, раз)
	}
}

func TestБезНазванногоРодаПравкаНеИдёт(t *testing.T) {
	// «Смешанный» и «неизвестный» — не сторона. Выбери мы сторону сами,
	// правка привела бы текст к угаданному полу и сделала бы это молча.
	было := "Пациент был доставлен."
	for _, род := range []Gender{GenderUnknown, GenderMixed} {
		if стало := AgreeGender(было, род); стало != было {
			t.Errorf("род %q тронул текст: %q", род, стало)
		}
	}
}

func TestСторонуВСпореВыбираетПеревесПоВсемуУсловию(t *testing.T) {
	// Заголовок — одна строка, и она может оказаться как раз тем местом,
	// где модель сбилась. Перевес по всему условию так не ошибается.
	спорный := "Пациент М., 34 лет. Обратилась к врачу, предъявляла жалобы, " +
		"была госпитализирована."
	if got := DetectGender(спорный); got != GenderMixed {
		t.Fatalf("спор не замечен: %q", got)
	}
	if got := DominantGender(спорный); got != GenderFemale {
		t.Fatalf("сторону выбрали по заголовку, а не по условию: %q", got)
	}
}

