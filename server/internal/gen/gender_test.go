func TestЧужиеДействующиеЛицаОстаютсяПриСвоёмРоде(t *testing.T) {
	// Виньетка редко бывает только о больном: его приводит дочь, о запое
	// рассказывает брат. Слепое согласование по полу пациента превращало
	// их в «брат также сообщила» — огрех заметнее и грубее того, ради
	// устранения которого словарь заведён.
	tests := []struct {
		name, text string
		want       Gender
		out        string
	}{{
		name: "брат при пациентке",
		text: "Брат также сообщил, что пациентка употребляла кокаин.",
		want: GenderFemale,
		out:  "Брат также сообщил, что пациентка употребляла кокаин.",
	}, {
		name: "сестра при пациенте",
		text: "Сестра сообщила, что пациент перестал работать.",
		want: GenderMale,
		out:  "Сестра сообщила, что пациент перестал работать.",
	}, {
		// Починка уже испорченного: подлежащее известно, и форма
		// приводится к его роду в обе стороны.
		name: "испорченное чинится",
		text: "Брат сообщила о запое.",
		want: GenderFemale,
		out:  "Брат сообщил о запое.",
	}, {
		// Косвенный падеж подлежащим не бывает: действует пациентка.
		name: "со слов брата",
		text: "Со слов брата, пациент стал замкнут.",
		want: GenderFemale,
		out:  "Со слов брата, пациентка стала замкнута.",
	}, {
		// Умолчание в придаточном — всегда о больном.
		name: "придаточное о пациенте",
		text: "Мать сообщила, что перестал спать.",
		want: GenderFemale,
		out:  "Мать сообщила, что перестала спать.",
	}, {
		// Точка кончает предложение вместе с чужим подлежащим.
		name: "новое предложение о пациенте",
		text: "Брат сообщил о запое. Поступил в отделение.",
		want: GenderFemale,
		out:  "Брат сообщил о запое. Поступила в отделение.",
	}}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := AgreeGender(tc.text, tc.want); got != tc.out {
				t.Errorf("получили %q\nожидали  %q", got, tc.out)
			}
		})
	}
}

func TestЧужойРодНеРешаетЗаПациента(t *testing.T) {
	// У пациентки с братом и мужем мужских форм в тексте бывает больше,
	// чем женских. Считая их наравне, перевес назвал бы больную мужчиной
	// — а потом привёл бы к нему весь текст.
	текст := "Пациентка обратилась к врачу. Брат сообщил о запое. " +
		"Муж рассказал о конфликтах. Отец настоял на обследовании."

	if got := DominantGender(текст); got != GenderFemale {
		t.Errorf("род определён как %q, а больная — женщина", got)
	}
	// И спора здесь нет: чужие формы не рассогласование, а второе
	// действующее лицо.
	if got := DetectGender(текст); got != GenderFemale {
		t.Errorf("текст объявлен %q, хотя формы больной согласованы", got)
	}
	male, _ := GenderMarkers(текст)
	if len(male) != 0 {
		t.Errorf("чужие формы показаны спорными: %v", male)
	}
}
