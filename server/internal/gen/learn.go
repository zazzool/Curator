// Обучение конвейера на собственных замечаниях.
//
// Детектор подсказок складывает найденное в черновик, составитель это
// читает и правит — а модель, пишущая следующую задачу, о замечании не
// знает ничего и повторяет то же самое. Замечание, повторяющееся из
// задачи в задачу, — это не свойство задачи, а повадка генерации, и
// чинить её надо в задании модели. Свод правил уже умеет копить,
// созревать по кворуму и уходить в задание блоком; здесь только новый
// источник подтверждений.
//
// Три предосторожности против переобучения, и все три существенны:
//
//  1. **Текст правила пишет человек, а не модель.** Для рода замечания
//     он взят из встроенного свода, для протёкшего слова — собран кодом
//     по написанному заранее образцу. Позволить модели формулировать
//     правило по собственной ошибке значило бы копить в задании её же
//     домыслы — а задание читает та же модель.
//  2. **Кворум.** Выведенное правило уходит в задание после трёх РАЗНЫХ
//     заданий: одна ошибка — случайность, две — совпадение.
//  3. **Затухание.** Правило, которое давно не подтверждалось, гаснет
//     само: модель меняется, задание правится, и правило, описывающее
//     вчерашнюю ошибку, занимает место и деньги впустую.
//
// И отдельно — круг не замыкается на себе. Подтверждают правила
// замечания ДЕТЕКТОРА, а не самого свода: правило, подтверждающее себя
// собственной проверкой, набрало бы кворум на трёх задачах подряд и
// никогда бы не выдохлось.

// урокиРодов — какое правило свода отвечает за какой род замечания.
//
// Словарь закрытый и намеренно неполный: учиться стоит тому, что
// проверяется механически и повторяется. Род, которого здесь нет,
// проходит мимо обучения молча — это не потеря, а решение.
var урокиРодов = map[string]string{
	CueNamedSign:   "builtin:show-dont-name",
	CueTargetTitle: "builtin:no-target-title",
	CueBareLabel:   "builtin:no-label",
}

// learn подтверждает правила свода замечаниями одного задания.
//
// Ошибок не возвращает и задание не роняет. Обучение — довесок к
// генерации: задача, написанная и оплаченная, не должна теряться
// оттого, что не записалось правило о ней. Но и молчать об отказе
// нельзя — иначе обучение, переставшее работать, выглядело бы
// работающим: система просто ничему не училась бы, а сказать об этом
// было бы некому.
func (r *Runner) learn(ctx context.Context, job Job, check CueCheck) {
	if r.rules == nil || !check.Done || len(check.Cues) == 0 {
		return
	}
	// Кворум считается ЗАДАНИЯМИ, и это верно ровно потому, что до
	// детектора доходит только удавшееся задание: он стоит последним, за
	// написанием и обеими сверками. Неудавшееся задание черновика не
	// даёт, детектора не зовёт и подтверждений не приносит — а повторяют
	// как раз неудавшиеся. Повторный же заказ той же единицы второго
	// задания не заводит вовсе (IdemKey). Значит «три разных задания»
	// здесь и означает «три разных задачи», а не одну, пересчитанную
	// трижды. Изменись любое из этих трёх — кворум придётся считать
	// единицей источника, а не заданием.
	//
	// Один род — одно подтверждение, сколько бы слов ни протекло:
	// задача, где признак назван трижды, всё равно одна задача, и
	// считать её за три значило бы выдать кворум в одиночку. Само
	// задание вторым разом тоже не считается — это держит seen_jobs в
	// хранилище, а не совесть вызывающего.
	учтено := map[string]bool{}
	for _, cue := range check.Cues {
		id, ok := урокиРодов[cue.Kind]
		if !ok || учтено[cue.Kind] {
			continue
		}
		учтено[cue.Kind] = true
		if _, _, err := r.rules.Confirm(ctx, id, job.ID); err != nil {
			log.Printf("задание %d: правило %q не подтверждено: %v", job.ID, id, err)
		}
	}

	for _, proposal := range словесныеПравила(job.Plan, check.Cues) {
		rule, counted, err := r.rules.Propose(ctx, proposal, job.ID)
		if err != nil {
			log.Printf("задание %d: правило о слове не заведено: %v", job.ID, err)
			continue
		}
		if counted && rule.Status == rules.Active {
			// Созревание правила — событие, а не мелочь: с этой минуты
			// оно уходит в задание каждой следующей задачи по этому
			// источнику, и знать, когда это началось, нужно раньше, чем
			// кто-нибудь спросит «почему задачи изменились».
			log.Printf("свод: правило %q дозрело до кворума (%d подтверждения)",
				rule.ID, rule.Confirmations)
		}
	}
}

// словесныеПравила — правила о конкретных протёкших словах.
//
// Это и есть то частное, ради чего у правила вообще есть область
// действия: «в условиях по этому приказу слово «явка» протекало трижды»
// модели больше взять неоткуда, а общее «показывай, не называй» она уже
// читает из встроенного свода.
//
// Опознаватель правила ставится по ОСНОВЕ слова, а не по самому слову:
// «ритуально» и «ритуальный» — одна протечка в двух формах, и по
// словоформам ни одна из них не набрала бы кворума, а в списке правил
// их было бы три.
//
// Текст берёт слово в той форме, в какой оно попалось первым. Правило
// заводится один раз и потом не переписывается, так что форма
// закрепляется первая — и это лучше, чем основа: «слово „ритуа“»
// составитель не узнает.
func словесныеПравила(plan Plan, cues []Cue) []rules.Rule {
	if plan.SourceID <= 0 {
		return nil
	}
	out := []rules.Rule{}
	видели := map[string]bool{}
	for _, cue := range cues {
		if _, ok := урокиРодов[cue.Kind]; !ok {
			continue
		}
		for _, word := range cue.Terms {
			word = strings.TrimSpace(word)
			key := ключСлова(word)
			if word == "" || key == "" || видели[key] {
				continue
			}
			видели[key] = true
			out = append(out, правилоОСлове(plan, word, key))
		}
	}
	return out
}

// ключСлова — по чему словоформы сводятся в одно правило.
//
// Основы одного слова разной длины не равны: стеммер режет два последних
// знака, и «ритуально» даёт «ритуаль», а «ритуальный» — «ритуальн». По
// самим основам ни одна форма не набрала бы кворума, а в списке правил
// стояло бы три пункта об одном и том же.
//
// Поэтому ключ — начало основы длиной cueMinStem, РОВНО та мера, по
// которой сам детектор считает два слова одним (см. сверку основ по
// общему началу в LintDraft). Мера грубая: «примера» и «применение»
// сойдутся в одном ключе. Но огрублять её здесь сверх детекторской
// нельзя, и мельчить тоже: свод учился бы не на том, что нашёл
// детектор, и составитель видел бы правило о слове, которого ему не
// показывали.
func ключСлова(word string) string {
	stem := stemRu(strings.ToLower(strings.TrimSpace(word)))
	runes := []rune(stem)
	if len(runes) > cueMinStem {
		runes = runes[:cueMinStem]
	}
	return string(runes)
}

// правилоОСлове собирает правило по образцу, написанному здесь заранее.
//
// Ни одного слова от модели: образец человеческий, подставляется в него
// только само протёкшее слово и название источника.
func правилоОСлове(plan Plan, word, key string) rules.Rule {
	title := fmt.Sprintf("Слово «%s» в условии", word)
	// Имя стоит в списке одной строкой, и потолок у него в БАЙТАХ.
	// Кириллическое слово длиной в полтора десятка букв уже занимает
	// треть; обрезать надо по знакам, а не по байтам, иначе обрез
	// придётся на середину буквы.
	if len(title) > rules.TitleMax {
		runes := []rune(word)
		if len(runes) > 20 {
			word = string(runes[:20]) + "…"
		}
		title = fmt.Sprintf("Слово «%s» в условии", word)
	}
	return rules.Rule{
		ID:    fmt.Sprintf("lint:term:%d:%s", plan.SourceID, key),
		Title: title,
		Text: fmt.Sprintf("Не пиши в условии слово «%s» и однокоренные: покажи "+
			"обстоятельствами то, что оно означает.", word),
		Why: fmt.Sprintf("Слово протекало в условия по источнику «%s» и каждый раз "+
			"делало задачу сведением слова со словом.", plan.Title),
		Kind:   rules.KindSubstance,
		Source: rules.FromLint,
		Scope: rules.Scope{
			Sources: []int64{plan.SourceID},
			Nodes:   []string{NodeCompose},
		},
	}
}
