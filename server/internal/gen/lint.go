// Детектор подсказок в условии.
//
// Изъян известен как cueing: текст задачи сам называет ответ. У нас он
// конкретнее — задача учит НАХОДИТЬ в описании то, что подтверждает
// положение источника, и термин, названный в условии прямо, делает поиск
// тривиальным: обучающийся сводит слово со словом, а не картину с
// положением.
//
// # Почему проверкой, а не запретом в задании
//
// Донор потратил на это три дуэли промптов, и вывод там записан прямо:
// запретом это не лечится. Жёсткий запрет вместе с терминами размывает
// разметку положений, мягкий перестаёт работать. Зато протечка —
// свойство проверяемое, и проверка детерминирована, бесплатна и не
// зависит от сговорчивости модели. Задание остаётся просьбой; детектор —
// контролем.
//
// # Редкость меряется по самому источнику
//
// Слово, стоящее в положениях единичных единиц, называет предмет; слово,
// стоящее почти везде, — обычный язык этого документа. Считается это по
// положениям самого источника, а НЕ по встроенному списку терминов:
// источник любой, и всякое «если это МКБ» здесь было бы дефектом. У
// приказа о сроках редкими окажутся одни слова, у клинических
// рекомендаций — другие, и знать их заранее неоткуда.
//
// Донорский список «обычных врачебных слов» сюда намеренно НЕ перенесён:
// он построен по одному источнику и по нему же откалиброван — это ровно
// то встроенное знание, которого здесь быть не должно. Его место занимает
// мера по источнику, а связки русского языка («течение», «часть», «день»)
// перечислены отдельно и коротко: они связки в любом документе.

// Роды замечаний детектора. Закрытый словарь, и это не формальность: род
// — то, по чему считаются повторы, когда система учится на своих
// промахах. Текст сообщения для счёта не годится, он всякий раз свой.
const (
	// CueNamedSign — признак назван словом вместо показа.
	CueNamedSign = "named-sign"
	// CueTargetTitle — в условии стоит слово из названия эталона.
	CueTargetTitle = "target-title"
	// CueBareLabel — в условии стоит метка единицы источника.
	CueBareLabel = "bare-label"
)

// Cue — одна найденная подсказка.
type Cue struct {
	Kind string `json:"kind"`
	// Where — где нашлось: "segments" или "segments[2]".
	Where   string `json:"where"`
	Message string `json:"message"`

	// Terms — сами протёкшие слова, как они стояли в условии.
	//
	// Отдельным полем, а не разбором Message обратно. Свод учится на
	// повторяющемся слове — «в условиях по этому источнику слово X
	// протекло трижды» становится правилом про этот источник, — и
	// вытаскивать слово из готовой фразы значило бы завести вторую
	// сборку того же перечня. Расходятся такие пары молча: перепиши
	// фразу для составителя, и обучение начнёт копить пустоту.
	Terms []string `json:"terms,omitempty"`
}

// CueCheck — что детектор сказал о черновике.
//
// Исходов три — «чисто», «есть подсказки», «судить не могу», — и
// различаются они полем, а не уговором о том, как читать пустоту. Пустой
// список иначе означал бы разом две несовместимые вещи: подсказок нет и
// мерить было нечем. Прими второе за первое — и источник, у которого
// словаря не набралось, за одно утро объявил бы чистым весь набор.
//
// Тот же довод, что у Check и Proofread: у непроведённой проверки есть и
// признак, и причина, потому что молчание составитель читает как
// подтверждение.
type CueCheck struct {
	Done   bool   `json:"done"`
	Note   string `json:"note,omitempty"`
	Cues   []Cue  `json:"cues,omitempty"`
	Remark string `json:"remark,omitempty"`
}

// Clean — черновик проверен, и подсказок в нём нет. Именно проверен: у
// непроведённой проверки чистоты не бывает, бывает неизвестность.
func (c CueCheck) Clean() bool { return c.Done && len(c.Cues) == 0 }

// Remarks — что сказать составителю. Считается при чтении и не хранится —
// тот же довод, что у SiblingCheck.Remark.
func (c CueCheck) Remarks() string {
	if !c.Done {
		note := strings.TrimSpace(c.Note)
		if note == "" {
			note = "причина не записана"
		}
		return "подсказки в условии не искали: " + note
	}
	if len(c.Cues) == 0 {
		return ""
	}
	parts := make([]string, 0, len(c.Cues))
	for _, cue := range c.Cues {
		parts = append(parts, cue.Message)
	}
	return strings.Join(parts, ". ")
}

// Пороги редкости.
//
// Доля единиц источника, в чьих положениях стоит слово. Взяты у донора
// вместе с их калибровкой: у него на живом каталоге ловились «ритуалы»
// (0,007), «компульсии» (0,004), «ангедония» (0,022) и пропускались
// «настроение» (0,175), «тревога» (0,244) — у последних подсказку несёт
// не родовое слово, а редкое уточнение рядом.
const (
	// cueStatementShare — для слов из положений эталона.
	cueStatementShare = 0.12

	// cueTitleShare — для слов из названия эталона. Мягче: название
	// выдаёт ответ и частым словом.
	cueTitleShare = 0.36

	// cueMinStem — короче этого основы не сравниваются: трёхбуквенная
	// основа совпадает с чем угодно.
	cueMinStem = 4

	// cueMinUnits — ниже этого числа единиц редкость мерить не по чему, и
	// детектор отказывается судить, а не объявляет чисто. На источнике из
	// трёх единиц всякое слово стоит у трети — это шум, а не мера.
	cueMinUnits = 20
)

// связки — слова, которые в любом документе служат сцепкой, а не
// названием предмета.
//
// Список короткий и проверяется глазами. Он не про медицину и не про
// право: это русский язык. Всё, что зависит от предмета источника,
// отсеивает мера редкости по нему же.
var связки = []string{
	"который", "которая", "которое", "которые", "такой", "такая", "такое",
	"течение", "часть", "случай", "порядок", "срок", "день", "время",
	"неделя", "месяц", "год", "число", "более", "менее", "также", "либо",
	"если", "после", "перед", "может", "должен", "должна", "должно",
	"следует", "настоящий", "указанный", "соответствующий", "данный",
	"иной", "другой", "весь", "всего", "этот", "тот",
}

var связкиОснов = func() map[string]bool {
	out := make(map[string]bool, len(связки))
	for _, w := range связки {
		out[stemRu(w)] = true
	}
	return out
}()

// отрицание — отрицательный оборот внутри фрагмента предложения.
//
// Отрицательная находка подсказкой не считается: «навязчивые мысли
// пациентка отрицает» — обязательная запись, а не протечка. Отсутствие
// признака нельзя показать проявлением, его можно только назвать.
var отрицание = regexp.MustCompile(
	`отрица|не выявлен|не наблюда|отсутству|не описыва|не отмеча|` +
		`не обнаруж|минимальн|не было|нет |без |исключ|не испытыва|не сообща|` +
		`кратковремен|мимолетн|мимолётн|вторичн|незначительн|не приме|не предусмотр`)

// Lexicon — насколько обычно слово в этом источнике.
//
// Снимок на один заход: единицы источника правятся, и черновик,
// проверенный по одному словарю, а показанный с меркой другого, дал бы
// составителю замечание, которого проверка не находила.
type Lexicon struct {
	// Units — сколько единиц источника имеют положения.
	Units int
	// Stems — основа → у скольких единиц она встречается.
	Stems map[string]int
}

// Ready — есть ли чем мерить редкость.
func (l Lexicon) Ready() bool { return l.Units >= cueMinUnits }

// Share — доля единиц, в чьих положениях стоит основа.
func (l Lexicon) Share(stem string) float64 {
	if l.Units == 0 {
		return 1
	}
	return float64(l.Stems[stem]) / float64(l.Units)
}

// подозрительнаяОснова — основа и то, откуда она пришла.
type подозрительнаяОснова struct {
	stem   string
	origin string
}

const originTitle = "название эталона"

// порядокОснов выстраивает основы определённо.
//
// Слово в условии подходит сразу под несколько основ, и обход карты в Go
// случаен: слово доставалось бы то одному положению, то другому, а вместе
// с ним плясало бы и само число найденных подсказок — замечание ставится
// по одному на основу, и сошедшиеся на одной основе слова то попадали бы
// в список, то нет.
//
// Цена этому не в числах, а в доверии: составитель, перепроверивший ту же
// задачу и увидевший другой список, перестаёт верить и тем замечаниям,
// которые верны. Проверка обязана давать один ответ на один вход.
//
// Порядок — от длинной основы к короткой, при равной длине по алфавиту.
// Длинная точнее: она совпадает со словом почти целиком, и назвать
// составителю надо то положение, чья формулировка ближе к стоящему в
// условии. Алфавит развязывает равные и больше ничего не значит.
func порядокОснов(terms map[string]подозрительнаяОснова) []подозрительнаяОснова {
	out := make([]подозрительнаяОснова, 0, len(terms))
	for _, info := range terms {
		out = append(out, info)
	}
	sort.Slice(out, func(i, j int) bool {
		if len([]rune(out[i].stem)) != len([]rune(out[j].stem)) {
			return len([]rune(out[i].stem)) > len([]rune(out[j].stem))
		}
		return out[i].stem < out[j].stem
	})
	return out
}

// LintDraft ищет в условии подсказки.
//
// Отказ судить — не пустой список: без словаря источника у детектора нет
// не ответа, а самого вопроса.
func LintDraft(draft Draft, plan Plan, lex Lexicon) CueCheck {
	if !lex.Ready() {
		return CueCheck{Note: fmt.Sprintf(
			"у источника %d %s с положениями — редкость слов мерить не по чему",
			lex.Units, plan.UnitWord)}
	}

	terms := map[string]подозрительнаяОснова{}
	// Основа из положения и из названия разом остаётся положенческой: эта
	// формулировка точнее, и составителю полезнее увидеть её.
	for stem := range основы(plan.Unit.Title) {
		if негодная(stem) || lex.Share(stem) > cueTitleShare {
			continue
		}
		terms[stem] = подозрительнаяОснова{stem: stem, origin: originTitle}
	}
	for _, st := range plan.Statements {
		имя := strings.TrimSpace(st.Designation)
		if имя == "" {
			имя = plan.StatementWord
		}
		for stem := range основы(st.Body) {
			if негодная(stem) || lex.Share(stem) > cueStatementShare {
				continue
			}
			terms[stem] = подозрительнаяОснова{stem: stem, origin: имя}
		}
	}
	ordered := порядокОснов(terms)

	out := []Cue{}
	названо := []string{}
	изНазвания := []string{}
	// Те же находки голыми словами — для свода. Собираются здесь же и
	// тем же проходом: второй проход разошёлся бы с первым молча.
	словаПоложений := []string{}
	словаНазвания := []string{}
	отмечено := map[string]bool{}

	// Метки единиц круга, записанные в условии буквально: это готовый
	// ответ, и никакой редкости для него мерить не надо.
	метки := []string{plan.Unit.Label}
	for _, s := range plan.Siblings {
		метки = append(метки, s.Label)
	}

	for i, seg := range draft.Segments {
		lower := strings.ToLower(seg.Text)
		for _, label := range метки {
			label = strings.TrimSpace(label)
			if label == "" || отмечено["метка:"+label] {
				continue
			}
			if !меткаВТексте(lower, strings.ToLower(label)) {
				continue
			}
			отмечено["метка:"+label] = true
			out = append(out, Cue{
				Kind:  CueBareLabel,
				Where: fmt.Sprintf("segments[%d]", i),
				Message: fmt.Sprintf(
					"в условии стоит метка %s «%s» — это готовый ответ",
					plan.UnitWord, label),
			})
		}
		if len(ordered) == 0 {
			continue
		}
		// По фрагментам предложений: отрицание действует внутри своего
		// фрагмента, а не на весь абзац — «срок не продлевается, но
		// заявление подано повторно» отрицает только первое.
		for _, fragment := range strings.FieldsFunc(lower, func(r rune) bool {
			return r == '.' || r == ';'
		}) {
			отрицаемый := отрицание.MatchString(fragment)
			for _, word := range strings.FieldsFunc(fragment, func(r rune) bool {
				return !unicode.IsLetter(r)
			}) {
				word = strings.ReplaceAll(word, "ё", "е")
				runes := []rune(word)
				if len(runes) < cueMinStem || !unicode.Is(unicode.Cyrillic, runes[0]) {
					continue
				}
				ws := stemRu(word)
				if связкиОснов[ws] {
					continue
				}
				// Основы сравниваются по общему началу, а не на равенство:
				// стеммер режет два последних знака, и словоформы разной
				// длины дают разные основы — «ритуалы» → «ритуа», но
				// «ритуал» → «риту». Общее начало от четырёх знаков сводит
				// их вместе, не сводя «ритм» с «ритуалом».
				// Совпавших основ может быть несколько, и первая не
				// всегда та. Основа, пришедшая и из положения, и из
				// названия, остаётся положенческой (см. сбор terms
				// выше) — но там это держится на равенстве основ, а
				// здесь они сводятся по общему началу, и равенства
				// нет: «ритуальн» из названия и «ритуал» из положения
				// суть разные записи карты. Возьми первую по длине —
				// и слово, стоящее в обоих, уехало бы в замечание о
				// названии, где формулировки положения не видно.
				// Поэтому положенческое совпадение старше, а внутри
				// каждого рода по-прежнему старше длинное.
				matched, origin := "", ""
				for _, info := range ordered {
					if len([]rune(info.stem)) < cueMinStem {
						continue
					}
					if !strings.HasPrefix(ws, info.stem) && !strings.HasPrefix(info.stem, ws) {
						continue
					}
					if matched == "" {
						matched, origin = info.stem, info.origin
					}
					if info.origin != originTitle {
						matched, origin = info.stem, info.origin
						break
					}
				}
				if matched == "" || отмечено[matched] || отрицаемый {
					continue
				}
				отмечено[matched] = true
				if origin == originTitle {
					изНазвания = append(изНазвания, "«"+word+"»")
					словаНазвания = append(словаНазвания, word)
				} else {
					названо = append(названо, fmt.Sprintf("«%s» — %s", word, origin))
					словаПоложений = append(словаПоложений, word)
				}
			}
		}
	}

	// По одному замечанию на род, а не на слово. У донора на живой
	// генерации набиралось до шестнадцати замечаний — список, который
	// перестают читать. Составителю нужен один пункт с перечнем.
	if len(названо) > 0 {
		out = append(out, Cue{
			Kind:  CueNamedSign,
			Where: "segments",
			// Через точку с запятой: внутри самих формулировок положений
			// запятые обычны, и по запятым перечень не разбирается.
			Message: "в условии названо то, что надо показать: " + strings.Join(названо, "; "),
			Terms:   словаПоложений,
		})
	}
	if len(изНазвания) > 0 {
		out = append(out, Cue{
			Kind:  CueTargetTitle,
			Where: "segments",
			Message: "в условии стоят слова из названия эталона: " +
				strings.Join(изНазвания, ", ") + " — это готовый ответ",
			Terms: словаНазвания,
		})
	}
	return CueCheck{Done: true, Cues: out}
}

// меткаВТексте — стоит ли метка в тексте отдельным словом.
//
// Отдельным, а не вхождением подстроки: метка «3.1» нашлась бы внутри
// «13.14», а односимвольная «а» — внутри каждого второго слова.
//
// По рунам, а не по байтам: сосед кириллической буквы в UTF-8 — это её
// второй байт, и проверка соседа байтом объявила бы границей середину
// слова.
func меткаВТексте(text, label string) bool {
	hay, needle := []rune(text), []rune(label)
	if len(needle) == 0 || len(needle) > len(hay) {
		return false
	}
	for i := 0; i+len(needle) <= len(hay); i++ {
		if string(hay[i:i+len(needle)]) != label {
			continue
		}
		if i > 0 && граничный(hay[i-1]) {
			continue
		}
		if i+len(needle) < len(hay) && граничный(hay[i+len(needle)]) {
			continue
		}
		return true
	}
	return false
}

func граничный(r rune) bool {
	return unicode.IsLetter(r) || unicode.IsDigit(r) || r == '.' || r == '-'
}

// негодная — основа, по которой судить нельзя.
func негодная(stem string) bool {
	return len([]rune(stem)) < cueMinStem || связкиОснов[stem]
}

// основы — основы значимых слов текста.
func основы(text string) map[string]bool {
	out := map[string]bool{}
	for _, word := range strings.FieldsFunc(strings.ToLower(text), func(r rune) bool {
		return !unicode.IsLetter(r)
	}) {
		word = strings.ReplaceAll(word, "ё", "е")
		runes := []rune(word)
		if len(runes) < cueMinStem || !unicode.Is(unicode.Cyrillic, runes[0]) {
			continue
		}
		out[stemRu(word)] = true
	}
	return out
}

// stemRu — грубое усечение окончания.
//
// Полной морфологии тут нет и не нужно: основы сравниваются по общему
// началу, и хвост в два знака съедает разницу падежей, не сводя разные
// слова. Свой, а не из зависимости: одна функция в семь строк дешевле
// шестой зависимости в проекте, где их пять.
func stemRu(word string) string {
	runes := []rune(word)
	if len(runes) <= cueMinStem {
		return word
	}
	cut := len(runes) - 2
	if cut < cueMinStem {
		cut = cueMinStem
	}
	return string(runes[:cut])
}

// SourceLexicon — словарь источника: у скольких единиц встречается каждая
// основа.
//
// Считается по положениям, а не по названиям: названия коротки и дают
// слишком мало слов, чтобы редкость по ним что-то значила.
func (j *Jobs) SourceLexicon(ctx context.Context, sourceID int64) (Lexicon, error) {
	rows, err := j.gate.Query(ctx,
		`SELECT unit_label, string_agg(body_md, ' ')
		   FROM source_unit_statements
		  WHERE source_id = $1
		  GROUP BY unit_label`, sourceID)
	if err != nil {
		return Lexicon{}, fmt.Errorf("словарь источника %d не прочитан: %w", sourceID, err)
	}
	defer rows.Close()

	lex := Lexicon{Stems: map[string]int{}}
	for rows.Next() {
		var label, body string
		if err := rows.Scan(&label, &body); err != nil {
			return Lexicon{}, fmt.Errorf("строка словаря не разобрана: %w", err)
		}
		lex.Units++
		for stem := range основы(body) {
			lex.Stems[stem]++
		}
	}
	if err := rows.Err(); err != nil {
		return Lexicon{}, fmt.Errorf("словарь источника дочитан не до конца: %w", err)
	}
	return lex, nil
}
