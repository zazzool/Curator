func TestБезСловаряДетекторОтказываетсяСудитьАНеОбъявляетЧисто(t *testing.T) {
	// Пустота у чистой задачи и пустота у непроверенной — разные вещи.
	// Слей их, и источник, у которого словаря не набралось, объявил бы
	// чистым весь набор за одно утро.
	check := LintDraft(Draft{Segments: []Segment{{Text: "Ответ направлен ритуально."}}},
		планПодсказок(), словарь("одна единица", "вторая единица"))
	if check.Done {
		t.Fatal("детектор судил по словарю из двух единиц")
	}
	if check.Clean() {
		t.Fatal("несостоявшаяся проверка объявлена чистой")
	}
	if !strings.Contains(check.Remarks(), "не по чему") {
		t.Fatalf("причина не названа: %q", check.Remarks())
	}
}

func TestРедкоеСловоИзПоложенияНазваноПрямо(t *testing.T) {
	// То, ради чего детектор и есть: обучающийся сводит слово со словом,
	// а не описание с положением.
	draft := Draft{Segments: []Segment{
		{Text: "Заявление подано."},
		{Text: "Ответ был направлен ритуально, с соблюдением обряда."},
	}}
	check := LintDraft(draft, планПодсказок(), большойСловарь())
	if !check.Done {
		t.Fatalf("детектор не состоялся: %q", check.Note)
	}
	if check.Clean() {
		t.Fatal("протечка пропущена")
	}
	var найдено *Cue
	for i := range check.Cues {
		if check.Cues[i].Kind == CueNamedSign {
			найдено = &check.Cues[i]
		}
	}
	if найдено == nil {
		t.Fatalf("род замечания не тот: %+v", check.Cues)
	}
	if !strings.Contains(найдено.Message, "абз. 1") {
		t.Fatalf("не сказано, из какого положения слово: %q", найдено.Message)
	}
}

func TestСловоИзПоложенияИНазванияОстаётсяПоложенческим(t *testing.T) {
	// «ритуально» стоит и в названии эталона, и в формулировке абзаца.
	// Замечание о названии говорит «это готовый ответ» и на том
	// кончается; замечание о положении называет абзац, чью формулировку
	// составителю и надо переписать показом. Сведи их в пользу названия —
	// и составитель получит упрёк без адреса.
	draft := Draft{Segments: []Segment{{Text: "Ответ направлен ритуально."}}}
	check := LintDraft(draft, планПодсказок(), большойСловарь())
	for _, c := range check.Cues {
		if c.Kind == CueTargetTitle {
			t.Fatalf("слово из положения ушло в замечание о названии: %q", c.Message)
		}
	}
}

func TestСловоТолькоИзНазванияЭталонаЭтоГотовыйОтвет(t *testing.T) {
	// «сопровождение» в положениях не стоит — только в названии эталона.
	// Названо оно в условии, и узнавать обучающемуся больше нечего.
	draft := Draft{Segments: []Segment{{Text: "Назначено сопровождение заявителя."}}}
	check := LintDraft(draft, планПодсказок(), большойСловарь())
	var найдено bool
	for _, c := range check.Cues {
		if c.Kind == CueTargetTitle {
			найдено = true
		}
	}
	if !найдено {
		t.Fatalf("слово из названия эталона пропущено: %+v", check.Cues)
	}
}

func TestОбычноеСловоИсточникаПодсказкойНеСчитается(t *testing.T) {
	// «Заявление» и «направляется» стоят у всех единиц: это язык
	// документа, а не название предмета. Замечание на каждое такое слово
	// убило бы доверие к детектору целиком.
	draft := Draft{Segments: []Segment{
		{Text: "Заявление рассматривается, ответ направляется заявителю."},
	}}
	check := LintDraft(draft, планПодсказок(), большойСловарь())
	if !check.Done {
		t.Fatalf("детектор не состоялся: %q", check.Note)
	}
	if !check.Clean() {
		t.Fatalf("обычные слова источника названы подсказками: %+v", check.Cues)
	}
}

func TestОтрицательнаяНаходкаПодсказкойНеСчитается(t *testing.T) {
	// «Ритуального сопровождения не было» — это обязательная запись, а не
	// протечка: отсутствие нельзя показать, его можно только назвать.
	draft := Draft{Segments: []Segment{
		{Text: "Заявление подано; ритуального сопровождения не было."},
	}}
	check := LintDraft(draft, планПодсказок(), большойСловарь())
	if !check.Clean() {
		t.Fatalf("отрицательная находка засчитана протечкой: %+v", check.Cues)
	}
}

func TestОтрицаниеДействуетТолькоВСвоёмФрагменте(t *testing.T) {
	// «Отказа не было, ответ направлен ритуально» отрицает только первое.
	// Считай мы отрицание на весь абзац, одна отрицательная запись
	// глушила бы протечку во всём остальном тексте.
	draft := Draft{Segments: []Segment{
		{Text: "Отказа не было. Ответ направлен ритуально."},
	}}
	check := LintDraft(draft, планПодсказок(), большойСловарь())
	if check.Clean() {
		t.Fatal("отрицание в соседнем предложении заглушило протечку")
	}
}

