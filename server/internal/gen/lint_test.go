func TestОдинОтветНаОдинВход(t *testing.T) {
	// Основы перебираются в определённом порядке, а не обходом карты:
	// составитель, перепроверивший ту же задачу и увидевший другой
	// список, перестаёт верить и тем замечаниям, которые верны.
	draft := Draft{Segments: []Segment{
		{Text: "Ответ направлен ритуально, обряд соблюдён ритуально."},
	}}
	первый := LintDraft(draft, планПодсказок(), большойСловарь())
	for i := 0; i < 20; i++ {
		ещё := LintDraft(draft, планПодсказок(), большойСловарь())
		if len(ещё.Cues) != len(первый.Cues) {
			t.Fatalf("число замечаний пляшет: %d против %d", len(ещё.Cues), len(первый.Cues))
		}
		for j := range ещё.Cues {
			if ещё.Cues[j].Message != первый.Cues[j].Message {
				t.Fatalf("замечание пляшет:\n%q\n%q", ещё.Cues[j].Message, первый.Cues[j].Message)
			}
		}
	}
}

func TestЗамечаниеОдноНаРодАНеНаСлово(t *testing.T) {
	// У донора на живой генерации набиралось до шестнадцати замечаний —
	// список, который перестают читать.
	план := планПодсказок()
	план.Statements = []StatementRef{{
		Designation: "абз. 1",
		Body:        "Ответ направляется ритуально, обрядово и церемониально.",
	}}
	draft := Draft{Segments: []Segment{
		{Text: "Ответ направлен ритуально, обрядово и церемониально."},
	}}
	check := LintDraft(draft, план, большойСловарь())
	named := 0
	for _, c := range check.Cues {
		if c.Kind == CueNamedSign {
			named++
		}
	}
	if named != 1 {
		t.Fatalf("замечаний о названном %d вместо одного: %+v", named, check.Cues)
	}
}

func TestPgСловарьИсточникаСчитаетсяПоЕдиницамАНеПоПоложениям(t *testing.T) {
	// Слово, стоящее дважды в одной единице, редким быть не перестаёт:
	// мера — у скольких ЕДИНИЦ оно встречается.
	ctx := context.Background()
	gate := testGate(t)
	sourceID := источник(t, gate)

	lex, err := NewJobs(gate).SourceLexicon(ctx, sourceID)
	if err != nil {
		t.Fatal(err)
	}
	// У источника проверки две единицы с положениями: 3.1 и 3.2.
	if lex.Units != 2 {
		t.Fatalf("единиц со словарём %d вместо двух", lex.Units)
	}
	if lex.Ready() {
		t.Fatal("словарь из двух единиц объявлен годным для меры редкости")
	}
	if lex.Stems[stemRu("рассмотрения")] == 0 && lex.Stems[stemRu("срок")] == 0 {
		t.Fatalf("словарь пуст: %+v", lex.Stems)
	}
}
