// Согласование по роду в текстах задач.
//
// Задача пишется про конкретного человека, и весь текст обязан быть с ним
// согласован: «пациентка… обратилась… была доставлена». Рассогласование
// («женщина 61 года… потерял работу… приведён дочерью») читается как
// небрежность и подрывает доверие к тексту, который составитель готовится
// показать обучающимся.
//
// Берётся оно из одного места: модель сбивается, если пол пациента ей
// прямо не назвать. Виньетку она пишет за один проход и следит
// одновременно за клиникой, за положениями источника и за форматом
// ответа — язык при этом идёт последним, и это видно в готовых задачах:
// «Пациент» в заголовке и «Пациентка» в третьей фразе.
//
// Здесь — распознавание рода по тексту и правка закрытого набора
// врачебных форм. Полной морфологии тут нет и быть не должно: словарь
// узкий и проверяемый, а всё, что в него не попало, выносится
// составителю замечанием — молча переписывать врачебный текст опаснее,
// чем оставить в нём огрех. Именно поэтому словарь и не закрывает задачу:
// «пошёл», «уволился с должности инженера» и рассогласованный причастный
// оборот в него не войдут никогда.

// Gender — род, с которым согласован текст.
type Gender string

const (
	GenderUnknown Gender = ""    // признаков рода нет — годится куда угодно
	GenderMale    Gender = "m"   //
	GenderFemale  Gender = "f"   //
	GenderMixed   Gender = "mix" // есть и те и другие: это ошибка
)

