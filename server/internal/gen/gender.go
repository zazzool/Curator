// patientWords — слова, которыми в виньетке называют самого больного.
//
// Возвращают согласование пациенту после чужого подлежащего: «мать
// сообщила, что пациентка перестала работать» — «перестала» здесь про
// больную, а не про мать.
var patientWords = map[string]bool{
	"пациент": true, "пациентка": true, "пациента": true, "пациентки": true,
	"больной": true, "больная": true, "больного": true, "больную": true,
	"он": true, "она": true,
}

// maleForms и femaleForms — те же пары, разложенные для поиска.
var maleForms, femaleForms = func() (map[string]string, map[string]string) {
	m := make(map[string]string, len(genderPairs))
	f := make(map[string]string, len(genderPairs))
	for _, pair := range genderPairs {
		// Многословные формы («не замужем») в поиск по словам не годятся:
		// они распознаются только как цель замены.
		if !strings.Contains(pair[0], " ") {
			m[pair[0]] = pair[1]
		}
		if !strings.Contains(pair[1], " ") {
			f[pair[1]] = pair[0]
		}
	}
	return m, f
}()

// subjectTracker следит, о ком идёт речь.
//
// Ведёт одно значение — род чужого действующего лица, если оно сейчас
// подлежащее, и GenderUnknown, когда речь о пациенте. Правил три, и
// каждое взято из того, как виньетки написаны на самом деле:
//
//   - «Брат сообщил…» — чужое лицо в именительном падеже становится
//     подлежащим;
//   - «…что пациентка перестала работать» — слово о больном возвращает
//     согласование ему, даже посреди чужой фразы;
//   - «Мать сообщила, что перестала спать» — придаточное с «что» и конец
//     предложения сбрасывают подлежащее к пациенту, потому что в
//     виньетке умолчание всегда о нём.
//
// Больше правил здесь не нужно и не будет: полной морфологии тут нет по
// замыслу (см. заголовок файла), а угадывание портит текст ровно так же,
// как его портило слепое согласование.
type subjectTracker struct{ other Gender }

// step принимает разделитель перед словом и само слово.
func (s *subjectTracker) step(before, word string) {
	if strings.ContainsAny(before, ".!?;") || strings.Contains(before, ",") &&
		strings.Contains(strings.ToLower(word), "что") {
		s.other = GenderUnknown
	}

	lower := strings.ToLower(word)
	if lower == "что" {
		s.other = GenderUnknown
		return
	}
	if patientWords[lower] {
		s.other = GenderUnknown
		return
	}
	if g, ok := otherPersons[lower]; ok {
		s.other = g
	}
}

// scanText обходит слова, сообщая, кому принадлежит каждое.
//
// owner — род чужого действующего лица или GenderUnknown, когда речь о
// пациенте. Разделители нужны самому обходу: на точке подлежащее
// сбрасывается.
func scanText(text string, visit func(word string, owner Gender)) {
	var subject subjectTracker
	eachWord(text, func(before, word string) {
		subject.step(before, word)
		visit(word, subject.other)
	})
}

// DetectGender определяет, с каким родом согласован текст.
//
// GenderMixed означает, что в тексте есть и мужские, и женские формы —
// то самое рассогласование, ради которого всё это заведено. Формы при
// чужом подлежащем в счёт не идут: «пациентка… брат сообщил» — это не
// спор о поле больной, а обычная виньетка с двумя действующими лицами.
func DetectGender(text string) Gender {
	male, female := false, false
	scanText(text, func(word string, owner Gender) {
		if owner != GenderUnknown {
			return
		}
		lower := strings.ToLower(word)
		if _, ok := maleForms[lower]; ok {
			male = true
		}
		if _, ok := femaleForms[lower]; ok {
			female = true
		}
	})

	switch {
	case male && female:
		return GenderMixed
	case male:
		return GenderMale
	case female:
		return GenderFemale
	}
	return GenderUnknown
}

// DominantGender — какого рода в тексте больше.
//
// Нужен там, где ответ «смешанный» бесполезен: чтобы согласовать текст,
// надо выбрать сторону, а DetectGender на спорном тексте разводит руками.
//
// Сторона считается по всему условию, а не по заголовку. Заголовок —
// одна строка, и она может оказаться как раз тем местом, где модель
// сбилась: «Пациент М., 34 лет» над женским текстом решил бы спор в
// пользу описки. Перевес по всему условию так не ошибается.
//
// Ровный счёт разрешается началом текста: пациента представляют в первой
// фразе. «Пациент К., 47 лет, токарь, направлен неврологом» против
// «обратилась, предъявляла» — две формы на две, а больной здесь
// очевидно один, и назван он в начале.
func DominantGender(text string) Gender {
	var male, female int
	first := GenderUnknown

	scanText(text, func(word string, owner Gender) {
		// Чужие формы в счёт не идут: у пациентки с братом и мужем
		// мужских форм в тексте бывает больше, чем женских, и перевес
		// назвал бы больную мужчиной — а потом привёл бы к нему весь текст.
		if owner != GenderUnknown {
			return
		}
		lower := strings.ToLower(word)
		if _, ok := maleForms[lower]; ok {
			male++
			if first == GenderUnknown {
				first = GenderMale
			}
		}
		if _, ok := femaleForms[lower]; ok {
			female++
			if first == GenderUnknown {
				first = GenderFemale
			}
		}
	})

	switch {
	case male > female:
		return GenderMale
	case female > male:
		return GenderFemale
	}
	// Поровну — верим началу. Ни одной формы — верить нечему.
	return first
}

// AgreeGender приводит текст к нужному роду.
//
// Меняются только слова из словаря и только целиком. Всё остальное
// остаётся как есть: задача этой правки — снять типовые огрехи, а не
// переписать врачебный текст по своему разумению.
//
// Формы при чужом подлежащем согласуются с ним, а не с пациентом:
// виньетка про больную, правленная наравне со всеми, получала «брат
// также сообщила» — огрех заметнее и грубее того, ради устранения
// которого словарь заведён. Заодно это чинит уже испорченное:
// подлежащее известно, и форма приводится к его роду в обе стороны.
func AgreeGender(text string, want Gender) string {
	if want != GenderMale && want != GenderFemale {
		return text
	}

	var subject subjectTracker
	return mapWords(text, func(before, word string) string {
		subject.step(before, word)

		// Кому принадлежит форма, тому она и подчиняется.
		target := want
		if subject.other != GenderUnknown {
			target = subject.other
		}
		from := femaleForms
		if target == GenderFemale {
			from = maleForms
		}

		replacement, ok := from[strings.ToLower(word)]
		if !ok {
			return word
		}
		return matchCase(word, replacement)
	})
}

// GenderMarkers перечисляет найденные в тексте формы каждого рода.
//
// Нужны замечанию составителю: сказать «в условии смешаны формы» мало,
// ему надо показать, какие именно слова спорят между собой.
func GenderMarkers(text string) (male, female []string) {
	seenM, seenF := map[string]bool{}, map[string]bool{}
	scanText(text, func(word string, owner Gender) {
		// Чужие формы не спорят с полом больного, и показывать их как
		// спорные значит отправить составителя искать несуществующий огрех.
		if owner != GenderUnknown {
			return
		}
		lower := strings.ToLower(word)
		if _, ok := maleForms[lower]; ok && !seenM[lower] {
			seenM[lower] = true
			male = append(male, lower)
		}
		if _, ok := femaleForms[lower]; ok && !seenF[lower] {
			seenF[lower] = true
			female = append(female, lower)
		}
	})
	return male, female
}

// --- Работа со словами ---

func isWordRune(r rune) bool {
	return unicode.IsLetter(r) || unicode.IsDigit(r) || r == '-' || r == 'ё' || r == 'Ё'
}

// eachWord проходит по словам, сообщая, что стояло перед каждым.
//
// Разделитель нужен для разбора подлежащего: точка кончает предложение и
// вместе с ним чужое действующее лицо. Замена по регулярному выражению
// здесь не годится: границы слова в Go (\b) рассчитаны на латиницу и на
// кириллице срабатывают не там, где нужно, — «был» нашёлся бы внутри
// «забыл».
func eachWord(text string, visit func(before, word string)) {
	runes := []rune(text)
	sep := make([]rune, 0, 8)
	for i := 0; i < len(runes); {
		if !isWordRune(runes[i]) {
			sep = append(sep, runes[i])
			i++
			continue
		}
		start := i
		for i < len(runes) && isWordRune(runes[i]) {
			i++
		}
		visit(string(sep), string(runes[start:i]))
		sep = sep[:0]
	}
}

// mapWords проходит по словам, сохраняя всё, что между ними.
func mapWords(text string, fn func(before, word string) string) string {
	var b strings.Builder
	b.Grow(len(text))

	runes := []rune(text)
	sep := make([]rune, 0, 8)
	for i := 0; i < len(runes); {
		if !isWordRune(runes[i]) {
			sep = append(sep, runes[i])
			b.WriteRune(runes[i])
			i++
			continue
		}
		start := i
		for i < len(runes) && isWordRune(runes[i]) {
			i++
		}
		b.WriteString(fn(string(sep), string(runes[start:i])))
		sep = sep[:0]
	}
	return b.String()
}

// matchCase возвращает замену с заглавной буквы, если такой была исходная.
func matchCase(original, replacement string) string {
	src := []rune(original)
	if len(src) == 0 || !unicode.IsUpper(src[0]) {
		return replacement
	}
	dst := []rune(replacement)
	dst[0] = unicode.ToUpper(dst[0])
	return string(dst)
}
