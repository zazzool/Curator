// Разбор расхождения слепой сверки.
//
// # Зачем нужен второй вопрос
//
// Слепая сверка показывает модели условие и перемешанные варианты и
// спрашивает, какой верен. Ничего сверх этого ей не даётся — подскажи, и
// она согласится с подсказкой, а проверка выродится в самоподтверждение.
// Это верно для ВОПРОСА и неверно для ПРИГОВОРА.
//
// Разница в том, чего каждая из них стоит. Слепая сверка выбирает из
// списка названий, и выбирает по тому, что помнит: два соседних пункта
// одного приказа различаются одним сроком или одним числом, а в списке
// они стоят похожими строками. Ошибка тут — не ошибка рассуждения, а
// ошибка узнавания: модель рассуждает про заказанное и отмечает соседа.
// Расхождение при этом задерживает исправную задачу, и задерживает её
// молча — составитель видит «сверка не сошлась» и не знает, спорить ли.
//
// Отсюда второй вопрос, и он ЗРЯЧИЙ: модели дают условие, положения
// заказанной единицы и положения её соседей и просят сказать, чему
// условие отвечает лучше. Здесь подсказка не вредит, а наоборот —
// сравнивать надо по положениям, а не по памяти о названиях.
//
// # Три свойства, которые делают это безопасным
//
// ПЕРВОЕ. Спрашивают только при расхождении. Сошедшаяся сверка второго
// вопроса не требует и денег не стоит.
//
// ВТОРОЕ. Разбор не отменяет слепую сверку, а стоит рядом с ней.
// Verdict.Agrees остаётся тем, что ответила слепая сверка, и переписать
// его разбором значило бы стереть единственную запись о том, что она
// вообще возражала. Решает же итог `Check.Agrees()` — он и смотрит на
// оба.
//
// ТРЕТЬЕ. Подтверждённое расхождение остаётся ошибкой. Смягчается один
// исход — «сверка рассудила верно, а отметила не то», — и в замечании
// это сказано вслух.
//
// # Почему мерилом служат соседи
//
// Соседи по родителю — это ровно то, с чем заказанную единицу можно
// перепутать; ими же собран круг вариантов, из которого сверка и
// выбирала. Дай мы разбору одну заказанную единицу, вопрос выродился бы
// в «подходит ли условие сюда», на который ответ «да» почти всегда:
// условие по ней и писалось.

// Arbitration — ответ разбора.
type Arbitration struct {
	// Verdict — чему условие отвечает лучше: "ordered" (заказанной
	// единице), "found" (одному из соседей), "unclear" (по тексту не
	// решить).
	//
	// Три исхода, а не два, и третий обязателен. Заставь мы модель
	// выбрать из двух — она выберет, и выбор наугад пришёл бы
	// составителю под видом разбора.
	Verdict string `json:"verdict"`

	// Which — метка соседа, если победил сосед. Пусто у прочих исходов.
	Which string `json:"which,omitempty"`

	// Why — решающий признак и его место в тексте. Читает составитель, и
	// по этой строке он решает, спорить ли с разбором.
	Why string `json:"why"`
}

// Исходы разбора. Словарь закрыт: исход, пришедший строкой от модели и
// не узнанный, разбором не считается вовсе — см. ParseArbitration.
const (
	ArbitrationOrdered = "ordered"
	ArbitrationFound   = "found"
	ArbitrationUnclear = "unclear"
)

// Clears — разбор снял расхождение.
//
// Только "ordered": «не решить» расхождения не снимает. Считай мы
// неясность оправданием, разбор превратился бы в способ пропускать
// спорное — и делал бы это тем чаще, чем хуже написано условие.
func (a Arbitration) Clears() bool { return a.Verdict == ArbitrationOrdered }

// ArbitrationSchema — строгая схема ответа разбора.
var ArbitrationSchema = json.RawMessage(`{
	"type": "object",
	"properties": {
		"verdict": {"type": "string", "enum": ["ordered", "found", "unclear"]},
		"which": {"type": "string"},
		"why": {"type": "string"}
	},
	"required": ["verdict", "why"],
	"additionalProperties": false
}`)

// ParseArbitration разбирает ответ модели.
//
// Непонятое не применяется: исход не из словаря — это отказ разбора, а
// не разбор с неизвестным итогом. Прими мы такой ответ, он попал бы в
// черновик исходом, которого не понимает ни одна ветка кода, и
// расхождение молча осталось бы неразобранным, выглядя разобранным.
func ParseArbitration(answer string) (Arbitration, error) {
	text := strings.TrimSpace(answer)
	if fenced := unfence(text); fenced != "" {
		text = fenced
	}
	var out Arbitration
	if err := json.Unmarshal([]byte(text), &out); err != nil {
		return Arbitration{}, fmt.Errorf("ответ разбора не разобран: %w", err)
	}
	switch out.Verdict {
	case ArbitrationOrdered, ArbitrationFound, ArbitrationUnclear:
	default:
		return Arbitration{}, fmt.Errorf("разбор вернул неизвестный исход %q", out.Verdict)
	}
	out.Which = strings.TrimSpace(out.Which)
	out.Why = strings.TrimSpace(out.Why)
	if out.Verdict != ArbitrationFound {
		// Метка соседа при «заказанное точнее» бессмысленна, и оставленная
		// она читалась бы как «победил вот этот сосед».
		out.Which = ""
	}
	return out, nil
}

// arbitrate — узел разбора расхождения.
//
// Отказа наружу не несёт, как и сама сверка: разбор уточняет уже
// оплаченную проверку, и ронять из-за него написанную задачу нельзя. Не
// вышло — остаётся вердикт слепой сверки, а в примечании сказано, что
// разбора не было. Молчание здесь было бы хуже: составитель принял бы
// неразобранное расхождение за разобранное и подтверждённое.
func (r *Runner) arbitrate(ctx context.Context, job Job, draft Draft) (*Arbitration, error) {
	plan := job.Plan
	if len(plan.Siblings) == 0 {
		// Спор двух сторон требует двух сторон: без соседей сравнивать
		// заказанную единицу не с чем, и вопрос выродился бы в «подходит
		// ли условие сюда».
		return nil, fmt.Errorf("у заказанной %s нет соседей: сравнивать не с чем", plan.UnitWord)
	}
	if strings.TrimSpace(plan.StatementsMd) == "" {
		return nil, fmt.Errorf("у заказанной %s нет положений: мерить нечем", plan.UnitWord)
	}
	neighbours := neighbourBlock(plan)
	if neighbours == "" {
		// Соседи без положений — это те же названия, по памяти о которых
		// слепая сверка и ошиблась. Второй такой вопрос ничего не добавит.
		return nil, fmt.Errorf("у соседей нет положений: разбор свёлся бы к сличению названий")
	}

	prompt, err := r.prompts.ForNode(ctx, NodeArbitrate)
	if err != nil {
		return nil, err
	}
	// Задание собирается по ОБЫЧНОМУ плану, а не по ослеплённому, и это
	// единственный узел после написания, где так можно. Слепота — свойство
	// первого вопроса; второй затем и задают, что он зрячий.
	user := Render(prompt.UserMd, plan)
	user = strings.ReplaceAll(user, "{условие}", draft.Condition())
	user = strings.ReplaceAll(user, "{соседи}", neighbours)

	answer, err := r.ask(ctx, job, prompt, llm.Prompt{
		System: Render(prompt.SystemMd, plan),
		User:   user,
		// Спор решается сличением текстов — разброс здесь не нужен.
		Temperature: 0.2,
		Schema:      ArbitrationSchema,
		SchemaName:  "arbitration",
	})
	if err != nil {
		return nil, err
	}
	out, err := ParseArbitration(answer)
	if err != nil {
		return nil, err
	}
	return &out, nil
}

// neighbourBlock — положения соседей для задания разбора.
//
// Соседи без положений пропускаются, а не показываются одним названием:
// мерилом объявлены положения, и сосед, у которого их нет, добавил бы в
// сравнение ровно ту память о названиях, ради ухода от которой разбор и
// затеян.
func neighbourBlock(plan Plan) string {
	var b strings.Builder
	for _, s := range plan.Siblings {
		statements := strings.TrimSpace(s.StatementsMd)
		if statements == "" {
			continue
		}
		if b.Len() > 0 {
			b.WriteString("\n\n")
		}
		// Метка и название пишутся как есть, в именительном падеже:
		// слово источника склонять нельзя — источник любой, и «пункта
		// 3.2» у него может не быть вовсе.
		fmt.Fprintf(&b, "=== %s — %s ===\n%s", s.Label, s.Title, statements)
	}
	return b.String()
}
