package gen

import (
	"context"
	"errors"
	"log"
	"time"
)

// Исполнитель очереди: тот, кто разбирает заказы, пока никто не смотрит.
//
// Отдельной программой не заводится намеренно. Очередь берётся из базы с
// FOR UPDATE SKIP LOCKED, то есть исполнителей может быть сколько угодно и
// они не мешают друг другу; заводить ради этого второй образ, вторую
// выкатку и второй журнал — плата без выигрыша, пока исполнитель один.

// Idle — сколько ждать, когда очередь пуста.
//
// Секунда, а не мгновенный повтор: пустой Take это запрос к базе, и цикл
// без паузы отдал бы базе целое ядро на то, чтобы узнавать «нечего».
const Idle = time.Second

// Work разбирает очередь, пока не отменят.
//
// Отказ отдельного задания не останавливает исполнителя: причина уже
// записана в само задание (Fail), а остановка из-за одной негодной
// единицы оставила бы без работы всю очередь. Останавливает только
// отмена — то есть остановка сервера.
func Work(ctx context.Context, runner *Runner) {
	for {
		if err := ctx.Err(); err != nil {
			return
		}
		result, took, err := runner.RunNext(ctx)
		switch {
		case errors.Is(err, context.Canceled), errors.Is(err, context.DeadlineExceeded):
			return
		case err != nil:
			// Сам отказ уже в задании; здесь он нужен затем, чтобы в
			// журнале выкатки было видно отказ, повторяющийся на каждом
			// задании подряд, — это отказ не единицы, а настройки.
			log.Printf("генерация: задание не выполнено: %v", err)
		case took:
			log.Printf("генерация: задание %d написано, черновик %d", result.JobID, result.DraftID)
		}
		if took {
			// Взяли задание — сразу за следующим: очередь, разбираемая по
			// одному в секунду, копится быстрее, чем расходится.
			continue
		}
		select {
		case <-ctx.Done():
			return
		case <-time.After(Idle):
		}
	}
}
