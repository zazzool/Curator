// Задания модели: узлы конвейера и их промпты.
//
// Формулировка задания — предмет врачебной работы, а не деталь
// реализации: от неё зависит, получится ли достоверное условие. Поэтому
// промпты живут в базе и правятся в студии, а в коде лежат только
// затравки — то, с чего начинают, пока их не правили.

// Узлы конвейера. Словарь закрыт: узел, появившийся строкой по месту, не
// получит ни промпта, ни модели — то есть пойдёт умолчанием, и заметят
// это по счёту, а не по работе.
const (
	// NodeParse — разбор документа на единицы и положения. Стоит первым:
	// по разобранному живёт всё остальное, и заказать задачу по
	// неразобранному источнику не по чему.
	NodeParse = "parse"

	// NodeCompose — написание условия, вариантов, разметки и разбора.
	NodeCompose = "compose"

	// NodeVerify — слепая сверка: сходится ли условие с заказанным
	// ответом, если смотреть на него глазами обучающегося.
	NodeVerify = "verify"

	// NodeSiblings — различающая сверка: не подтверждает ли условие ещё и
	// НЕВЕРНЫЙ вариант.
	//
	// Слепая сверка отвечает на другой вопрос — «ведёт ли условие к
	// заказанному ответу», — и отвечает на него «да» и тогда, когда
	// условие точно так же ведёт к соседу. Задача с двумя верными
	// ответами проходит слепую сверку насквозь: сверка выбрала
	// заказанное, сошлась, и никто не спросил, что было бы, выбери она
	// соседа.
	NodeSiblings = "siblings"

	// NodeArbitrate — разбор расхождения слепой сверки.
	//
	// Спрашивается только при расхождении и спрашивается ЗРЯЧЕ: слепота
	// нужна первому вопросу, а не приговору по нему. Разбор сличает
	// условие с положениями заказанной единицы и её соседей — то есть с
	// тем, чем они на самом деле различаются, а не с их названиями, по
	// памяти о которых слепая сверка и путается.
	NodeArbitrate = "arbitrate"

	// NodeProofread — литературная вычитка написанного.
	//
	// Отдельным проходом и отдельной моделью, потому что автор согласится
	// сам с собой: написание следит за существом дела, за положениями
	// источника и за форматом ответа разом, и язык идёт у него последним.
	// Видно это в готовых задачах — «Пациент» в заголовке и «Пациентка» в
	// третьей фразе.
	NodeProofread = "proofread"
)

// Nodes — узлы по порядку прохождения.
// Вычитка стоит между написанием и сверками не по алфавиту: она правит
// условие, а сверки обязаны мерить то, что уйдёт обучающемуся.
var Nodes = []string{NodeParse, NodeCompose, NodeProofread, NodeVerify, NodeArbitrate, NodeSiblings}

// NodeWord — узел по-русски. Читает это составитель, и «compose» ему
// ничего не говорит.
func NodeWord(node string) string {
	switch node {
	case NodeParse:
		return "разбор документа"
	case NodeCompose:
		return "написание"
	case NodeVerify:
		return "слепая сверка"
	case NodeProofread:
		return "вычитка"
	case NodeArbitrate:
		return "разбор расхождения"
	case NodeSiblings:
		return "различающая сверка"
	default:
		return node
	}
}

// Prompt — задание модели.
type Prompt struct {
	ID       string
	Name     string
	Node     string
	SystemMd string
	UserMd   string

	// Model — модель ЭТОГО узла. Пусто — модель поставщика по умолчанию.
	//
	// Узлы стоят разных денег и требуют разного: написание условия —
	// самая дорогая работа конвейера, а слепая сверка отвечает одним
	// словом из списка. Одна модель на весь конвейер оставляла выбор
	// между «дорого везде» и «плохо везде».
	//
	// Живёт рядом с заданием, а не отдельной настройкой, потому что
	// правят их вместе: задание, написанное под рассуждающую модель,
	// на отвечающей сразу работает иначе.
	Model string

	// IsDefault — по этому заданию узел и работает.
	//
	// Умолчание ровно одно на узел, и держит это указатель базы. Поле
	// нужно там, где задания перебирают списком: запасное задание того
	// же узла стоит в выдаче рядом с рабочим, и взятое по порядку вместо
	// отмеченного показало бы настройку, которой конвейер не
	// пользуется, — составитель поправил бы модель у задания, мимо
	// которого задачи не ходят.
	IsDefault bool

	Revision int
}

// Prompts — хранилище заданий.
type Prompts struct {
	gate *dbgate.Gate
}

func NewPrompts(gate *dbgate.Gate) *Prompts { return &Prompts{gate: gate} }

// ForNode отдаёт задание узла: то, что отмечено умолчанием.
//
// Умолчание ровно одно на узел — двух конвейер не разберёт, и держит это
// указатель базы. Нет ни одного — отказ, а не пустое задание: модель,
// получившая пустое задание, ответит чем угодно, и ответ этот будет
// выглядеть работой.
func (p *Prompts) ForNode(ctx context.Context, node string) (Prompt, error) {
	var out Prompt
	err := p.gate.QueryRow(ctx,
		`SELECT id, name, node, system_md, user_md, model, is_default, revision
		   FROM prompts
		  WHERE node = $1 AND is_default
		  LIMIT 1`, node).
		Scan(&out.ID, &out.Name, &out.Node, &out.SystemMd, &out.UserMd,
			&out.Model, &out.IsDefault, &out.Revision)
	if errors.Is(err, pgx.ErrNoRows) {
		return Prompt{}, fmt.Errorf("у узла «%s» нет задания по умолчанию", NodeWord(node))
	}
	if err != nil {
		return Prompt{}, fmt.Errorf("задание узла «%s» не прочитано: %w", NodeWord(node), err)
	}
	return out, nil
}

// Seed кладёт затравки тех узлов, у которых заданий ещё нет.
//
// Только недостающие: правленое в студии задание затирать накатом нельзя —
// правка задания это врачебная работа, и потерять её значит потерять
// неделю чьей-то настройки. Поэтому ON CONFLICT DO NOTHING, а не UPSERT.
func (p *Prompts) Seed(ctx context.Context) error {
	return p.gate.InTx(ctx, func(tx pgx.Tx) error {
		for _, seed := range seeds() {
			_, err := tx.Exec(ctx,
				`INSERT INTO prompts (id, name, node, system_md, user_md, is_default)
				 VALUES ($1, $2, $3, $4, $5, TRUE)
				 ON CONFLICT (id) DO NOTHING`,
				seed.ID, seed.Name, seed.Node, seed.SystemMd, seed.UserMd)
			if err != nil {
				return fmt.Errorf("затравка %q не положена: %w", seed.ID, err)
			}
		}
		return nil
	})
}

// Render подставляет в задание переменные заказа.
//
// Круга вариантов у него нет: {круг} и {откуда} подставляются из пустого
// набора. Так рендерятся слепые задания — сверки, которым круг знать
// нельзя, — и слепота эта держится здесь, а не уговором на местах: чтобы
// показать сверке варианты, пришлось бы позвать другую функцию.
func Render(text string, plan Plan) string {
	return RenderSet(text, plan, AnswerSet{})
}

// RenderSet — то же, но с кругом вариантов, собранным сервером.
//
// Переменные названы по-русски и в фигурных скобках: задание правит
// составитель, а не программист, и {единица} он прочтёт, а {{.UnitWord}}
// — нет. Незнакомая переменная остаётся в тексте как есть: молча
// вычищенная, она превратила бы опечатку в задании в тихую потерю смысла.
func RenderSet(text string, plan Plan, set AnswerSet) string {
	vars := map[string]string{
		"источник":    plan.Title,
		"единица":     plan.UnitWord,
		"положение":   plan.StatementWord,
		"метка":       plan.Unit.Label,
		"название":    plan.Unit.Title,
		"положения":   plan.StatementsMd,
		"вложенность": hierarchyWord(plan.Hierarchy),
		"круг":        set.Listing(),
		"откуда":      set.Origins(),
		"обозначения": strings.Join(plan.Designations(), ", "),
		"вид":         KindWord(plan.TaskKind),
	}
	if plan.Target != nil {
		vars["эталон"] = plan.Target.Body
	} else {
		vars["эталон"] = plan.Unit.Title
	}

	// Один проход слева направо, а не цепочка замен.
	//
	// Цепочка перебирала карту, а порядок обхода карты в Go случаен по
	// замыслу языка: значение одной переменной, содержащее имя другой,
	// раскрывалось или нет — как выпадет. Из 400 прогонов одного и того
	// же заказа 277 давали один текст задания, 123 другой, и запись в
	// llm_calls переставала быть следом того, что было. Подставить имя
	// переменной в значение может и составитель, сам того не желая:
	// {положения} — обычное название единицы в приказе.
	//
	// NewReplacer меняет слева направо и в подставленное не заглядывает.
	// Порядок пар при этом не важен: имя обёрнуто скобками, и ни один
	// образец не начинает собой другой — иначе случайный порядок карты
	// вернулся бы сюда же через выбор между двумя совпадениями.
	pairs := make([]string, 0, 2*len(vars))
	for name, value := range vars {
		pairs = append(pairs, "{"+name+"}", value)
	}
	return strings.NewReplacer(pairs...).Replace(text)
}

// hierarchyWord — смысл вложенности словами.
//
// Модели это говорится прямо: у «часть целого» сосед по родителю — другая
// часть того же целого, у «разновидности» — другая разновидность того же
// рода. Подразумевать одно устройство для всех источников значит писать
// неверные варианты наугад.
func hierarchyWord(hierarchy string) string {
	switch hierarchy {
	case "is-a":
		return "вложенные — разновидности вышестоящего"
	case "part-of":
		return "вложенные — части вышестоящего"
	default:
		return "вложенные просто сгруппированы под вышестоящим"
	}
}

