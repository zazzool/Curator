// Package rules — свод правил: то, чего система обязана держаться, когда
// пишет задачу.
//
// Это и есть «самообучение» конвейера. Обучается он не весами, а сводом:
// то, что приходилось править руками, становится правилом, правило
// уходит в задание, и следующая задача пишется уже с ним.
//
// # Почему свод, а не список уроков
//
// Прежде накопленное у донора жило одним плоским списком и уходило в
// один общий блок задания. Три причины, по которым такой список
// перестаёт работать, известны наперёд:
//
//   - **Правило без области действия применяется не к месту.** «Не путай
//     очную форму с заочной» верно для одного раздела приказа и
//     бессмысленно для другого. Общий список несёт всё ко всем, и
//     половина задания в каждом запросе — про чужие единицы.
//   - **Правило, живущее только текстом в задании, необязательно к
//     исполнению.** Три проигранные дуэли промптов (см. gen/lint.go)
//     показали это на одном частном запрете: задание остаётся просьбой.
//   - **Составителю негде высказаться.** Уроки писала модель по разбору
//     правки, сделанному моделью же; человеку оставалось право погасить
//     чужое. А у него есть свои требования, и сказать их было негде.
//
// # Чего здесь сознательно НЕ сделано
//
//   - **Модель не пишет проверок.** Она предлагает правило словами;
//     проверку к нему подбирает код из закрытого каталога, и подобранное
//     видит человек. Иначе система, которая учится на своих ошибках,
//     рано или поздно выучит правило, ослабляющее проверку собственных
//     ошибок. Это описанный и измеренный сбой самообучающихся петель, а
//     не выдумка.
//   - **Правило не удаляется, а закрывается датой.** Дрейф свода
//     замечают через недели, и вопрос «чего мы требовали в марте» обязан
//     иметь ответ.
//
// Каталог предикатов и судья — отдельные наряды; здесь у правила один
// канал, задание модели. Поле под остальные каналы не заводится заранее:
// поле без исполнения — это обещание, которого никто не держит.
package rules

import (
	"errors"
	"fmt"
	"sort"
	"strings"
	"time"
	"unicode/utf8"
)

// Kind — о чём правило. Род определяет вес в блоке задания: место в нём
// ограничено, и жертвовать надо правилом о слоге, а не о существе.
//
// У донора первый род звался клиническим. Здесь он зовётся «про
// существо»: источник любой, и правило о существе дела одинаково нужно
// и приказу, и клиническим рекомендациям. Имя рода, знающее один
// источник, — это то же «если это МКБ», только в словаре.
type Kind string

const (
	// KindSubstance — про существо: выдуманный признак, описание не того
	// случая, невозможное сочетание обстоятельств.
	KindSubstance Kind = "substance"
	// KindConsistency — про то, чтобы текст не спорил сам с собой: род,
	// возраст, сроки, действующие лица. Отдельный род, а не часть языка:
	// «мужчина и его муж» — не огрех слога, это другой человек в
	// середине абзаца, и читатель теряет доверие ко всему тексту разом.
	KindConsistency Kind = "consistency"
	// KindMarking — про разметку: какой фрагмент какое положение
	// подтверждает.
	KindMarking Kind = "marking"
	// KindStructure — про устройство задачи: длина, порядок, варианты.
	KindStructure Kind = "structure"
	// KindLanguage — про слог и грамматику.
	KindLanguage Kind = "language"
)

// Kinds — рода по порядку веса. Словарь закрыт: род, появившийся строкой
// по месту, получил бы вес ноль и молча ушёл в хвост блока.
var Kinds = []Kind{KindSubstance, KindConsistency, KindMarking, KindStructure, KindLanguage}

// KindWord — род словами составителя.
func KindWord(k Kind) string {
	switch k {
	case KindSubstance:
		return "существо"
	case KindConsistency:
		return "согласованность"
	case KindMarking:
		return "разметка"
	case KindStructure:
		return "устройство"
	case KindLanguage:
		return "слог"
	default:
		return string(k)
	}
}

// kindWeight — насколько род важен при отборе в задание.
func kindWeight(k Kind) int {
	switch k {
	case KindSubstance:
		return 5
	case KindConsistency:
		return 4
	case KindMarking:
		return 3
	case KindStructure:
		return 2
	case KindLanguage:
		return 1
	default:
		return 0
	}
}

// Source — откуда правило взялось.
type Source string

const (
	// FromCurator — написано составителем. Высшая власть в своде.
	FromCurator Source = "curator"
	// Builtin — заведено вместе с кодом. Правится, но не удаляется:
	// удалённое вернулось бы при следующем запуске и выглядело бы
	// воскресшим из мёртвых.
	Builtin Source = "builtin"
	// FromEdit — выведено из правки, сделанной составителем.
	FromEdit Source = "edit"
	// FromLint — выведено из повторяющихся замечаний детектора подсказок.
	FromLint Source = "lint"
)

// sourceRank — кто главнее при споре. Составитель > встроенное > правка
// > замечание детектора. Разрешать спор правил рассуждением модели
// нельзя: на двух противоречивых пунктах ни одна известная система не
// даёт предсказуемого поведения.
func sourceRank(s Source) int {
	switch s {
	case FromCurator:
		return 4
	case Builtin:
		return 3
	case FromEdit:
		return 2
	case FromLint:
		return 1
	default:
		return 0
	}
}

// Status — что с правилом делать сейчас.
type Status string

const (
	// Draft — составитель пишет правило и ещё не закончил. В работу не
	// идёт.
	Draft Status = "draft"
	// Candidate — подтверждений мало, в задание не уходит.
	Candidate Status = "candidate"
	// Active — действует.
	Active Status = "active"
	// Muted — погашено составителем. Подтверждениями не воскресает: оно
	// побывало перед глазами и было отвергнуто.
	Muted Status = "muted"
	// Deprecated — закрыто как устаревшее. От погашенного отличается
	// тем, что гасил не человек: правило давно не подтверждалось.
	Deprecated Status = "deprecated"
)

const (
	// Quorum — сколько разных заданий должны подтвердить выведенное
	// правило, прежде чем оно уйдёт в работу. Одна правка —
	// случайность, две — совпадение.
	//
	// Правило составителя кворума не ждёт: он и есть подтверждение.
	Quorum = 3

	// TitleMax — потолок имени правила в БАЙТАХ. Имя стоит в списке
	// одной строкой; длиннее — и список перестаёт читаться взглядом.
	TitleMax = 90

	// TextMax — потолок текста правила в БАЙТАХ.
	//
	// Байты, а не знаки: кириллица стоит двух, и «300 знаков» на деле
	// оказались бы шестьюстами. Правило должно быть правилом, а не
	// пересказом случая; 300 байт — это около 140 русских букв, ровно
	// одна фраза повелительного наклонения.
	TextMax = 300

	// coreChars и scopedChars — бюджеты блока в задании, в байтах.
	//
	// Два ведра, а не одно, и это главное отличие от плоского списка.
	// Общие правила накапливаются быстрее частных — их подтверждает
	// любая задача, — и в общем списке они вытеснили бы правила про
	// конкретный источник подчистую. Между тем ценность обратная: общее
	// модель знает и из самого задания, а «в этом приказе очная форма
	// называется явкой» ей больше взять неоткуда.
	coreChars   = 2000
	scopedChars = 1500

	// blockLimit — потолок числа правил в блоке. Второй предел, на
	// случай очень коротких правил: тридцать однострочников уложатся в
	// байты и всё равно не будут удержаны.
	blockLimit = 16

	// Idle — сколько выведенное правило живёт без подтверждений.
	//
	// Месяц. Правило, которое месяц не подтверждалось ни одним
	// заданием, описывает ошибку, которой модель больше не делает: либо
	// задание поправили, либо сменилась модель. Правил составителя
	// затухание не касается — их писал человек, и молчание тут значит
	// «работает».
	Idle = 30 * 24 * time.Hour
)

// Rule — одно правило свода.
type Rule struct {
	ID string `json:"id"`

	// Title — как правило зовут в списке. Короткое имя, потому что сам
	// текст правила — фраза на строку, и списком из таких фраз
	// пользоваться нельзя.
	Title string `json:"title"`

	// Text — само правило, как оно уйдёт в задание модели. Одна фраза
	// повелительного наклонения.
	Text string `json:"text"`

	// Why — почему правило появилось, для составителя. В задание не
	// уходит: модели нужно указание, а не его обоснование, и
	// обоснование стоило бы токенов в каждом запросе.
	Why string `json:"why"`

	Kind   Kind   `json:"kind"`
	Source Source `json:"source"`
	Scope  Scope  `json:"scope"`
	Status Status `json:"status"`

	// Pinned — состояние назначено человеком, а не счётчиком.
	//
	// Без этого признака включение правила рукой молча не работает:
	// обработчик ставит «действует», хранилище пересчитывает состояние
	// по кворуму и возвращает «кандидат», отвечая при этом успехом.
	// Решение человека счётчик не отменяет.
	Pinned bool `json:"pinned,omitempty"`

	// Confirmations — сколько разных заданий подтвердили правило.
	Confirmations int `json:"confirmations"`

	// SeenJobs — задания, уже подтвердившие правило, одними
	// опознавателями.
	//
	// Отдельно от примеров, и это не дублирование: примеры обрезаются, а
	// обрезка стирала бы и память о подтвердивших заданиях — и задание,
	// чей пример вытеснили, подтвердило бы правило снова. «Разных
	// заданий» переставало бы значить «разных» ровно там, где число уже
	// большое и на него смотрят.
	SeenJobs []int64 `json:"seenJobs,omitempty"`

	// ValidFrom и ValidTo — когда правило считалось верным. Закрытие
	// датой вместо удаления: свод дрейфует, и дрейф замечают через
	// недели.
	ValidFrom time.Time  `json:"validFrom"`
	ValidTo   *time.Time `json:"validTo,omitempty"`

	CreatedAt  time.Time `json:"createdAt"`
	UpdatedAt  time.Time `json:"updatedAt"`
	LastSeenAt time.Time `json:"lastSeenAt"`
}

// InForce — правило действует и может уйти в задание.
func (r Rule) InForce() bool { return r.Status == Active && r.ValidTo == nil }

// faded — выведенное правило замолчало и больше не подтверждается.
//
// Правил составителя и встроенных затухание не касается: их писал
// человек, и молчание тут значит «работает», а не «забыто».
func (r Rule) faded(now time.Time) bool {
	if r.Source == FromCurator || r.Source == Builtin || r.Pinned {
		return false
	}
	if r.LastSeenAt.IsZero() {
		return false
	}
	return now.Sub(r.LastSeenAt) > Idle
}

// Normalize приводит правило к годному виду и считает состояние по
// кворуму.
//
// Состояние, назначенное человеком (Pinned), не пересчитывается — см.
// довод у самого признака.
func (r *Rule) Normalize(now time.Time) error {
	r.Title = strings.TrimSpace(r.Title)
	r.Text = strings.TrimSpace(r.Text)
	r.Why = strings.TrimSpace(r.Why)

	if r.Title == "" {
		return errors.New("у правила нет имени: список правил читается именами")
	}
	if len(r.Title) > TitleMax {
		return fmt.Errorf("имя правила длиннее %d байт — оно стоит в списке одной строкой", TitleMax)
	}
	if r.Text == "" {
		return errors.New("у правила нет текста: правило без текста ничего не требует")
	}
	if len(r.Text) > TextMax {
		return fmt.Errorf("текст правила длиннее %d байт — это уже пересказ случая, а не правило", TextMax)
	}
	if !utf8.ValidString(r.Title) || !utf8.ValidString(r.Text) {
		return errors.New("текст правила не в UTF-8")
	}
	if kindWeight(r.Kind) == 0 {
		return fmt.Errorf("род правила «%s» не из словаря", r.Kind)
	}
	if sourceRank(r.Source) == 0 {
		return fmt.Errorf("источник правила «%s» не из словаря", r.Source)
	}
	r.Scope.normalize()

	if r.ValidFrom.IsZero() {
		r.ValidFrom = now
	}
	r.UpdatedAt = now

	switch r.Status {
	case Draft, Muted, Deprecated:
		// Состояния, в которых счётчик ничего не решает: черновик ещё не
		// дописан, погашенное отвергнуто человеком, закрытое закрыто.
		return nil
	case Active, Candidate, "":
		if r.Pinned {
			if r.Status == "" {
				return errors.New("состояние назначено человеком, но не названо")
			}
			return nil
		}
		// Правило составителя кворума не ждёт: он и есть подтверждение.
		if r.Source == FromCurator || r.Source == Builtin || r.Confirmations >= Quorum {
			r.Status = Active
		} else {
			r.Status = Candidate
		}
		return nil
	default:
		return fmt.Errorf("состояние правила «%s» не из словаря", r.Status)
	}
}

// sortRules — порядок старшинства: сперва по источнику, потом по роду,
// потом по подтверждениям, и лишь затем по опознавателю.
//
// Опознаватель последним разводит равные и больше ничего не значит: без
// него порядок зависел бы от того, как их вернула база, и блок задания
// плясал бы от запроса к запросу. Запись в журнале обращений перестала
// бы быть следом того, что было.
func sortRules(list []Rule) {
	sort.SliceStable(list, func(i, j int) bool {
		a, b := list[i], list[j]
		if ra, rb := sourceRank(a.Source), sourceRank(b.Source); ra != rb {
			return ra > rb
		}
		if wa, wb := kindWeight(a.Kind), kindWeight(b.Kind); wa != wb {
			return wa > wb
		}
		if a.Confirmations != b.Confirmations {
			return a.Confirmations > b.Confirmations
		}
		return a.ID < b.ID
	})
}
