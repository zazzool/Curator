package rules

import (
	"sort"
	"strings"
)

// Область действия правила.
//
// Главная мысль свода и главное его отличие от плоского списка. Правило
// без области действия уходит в каждый запрос по каждому источнику:
// «очная форма в этом приказе называется явкой» приезжает в задачу по
// клиническим рекомендациям и занимает там место правила, которое было
// бы кстати. Место в задании ограничено физически — не байтами базы, а
// тем, сколько правил модель способна удержать при письме, — и общее
// правило, накопившее подтверждений на любых задачах, вытесняет
// частное, подтверждавшееся только на своём источнике.
//
// Пустая область — «всегда». Это законный и частый случай: «не пиши в
// условии метку единицы» верно везде. Но по умолчанию у правила,
// выведенного из замечания, область ставится по источнику разобранного
// задания: замечание сделано на конкретном документе, и обобщать его на
// все источники — то самое возведение случайности в закон, ради борьбы
// с которым заведён кворум.
//
// Измерений здесь нет ни одного, знающего один источник. У донора
// область резалась главами МКБ; здесь источник любой, и единственное,
// чем его можно резать, — он сам и его собственные единицы.
type Scope struct {
	// Sources — опознаватели источников, при которых правило действует.
	Sources []int64 `json:"sources,omitempty"`

	// Units — метки единиц. Действует на саму единицу И на всё, что под
	// ней: у источника с вложенностью правило про раздел обязано
	// доставаться его пунктам, иначе область пришлось бы перечислять
	// поимённо и переписывать при каждом пополнении источника.
	//
	// Без Sources метки бессмысленны: «3.1» есть в любом приказе, и
	// правило про один документ уехало бы в другой. Это не придирка —
	// normalize такую область чистит.
	Units []string `json:"units,omitempty"`

	// TaskKinds — виды задачи: узнавание, действие. «Не подсказывай
	// действие в условии» — правило именно про вид.
	TaskKinds []string `json:"taskKinds,omitempty"`

	// Nodes — узлы конвейера, которым правило показывается.
	//
	// Измерение особого рода: остальные отвечают на вопрос «когда
	// правило действует», это — «кому». Заведено потому, что задачу
	// пишет не один запрос. Условие вычитывает корректор, разбор пишет
	// написание, сверяет сверка, и каждому уходит свой блок свода. Без
	// этого измерения правило про существо дела уезжало бы корректору:
	// указание, которого он выполнить не может и которое только
	// занимает место и внимание, — а весь этап вычитки держится на том,
	// что существа она не трогает.
	Nodes []string `json:"nodes,omitempty"`
}

// Context — обстоятельства, при которых спрашивают свод.
//
// Одна структура и для сборки задания, и для проверки написанного:
// правило, ушедшее в задание, обязано проверяться на том же тексте, а не
// на соседнем. Разъедься эти два подбора — и свод начнёт требовать
// одного, а проверять другое, причём молча.
type Context struct {
	SourceID int64

	// UnitPath — путь единицы от корня («3/3.1»), а не одна её метка.
	// По нему и сверяется область: правило про раздел достаётся его
	// пунктам. Собирает путь заказ, при чтении источника; разбирать его
	// обратно из метки нельзя — это была бы вторая реализация
	// вложенности, и расходилась бы она с первой тихо.
	UnitPath string

	TaskKind string

	// Node — узел, который спрашивает. Пусто — спрашивают не узлом: так
	// свод показывают в студии, и там нужен весь, какой вообще может
	// уйти. Разведено с «узел, у которого нет правил», потому что иначе
	// правило, показываемое одному узлу, исчезало бы из предпросмотра,
	// который обещает показать весь свод.
	Node string

	// Kinds — рода правил, уместные спрашивающему. Пусто — все.
	//
	// Мера предосторожности, а не отбор по важности: у накопленных
	// правил узел может быть не проставлен, и пока он пуст, узлу
	// достаётся весь свод. Род проставлен у всех и потому годится там,
	// где узел ещё молчит.
	Kinds []Kind
}

// normalize приводит область к годному виду.
func (s *Scope) normalize() {
	s.Sources = cleanInts(s.Sources)
	s.TaskKinds = cleanStrings(s.TaskKinds)
	s.Nodes = cleanStrings(s.Nodes)
	s.Units = cleanStrings(s.Units)

	// Метка единицы без источника — область, которая выглядит узкой и не
	// является ею: «3.1» есть в любом приказе. Правило, написанное про
	// один документ, уезжало бы во все.
	if len(s.Sources) == 0 {
		s.Units = nil
	}
}

// always — область пуста, правило действует везде.
func (s Scope) always() bool {
	return len(s.Sources) == 0 && len(s.Units) == 0 &&
		len(s.TaskKinds) == 0 && len(s.Nodes) == 0
}

// matches — действует ли правило при этих обстоятельствах.
//
// Измерения складываются по «и», значения внутри измерения — по «или»:
// правило про два источника действует на любом из них, но правило про
// источник и вид задачи — только там, где сошлись оба. Иначе область,
// которую составитель сужал двумя измерениями, становилась бы шире от
// каждого уточнения.
func (s Scope) matches(ctx Context) bool {
	if len(s.Sources) > 0 && !hasInt(s.Sources, ctx.SourceID) {
		return false
	}
	if len(s.Units) > 0 && !underAny(s.Units, ctx.UnitPath) {
		return false
	}
	if len(s.TaskKinds) > 0 && !hasString(s.TaskKinds, ctx.TaskKind) {
		return false
	}
	// Узел спрашивают не всегда: пустой узел — это «покажи весь свод», и
	// правило с названным узлом из такого показа исчезать не должно.
	if len(s.Nodes) > 0 && ctx.Node != "" && !hasString(s.Nodes, ctx.Node) {
		return false
	}
	return true
}

// underAny — стоит ли единица под одной из меток области.
//
// Сверяется ПУТЬ, а не метка, и сверяется он по разделителю, а не по
// началу строки. Голое начало строки роднит «3.1» с «3.10»: у источника
// с десятью пунктами в разделе правило про первый достаётся десятому, и
// заметить это можно только по тексту задачи.
func underAny(units []string, path string) bool {
	path = strings.TrimSpace(path)
	if path == "" {
		return false
	}
	for _, u := range units {
		if path == u || strings.HasPrefix(path, u+"/") {
			return true
		}
		// Путь собирается заказом и в старых записях может быть пуст —
		// тогда в нём стоит одна метка. Сверка по последнему звену
		// оставляет такие записи рабочими, не роняя сверку по пути.
		if last := path[strings.LastIndex(path, "/")+1:]; last == u {
			return true
		}
	}
	return false
}

func hasInt(list []int64, want int64) bool {
	for _, v := range list {
		if v == want {
			return true
		}
	}
	return false
}

func hasString(list []string, want string) bool {
	for _, v := range list {
		if v == want {
			return true
		}
	}
	return false
}

// cleanStrings — убрать пустые, повторы и разнобой в пробелах, и
// разложить по порядку.
//
// Порядок нужен не для красоты: область уезжает в базу как JSON и
// сравнивается при показе изменений. Карта порядка не держит, и одно и
// то же правило выглядело бы изменившимся от каждой пересборки.
func cleanStrings(list []string) []string {
	if len(list) == 0 {
		return nil
	}
	seen := map[string]bool{}
	out := make([]string, 0, len(list))
	for _, v := range list {
		v = strings.TrimSpace(v)
		if v == "" || seen[v] {
			continue
		}
		seen[v] = true
		out = append(out, v)
	}
	if len(out) == 0 {
		return nil
	}
	sort.Strings(out)
	return out
}

func cleanInts(list []int64) []int64 {
	if len(list) == 0 {
		return nil
	}
	seen := map[int64]bool{}
	out := make([]int64, 0, len(list))
	for _, v := range list {
		if v <= 0 || seen[v] {
			continue
		}
		seen[v] = true
		out = append(out, v)
	}
	if len(out) == 0 {
		return nil
	}
	sort.Slice(out, func(i, j int) bool { return out[i] < out[j] })
	return out
}
