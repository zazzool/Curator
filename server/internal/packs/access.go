package packs

// Линейка набора — чем он открывается.
//
// # Зачем линейка, а не дневной предел
//
// Граница бесплатного названа решением владельца 2026-09-20 и названа
// пакетно: гостевой набор открыт неавторизованному без ограничений,
// базовый — тому, кто привязал почту, остальное продаётся или дарится
// спонсором. Дневной предел и пробный срок были предложены и отвергнуты:
// предел отмеряет то же самое содержание порциями, а линейка отвечает на
// вопрос, за что вообще платят.
//
// До этого решения границы не существовало вовсе — ни числом, ни правилом.
// Корпус `/v1/cases` отдавался всякому заведённому устройству целиком, то
// есть подписка не отличалась от её отсутствия ничем, что делает сервер
// (СЕР-8 приговора аудита).
const (
	// LineGuest — открыт всякому, без единой строки прав.
	LineGuest = "guest"

	// LineBasic — открыт тому, кто привязал почту. «Авторизованный» у нас
	// и значит это: учётная запись заводится молча при первом запуске, и
	// отличает назвавшегося от промолчавшего только почта.
	LineBasic = "basic"

	// LinePaid — открыт подпиской или покупкой этого набора.
	LinePaid = "paid"

	// LineSponsored — открыт всем и бесплатен: за него заплатил спонсор.
	// Второй раз, деньгами врача, за него не платят никогда, и потому
	// стена входа перед ним превратила бы подарок в приманку.
	LineSponsored = "sponsored"
)

// Lines — все линейки, в порядке от открытой к закрытой.
//
// Список закрытый, и закрытость его — это то, что делает контракт
// дешёвым: линейка, добавленная «для гибкости», не значит ничего ни для
// OpenTo, ни для витрины.
var Lines = []string{LineGuest, LineBasic, LinePaid, LineSponsored}

// Rights — то, что известно о пришедшем применительно к ОДНОМУ набору.
type Rights struct {
	// Owns — право именно на этот набор: покупка или выдача оператором.
	Owns bool

	// Subscribed — живая подписка.
	Subscribed bool

	// EmailBound — почта привязана.
	EmailBound bool
}

// OpenTo — единственное место, где решается, открыт ли набор.
//
// Одна функция на витрину, корпус и выгрузку, и это не удобство: разойдись
// эти расчёты, витрина показывала бы «открыто» там, где выгрузка отвечает
// отказом, — а врач читал бы это как поломку приложения. Разошлись бы они
// непременно в сторону «выдали лишнее»: корпус выглядит исправным при
// любом составе, и заметить лишнее в нём нечем.
//
// Порядок доводов — от сильного к слабому. Купленное сильнее линейки:
// набор, купленный платным, остаётся открытым, даже если линейку потом
// сменят. Отобрать купленное сменой линейки значило бы отобрать
// оплаченное молча.
//
// Незнакомая линейка закрыта, а не открыта: непонятое не применяется.
func OpenTo(line string, r Rights) bool {
	if r.Owns {
		return true
	}
	switch line {
	case LineGuest, LineSponsored:
		return true
	case LineBasic:
		return r.EmailBound
	case LinePaid:
		return r.Subscribed
	}
	return false
}

// KnownLine — есть ли такая линейка.
func KnownLine(line string) bool {
	for _, one := range Lines {
		if one == line {
			return true
		}
	}
	return false
}
