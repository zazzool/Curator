package packs

// Линейка набора — чем он открывается.
//
// # Зачем линейка, а не дневной предел
//
// Граница бесплатного названа решением владельца 2026-09-20 и названа
// пакетно: гостевой набор открыт неавторизованному без ограничений,
// базовый — тому, кто привязал почту, остальное продаётся или дарится
// спонсором. Дневной предел и пробный срок были предложены и отвергнуты:
// предел отмеряет то же самое содержание порциями, а линейка отвечает на
// вопрос, за что вообще платят.
//
// До этого решения границы не существовало вовсе — ни числом, ни правилом.
// Корпус `/v1/cases` отдавался всякому заведённому устройству целиком, то
// есть подписка не отличалась от её отсутствия ничем, что делает сервер
// (СЕР-8 приговора аудита).
const (
	// LineGuest — открыт всякому, без единой строки прав.
	LineGuest = "guest"

	// LineBasic — открыт тому, кто привязал почту. «Авторизованный» у нас
	// и значит это: учётная запись заводится молча при первом запуске, и
	// отличает назвавшегося от промолчавшего только почта.
	LineBasic = "basic"

	// LinePaid — открыт подпиской или покупкой этого набора.
	LinePaid = "paid"

	// LineSponsored — открыт всем и бесплатен: за него заплатил спонсор.
	// Второй раз, деньгами врача, за него не платят никогда, и потому
	// стена входа перед ним превратила бы подарок в приманку.
	LineSponsored = "sponsored"
)

// Lines — все линейки, в порядке от открытой к закрытой.
//
// Список закрытый, и закрытость его — это то, что делает контракт
// дешёвым: линейка, добавленная «для гибкости», не значит ничего ни для
// OpenTo, ни для витрины.
var Lines = []string{LineGuest, LineBasic, LinePaid, LineSponsored}

// Rights — то, что известно о пришедшем применительно к ОДНОМУ набору.
type Rights struct {
	// Owns — право именно на этот набор: покупка или выдача оператором.
	Owns bool

	// Subscribed — живая подписка.
	Subscribed bool

	// EmailBound — почта привязана.
	EmailBound bool

	// Granted — набор открыт группе, в которую попадает врач.
	//
	// Группы — это расширение линейки, а не второй механизм рядом с ней:
	// они добавляют доводы сюда, а решает по-прежнему OpenTo. Так
	// кафедральный заказ («этот набор открыт ординаторам кафедры») не
	// требует ни новой линейки, ни выдачи права каждому поимённо.
	Granted bool

	// Hidden — набор скрыт от группы, в которую попадает врач.
	Hidden bool
}

// OpenTo — единственное место, где решается, открыт ли набор.
//
// Одна функция на витрину, корпус и выгрузку, и это не удобство: разойдись
// эти расчёты, витрина показывала бы «открыто» там, где выгрузка отвечает
// отказом, — а врач читал бы это как поломку приложения. Разошлись бы они
// непременно в сторону «выдали лишнее»: корпус выглядит исправным при
// любом составе, и заметить лишнее в нём нечем.
//
// Порядок доводов — от сильного к слабому. Купленное сильнее линейки:
// набор, купленный платным, остаётся открытым, даже если линейку потом
// сменят. Отобрать купленное сменой линейки значило бы отобрать
// оплаченное молча.
//
// Группы стоят между купленным и линейкой, и скрытие среди них сильнее
// открытия. Пересечение групп неизбежно — врач бывает и в «кафедре», и в
// «уснувших», — и при споре двух правил выигрывать должно закрывающее:
// набор, закрытый по ошибке, виден сразу, потому что врач его не получит
// и скажет; открытый по ошибке не виден никому, и узнают о нём по
// непришедшим деньгам. Тот же довод, по которому линейка в схеме
// умалчивается платной.
//
// Скрытие при этом не отбирает купленное: Owns стоит выше него. Отобрать
// оплаченное правкой правила значило бы отобрать деньги молча, а правило
// правят на живых группах, и задеть им купившего проще всего.
//
// Незнакомая линейка закрыта, а не открыта: непонятое не применяется.
func OpenTo(line string, r Rights) bool {
	return Decide(line, r).Open
}

// Чем набор открыт — словарь закрытый, и в нём ровно те доводы, которые
// перебирает Decide.
//
// Уезжает в приложение затем, чтобы открытый набор мог сказать, надолго
// ли он открыт. Купленное не отбирают никогда; открытое группой держится
// на правиле, а правило смотрит на живого врача — тот, кто попал в группу
// «не заходил 30 дней», выйдет из неё, едва зайдя. Промолчи мы об этом,
// набор пропал бы у врача без причины, и он прочёл бы это как поломку.
const (
	// ByPurchase — куплен или выдан оператором.
	ByPurchase = "purchase"

	// ByGroup — открыт группе, в которую попадает врач.
	ByGroup = "group"

	// ByLine — открыт своей линейкой: бесплатен, спонсорский, или врач
	// привязал почту и подписался.
	ByLine = "line"
)

// Verdict — открыт ли набор и чем именно.
type Verdict struct {
	Open bool

	// By — довод, по которому набор открыт; у закрытого пусто.
	By string
}

// Decide — тот же перебор, что и у OpenTo, но говорящий, на каком доводе
// он остановился.
//
// Разделены они ровно настолько, насколько нужно витрине, и ни на сколько
// больше: перебор ОДИН. Второй, считающий «почему», разошёлся бы с первым,
// считающим «открыт ли», — и разошёлся бы молча, потому что «почему»
// видно только врачу, а витрина при любом ответе выглядит исправной.
func Decide(line string, r Rights) Verdict {
	if r.Owns {
		return Verdict{Open: true, By: ByPurchase}
	}
	if r.Hidden {
		return Verdict{}
	}
	if r.Granted {
		return Verdict{Open: true, By: ByGroup}
	}
	switch line {
	case LineGuest, LineSponsored:
		return Verdict{Open: true, By: ByLine}
	case LineBasic:
		if r.EmailBound {
			return Verdict{Open: true, By: ByLine}
		}
	case LinePaid:
		if r.Subscribed {
			return Verdict{Open: true, By: ByLine}
		}
	}
	return Verdict{}
}

// KnownLine — есть ли такая линейка.
func KnownLine(line string) bool {
	for _, one := range Lines {
		if one == line {
			return true
		}
	}
	return false
}
