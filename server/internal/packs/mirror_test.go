package packs

import (
	"os"
	"regexp"
	"testing"
)

// Словарь линеек живёт в двух местах: здесь и в приложении, где по нему
// выбирается, что сказать врачу о закрытом наборе. Сервер и приложение
// живут в разных экосистемах, и рассинхрон между ними не поймает ни один
// компилятор: линейка, добавленная здесь и не добавленная там, приедет на
// устройство неузнанной, и закрытый набор промолчит о способе открыть
// себя вместо того, чтобы его назвать.
//
// То же со словарём «чем открыт»: незнакомое приложению значение не
// сломает его — оно отбрасывается, — но и не скажет ничего, и открытый
// группой набор снова станет неотличим от купленного.
//
// Сверка двусторонняя: ловит и лишнее в приложении, и недостающее, и
// переставленное. Порядок значим, потому что расхождение в порядке — это
// то же расхождение, только его труднее заметить глазами.
//
// Отказ, а не пропуск: недоступный исходник приложения значит, что
// проверка ничего не сверила, и объявлять её пройденной нельзя. Прежняя
// сверка каталога величин у донора звала здесь `t.Skipf`, и величина,
// которую считает одно приложение, проходила молча.
//
// Свой прогон зовётся только с -count=1: читаемый файл лежит вне каталога
// пакета, и кэш `go test` правку такого файла не замечает — отвечает
// «ok (cached)» на разошедшемся словаре. Сторож зовёт проверки именно так.
const appShelfFile = "../../../app/lib/packs/shelf.dart"

var (
	appLineConst = regexp.MustCompile(`(?m)^\s+static const (\w+) = '([a-z]+)';`)
	appLineList  = regexp.MustCompile(`static const all = \[([^\]]+)\];`)
)

func TestСловарьЛинеекПриложенияЗеркаленСерверному(t *testing.T) {
	shown := объявленныеВПриложении(t, "PackLine")
	if len(shown) != len(Lines) {
		t.Fatalf("на сервере %d линеек, в приложении %d: %v против %v",
			len(Lines), len(shown), Lines, shown)
	}
	for i, line := range Lines {
		if shown[i] != line {
			t.Errorf("линейка %d: на сервере %q, в приложении %q",
				i, line, shown[i])
		}
	}
}

func TestСловарьДоводовПриложенияЗеркаленСерверному(t *testing.T) {
	// Порядок здесь задан сервером — порядком доводов в Decide, от
	// сильного к слабому. Он же записан в приложении, и сверяется он
	// затем, чтобы читающий один файл видел тот же порядок, что и
	// читающий другой.
	want := []string{ByPurchase, ByGroup, ByLine}
	shown := объявленныеВПриложении(t, "OpenedBy")
	if len(shown) != len(want) {
		t.Fatalf("на сервере %d доводов, в приложении %d: %v против %v",
			len(want), len(shown), want, shown)
	}
	for i, one := range want {
		if shown[i] != one {
			t.Errorf("довод %d: на сервере %q, в приложении %q",
				i, one, shown[i])
		}
	}
}

// объявленныеВПриложении — значения словаря из тела названного класса.
//
// Читаются именно объявленные значения, а не список `all`: список — это
// второе место, и сверять надо оба. Поэтому список тут же проверяется на
// совпадение с объявленным по числу имён: пропущенное в нём имя значит,
// что `known` не узнает исправное значение и молча отбросит его.
func объявленныеВПриложении(t *testing.T, class string) []string {
	t.Helper()

	raw, err := os.ReadFile(appShelfFile)
	if err != nil {
		t.Fatalf("не прочитать исходник приложения %s: %v "+
			"(сверка обязана отказывать, а не пропускать)", appShelfFile, err)
	}
	text := string(raw)

	from := indexAfter(text, "abstract final class "+class+" {")
	if from < 0 {
		t.Fatalf("в %s не нашлось класса %s: сверка сломана, "+
			"а не словарь пуст", appShelfFile, class)
	}
	body := text[from:]
	if end := indexAfter(body, "\n}"); end >= 0 {
		body = body[:end]
	}

	found := appLineConst.FindAllStringSubmatch(body, -1)
	out := make([]string, 0, len(found))
	for _, one := range found {
		out = append(out, one[2])
	}
	if len(out) == 0 {
		t.Fatalf("в классе %s не нашлось ни одного значения: "+
			"сверка сломана, а не словарь пуст", class)
	}

	list := appLineList.FindStringSubmatch(body)
	if list == nil {
		t.Fatalf("у класса %s нет списка all: по нему приложение узнаёт "+
			"исправное значение, и без него оно отбросит все", class)
	}
	if named := len(regexp.MustCompile(`\w+`).FindAllString(list[1], -1)); named != len(out) {
		t.Errorf("у класса %s объявлено %d значений, а в списке all их %d: "+
			"пропущенное в списке значение приложение молча отбросит",
			class, len(out), named)
	}
	return out
}

func indexAfter(text, mark string) int {
	at := -1
	for i := 0; i+len(mark) <= len(text); i++ {
		if text[i:i+len(mark)] == mark {
			at = i + len(mark)
			break
		}
	}
	return at
}
