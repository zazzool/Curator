import "testing"

func TestОткрытостьНабораРешаетсяЛинейкойИПравами(t *testing.T) {
	// Таблицей, а не десятком проверок: важен не каждый случай сам по
	// себе, а то, что их ровно столько и что ни один не открыт по
	// недосмотру.
	for _, случай := range []struct {
		имя    string
		line   string
		rights Rights
		открыт bool
	}{
		{"гостевой открыт никому не известному", LineGuest, Rights{}, true},
		{"спонсорский открыт никому не известному", LineSponsored, Rights{}, true},
		{"базовый закрыт не назвавшемуся", LineBasic, Rights{}, false},
		{"базовый открыт привязавшему почту", LineBasic, Rights{EmailBound: true}, true},
		{"платный закрыт привязавшему почту", LinePaid, Rights{EmailBound: true}, false},
		{"платный открыт подписчику", LinePaid, Rights{Subscribed: true}, true},
		{"платный открыт купившему", LinePaid, Rights{Owns: true}, true},
		// Купленное сильнее линейки: отобрать оплаченное сменой линейки
		// значило бы отобрать его молча.
		{"купленное переживает смену линейки", LinePaid, Rights{Owns: true}, true},
		// Непонятое не применяется. Линейка с опечаткой — это не «какая-то
		// линейка», а неизвестно что, и открывать по ней нельзя.
		{"незнакомая линейка закрыта", "besplatno", Rights{Subscribed: true}, false},
		{"пустая линейка закрыта", "", Rights{EmailBound: true}, false},

		// Группы. Они расширяют линейку, а не встают рядом с ней: тот же
		// OpenTo, те же четыре линейки, два новых довода между купленным
		// и линейкой.
		{"группа открывает платный", LinePaid, Rights{Granted: true}, true},
		{"группа открывает базовый без почты", LineBasic, Rights{Granted: true}, true},
		{"группа скрывает гостевой", LineGuest, Rights{Hidden: true}, false},
		{"группа скрывает спонсорский", LineSponsored, Rights{Hidden: true}, false},
		// Пересечение групп неизбежно, и при споре выигрывает скрывающая:
		// закрытое по ошибке врач заметит и скажет, открытое по ошибке не
		// заметит никто.
		{"скрытие сильнее открытия", LineGuest, Rights{Granted: true, Hidden: true}, false},
		// Но не сильнее купленного: отобрать оплаченное правкой правила
		// значило бы отобрать деньги молча.
		{"купленное переживает скрытие", LinePaid, Rights{Owns: true, Hidden: true}, true},
		// Группы ничего не отбирают у того, кому и так открыто: врач без
		// групп видит ровно то, что видел до них.
		{"без групп линейка решает как прежде", LineBasic, Rights{EmailBound: true}, true},
	} {
		if got := OpenTo(случай.line, случай.rights); got != случай.открыт {
			t.Errorf("%s: OpenTo(%q, %+v) = %v", случай.имя, случай.line, случай.rights, got)
		}
	}
}

func TestДоводОткрытостиСчитаетсяТемЖеПереборомЧтоИОна(t *testing.T) {
	// Врачу говорится не только «открыт», но и «чем»: открытое группой не
	// навсегда, а купленное навсегда, и молчащая об этом витрина однажды
	// покажет пропажу набора без причины.
	//
	// Опасность здесь ровно одна: «чем» разойдётся с «открыт ли».
	// Разойдётся молча — витрина при любом доводе выглядит исправной, и
	// заметит расхождение только врач, которому нечего будет ответить.
	// Поэтому проверяется не довод сам по себе, а то, что Decide и OpenTo
	// отвечают согласно на каждом случае, и что у закрытого довод пуст.
	for _, случай := range []struct {
		имя    string
		line   string
		rights Rights
		by     string
	}{
		{"купивший — покупкой", LinePaid, Rights{Owns: true}, ByPurchase},
		{"купивший при скрытии — всё равно покупкой",
			LinePaid, Rights{Owns: true, Hidden: true}, ByPurchase},
		{"открытый группе — группой", LinePaid, Rights{Granted: true}, ByGroup},
		// Довод называет то, на чём перебор остановился, а не всё
		// подходящее сразу: купивший, попавший заодно в группу, остаётся
		// купившим — иначе витрина сказала бы ему, что доступ временный.
		{"купивший и в группе — покупкой",
			LinePaid, Rights{Owns: true, Granted: true}, ByPurchase},
		{"гостевой — линейкой", LineGuest, Rights{}, ByLine},
		{"спонсорский — линейкой", LineSponsored, Rights{}, ByLine},
		{"базовый с почтой — линейкой", LineBasic, Rights{EmailBound: true}, ByLine},
		{"платный с подпиской — линейкой", LinePaid, Rights{Subscribed: true}, ByLine},
		// У закрытого довода нет: сказать «открыт линейкой» про закрытый
		// значит соврать, а промолчать — оставить витрине только линейку,
		// по которой она и объясняет, что делать.
		{"базовый без почты — ничем", LineBasic, Rights{}, ""},
		{"платный без прав — ничем", LinePaid, Rights{}, ""},
		{"скрытый — ничем", LineGuest, Rights{Hidden: true}, ""},
		{"незнакомая линейка — ничем", "besplatno", Rights{}, ""},
	} {
		verdict := Decide(случай.line, случай.rights)
		if verdict.By != случай.by {
			t.Errorf("%s: Decide(%q, %+v).By = %q, ждали %q",
				случай.имя, случай.line, случай.rights, verdict.By, случай.by)
		}
		if verdict.Open != OpenTo(случай.line, случай.rights) {
			t.Errorf("%s: Decide говорит open=%v, а OpenTo — %v: "+
				"перебор разошёлся сам с собой",
				случай.имя, verdict.Open, OpenTo(случай.line, случай.rights))
		}
		if verdict.Open == (verdict.By == "") {
			t.Errorf("%s: open=%v при доводе %q — открытый обязан назвать "+
				"довод, закрытый обязан промолчать",
				случай.имя, verdict.Open, verdict.By)
		}
	}
}

func TestПереченьЛинеекЗакрыт(t *testing.T) {
	// Линейка, добавленная «для гибкости», не значит ничего ни для
	// OpenTo, ни для витрины: она просто закрыта. Перечень и проверка
	// линейки ходят парой, и разойдись они — студия предложила бы завести
	// набор, который никому не откроется.
	for _, line := range Lines {
		if !KnownLine(line) {
			t.Errorf("линейка %q есть в перечне и не признана известной", line)
		}
		if !OpenTo(line, Rights{Owns: true, Subscribed: true, EmailBound: true}) {
			t.Errorf("линейка %q не открывается никакими правами вообще", line)
		}
	}
	if KnownLine("guest ") {
		t.Error("линейка с пробелом признана известной")
	}
}
