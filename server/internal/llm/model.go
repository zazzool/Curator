// Дверь к моделям: единственное место, через которое проект обращается к
// LLM.
//
// Перенесено из MVExams (chatprovider.go, providers.go) вместе с доводами:
// каждый из них куплен отказом на бою, и стирать их при переносе нельзя.
// Что не перенесено и почему — сказано там, где след остался: поток ответа
// и управление размышлением приедут вместе с теми, кто их спрашивает, а
// квоты организаций не приедут никогда — организаций в Кураторе нет.
//
// Пакет не знает ни про базу, ни про источники, ни про задачи: ему
// передают готовое задание и получают текст. Это не аккуратность, а
// граница — дверь, которая знала бы содержимое задач, перестала бы быть
// дверью и стала бы вторым местом, где живёт предметная область.
package llm

import "encoding/json"

// Kind — диалект провайдера.
//
// Их два. Perplexity, OpenAI, OpenRouter и большинство остальных говорят
// на chat/completions; Anthropic — на своём messages. Всё остальное —
// адрес, ключ, модель и канал — задаётся настройкой, поэтому добавление
// провайдера не требует нового кода.
type Kind string

const (
	KindOpenAI    Kind = "openai"
	KindAnthropic Kind = "anthropic"
)

// ProviderConfig — один провайдер в списке.
type ProviderConfig struct {
	ID      string `json:"id"`
	Name    string `json:"name"`
	Kind    Kind   `json:"kind"`
	BaseURL string `json:"baseUrl"`
	Model   string `json:"model"`
	Enabled bool   `json:"enabled"`

	// APIKey наружу не отдаётся: в ответ уезжает только признак «ключ
	// задан» и его огрызок. Поле с ключом, отданное «на всякий случай»,
	// однажды уедет в ответ вместе с остальными.
	APIKey string `json:"apiKey,omitempty"`

	// ProxyURL — через какой канал ходить. Пусто — напрямую: прокси нужен
	// не всем провайдерам одинаково.
	ProxyURL string `json:"-"`
}

// Prompt — задание с уже подставленными переменными, готовое к отправке.
type Prompt struct {
	System string
	User   string

	// MaxTokens — потолок ответа. Ноль означает «обычный».
	//
	// Снаружи не принимается намеренно: потолок, приехавший из браузера,
	// стал бы способом заказать ответ любой длины — то есть счёт любого
	// размера.
	MaxTokens int

	// Temperature — жар выборки. Ноль означает «обычный».
	//
	// Одного значения на все виды работы мало: вычитке и слепой сверке
	// нужна повторяемость (один и тот же текст даёт один и тот же
	// вердикт), а пересказу фразы — наоборот, разброс.
	Temperature float64

	// Schema — JSON-схема ответа, SchemaName — её имя в запросе. Пусто —
	// формат просят одним текстом задания.
	//
	// Схема нужна прежде всего подсобным заданиям на дешёвых моделях:
	// именно мелкие модели чаще всего ломают формат, а ответ с битым JSON
	// оплачен полностью и не даёт ничего.
	Schema     json.RawMessage
	SchemaName string
}

// defaultTemperature — умолчание: низкое, потому что нужна достоверность,
// а не разнообразие формулировок. Разнообразие вариантов задачи берётся не
// отсюда — модель пишет их одним ответом и различает сама.
const defaultTemperature = 0.4

func (p Prompt) temperature() float64 {
	if p.Temperature > 0 {
		return p.Temperature
	}
	return defaultTemperature
}

// defaultMaxTokens — сколько хватает на одну задачу.
//
// Число взято у донора по замеру его журнала: при потолке в 8000 девять
// процентов генераций упирались в него при среднем ответе в три тысячи
// токенов. Потолок в десять тысяч покрывает честный верхний хвост с
// запасом, а зациклившуюся модель всё равно остановит. Сам по себе потолок
// денег не стоит — платят за написанное; обрыв же стоит всего.
const defaultMaxTokens = 10000

func (p Prompt) tokenBudget() int {
	if p.MaxTokens > 0 {
		return p.MaxTokens
	}
	return defaultMaxTokens
}

// Usage — во что обошлось одно обращение.
type Usage struct {
	PromptTokens     int
	CompletionTokens int

	// CachedTokens — сколько входных токенов пришло из префиксного кэша,
	// CacheWriteTokens — сколько в него записано. Ради этих двух чисел и
	// проставляется пометка кэша: экономию иначе видно только по итоговой
	// цене, то есть никак.
	CachedTokens     int
	CacheWriteTokens int

	// CostUSD — цена, названная провайдером. CostExact отличает её от
	// посчитанной по прайсу: точная учитывает скидку кэша и наценку шлюза,
	// расчётная — ничего из этого, и складывать их в одну колонку без
	// пометки нельзя.
	CostUSD   float64
	CostExact bool
}

// ModelInfo — модель в списке провайдера.
type ModelInfo struct {
	ID   string `json:"id"`
	Name string `json:"name"`
}
