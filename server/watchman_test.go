// Проверки самого сторожа.
//
// Сторож — единственное мерило зелёного в этом проекте, и проверять его
// больше нечем: сломанный сторож не падает, он проходит. Поэтому то, ради
// чего он заведён, записано ещё и здесь — и здесь оно ломается вслух.
//
// Проверки эти не про базу и потому не зовутся TestPg: они читают файлы и
// идут всегда, в том числе там, где базы нет.

func TestСторожИщетГонки(t *testing.T) {
	// Гонки здесь есть по устройству: сторож входа под общим замком, ведро
	// жетонов под общим замком, фоновая петля сведения, исполнитель
	// очереди, съёмка снимков. Гонка, не пойманная набором, ловится на бою
	// раз в месяц и не воспроизводится.
	checks := читай(t, "../tools/checks.sh")
	if !regexp.MustCompile(`go test[^\n]*-race`).MatchString(checks) {
		t.Error("набор гоняет проверки без -race")
	}
}

func TestСторожИщетИзвестныеУязвимости(t *testing.T) {
	// Репозиторий публичный: о дыре в зависимости узнаёт сперва тот, кто
	// её ищет.
	checks := читай(t, "../tools/checks.sh")
	if !strings.Contains(checks, "govulncheck") {
		t.Fatal("набор не ищет известных уязвимостей")
	}
	// Версия набора названа поимённо: @latest тянет на каждый прогон
	// другой инструмент, и красный сторож оказывается не про наш код.
	if !regexp.MustCompile(`govulncheck@v\d+\.\d+\.\d+`).MatchString(checks) {
		t.Error("версия govulncheck не пришпилена: сторож зависит от чужого вчерашнего дня")
	}
}

func TestСторожСобираетСтудию(t *testing.T) {
	// Разбор типов и проверки идут по исходникам, а сборка — это ещё и
	// разрешение путей сборщиком: упасть она может на том, чего не видят
	// ни первый, ни второй, и упасть ей негде, кроме выкатки.
	checks := читай(t, "../tools/checks.sh")
	if !regexp.MustCompile(`npm run [^\n]*build`).MatchString(checks) {
		t.Error("набор не собирает студию: сборка впервые случается на выкатке")
	}
}

func TestСторожРазбираетДоступностьСтудии(t *testing.T) {
	// Разбор типов доступности не видит: `<div onClick=…>` для него
	// безупречен, а для читающего с экрана это не кнопка вовсе — её нет
	// ни в обходе по клавише, ни в списке действий.
	checks := читай(t, "../tools/checks.sh")
	if !strings.Contains(checks, "npm run --silent lint") {
		t.Fatal("набор не разбирает стиль студии")
	}
	config := читай(t, "../web/eslint.config.js")
	if !strings.Contains(config, "jsx-a11y") {
		t.Error("в разборе студии нет правил доступности: половина находок аудита ловится ими")
	}
	if !strings.Contains(config, "react-hooks/exhaustive-deps") {
		t.Error("не проверяются зависимости крючков: чтение без них уводит экран в вечный круг запросов")
	}
}

func TestУСторожаНазваныПраваИСрок(t *testing.T) {
	workflow := читай(t, "../.github/workflows/checks.yml")

	// Проверки не пишут ни строки — ни метки, ни отзыва, ни выпуска.
	// Права по умолчанию настраиваются на уровне репозитория и бывают
	// шире нужного, а лишнее право нужно ровно затем, чтобы однажды им
	// воспользовался не тот, кто его просил.
	if !regexp.MustCompile(`(?m)^permissions:\s*\n\s+contents:\s*read`).MatchString(workflow) {
		t.Error("у сторожа не названы права: достаются те, что настроены у репозитория")
	}

	// Висящий прогон занимает исполнителя и держит очередь до шести часов
	// умолчания, а весь набор идёт минут десять.
	if !regexp.MustCompile(`(?m)^\s+timeout-minutes:\s*\d+`).MatchString(workflow) {
		t.Error("у работы сторожа нет срока: зависший прогон держит очередь часами")
	}
}

func TestНаборFlutterСверяетсяПоОтпечатку(t *testing.T) {
	// Полтора гигабайта, приезжающие по сети на каждый прогон и
	// распаковываемые в тот же образ, где идут проверки. Без сверки
	// подменённый архив — это чужой код, исполненный сторожем.
	workflow := читай(t, "../.github/workflows/checks.yml")

	m := regexp.MustCompile(`FLUTTER_SHA256=([0-9a-f]+)`).FindStringSubmatch(workflow)
	if m == nil {
		t.Fatal("отпечаток набора Flutter не записан: сторож ставит что приехало")
	}
	if len(m[1]) != 64 {
		t.Errorf("отпечаток длиной %d знаков вместо 64", len(m[1]))
	}
	// Записать отпечаток и не сверить с ним — то же самое, что не
	// записывать; выглядит при этом как заведённая защита.
	if !strings.Contains(workflow, "sha256sum -c") {
		t.Error("отпечаток записан, но архив с ним не сверяется")
	}
	// Отпечаток и версия обязаны меняться парой, и увидеть это можно
	// только рядом: обе строки стоят в одном шаге.
	if !regexp.MustCompile(`FLUTTER_VERSION=[\d.]+\n(?s).{0,600}?FLUTTER_SHA256=`).MatchString(workflow) {
		t.Error("версия и отпечаток стоят далеко друг от друга: менять их парой никто не вспомнит")
	}
}
